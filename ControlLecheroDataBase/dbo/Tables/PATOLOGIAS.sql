CREATE TABLE [dbo].[PATOLOGIAS] (
    [ESTABLO]            CHAR (7)      NULL,
    [RES]                CHAR (14)     NULL,
    [FPATOLOGIA]         SMALLDATETIME NULL,
    [TIPOPATOLOGIA]      CHAR (2)      NULL,
    [CONTROLADOR]        INT           NULL,
    [FRegistroPatologia] SMALLDATETIME NULL
