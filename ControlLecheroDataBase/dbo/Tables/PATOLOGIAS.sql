    ON [dbo].[PATOLOGIAS]([ESTABLO] ASC) WITH (FILLFACTOR = 90);


GO
CREATE NONCLUSTERED INDEX [IX_PATOLOGIAS_1]
    ON [dbo].[PATOLOGIAS]([RES] ASC) WITH (FILLFACTOR = 90);


GO
CREATE NONCLUSTERED INDEX [IX_PATOLOGIAS_2]
    ON [dbo].[PATOLOGIAS]([FPATOLOGIA] ASC) WITH (FILLFACTOR = 90);

