






CREATE PROCEDURE PR_ACTUALIZA_VACAS_DIB_MENOR_01868130
(@intCONTROLADOR INT)
--VACAS QUE SE ESTAN CONTROLANDO POR EL DIB Y TENDRIA QUE SER ESPH
	
AS
	
DECLARE @MAES_TIT CHAR(7),@MAES_GEN CHAR(14),@CONTROLADOR INT,@DIB CHAR(14)
DECLARE @TIT CHAR(7),@GEN CHAR(14),@NP INT,@NC INT,@FP SMALLDATETIME


--AHORA ACTUALIZO LOS VALORES DE TODAS LAS TABLAS

DECLARE C1 CURSOR  FOR
	SELECT ESTABLOACTUAL,NUMGEN,DIB 
	FROM NUMGEN_DIB_MENOR_01868130
	WHERE CONTROLADOR=@intCONTROLADOR
	
	OPEN C1
	FETCH NEXT FROM C1 INTO @MAES_TIT,@MAES_GEN,@DIB --GEN Y DIB
	
	WHILE ( @@FETCH_STATUS=0)
	BEGIN
		--ACTUALIZO MAESTRO
			UPDATE MAESTRO
			SET MAES_GEN=@MAES_GEN
			WHERE MAES_GEN=@DIB
		--ACTUALIZO CONTROL
			UPDATE CONTROL
			SET RES_GEN=@MAES_GEN	
			WHERE RES_GEN=@DIB
		--ACTUALIZO INSEMINACIONES
			UPDATE INSEMINACIONES
			SET ID=@MAES_GEN	
			WHERE ID=@DIB
		--ACTUALIZO PARTOS
			UPDATE PARTOS
			SET ID=@MAES_GEN	
			WHERE ID=@DIB
		--ACTUALIZO CELOS
			UPDATE CELOS
			SET VACA=@MAES_GEN	
			WHERE VACA=@DIB
		--ACTUALIZO INCIDENCIAS GENERALES
			UPDATE INCIDENCIASGENERALES
			SET RES=@MAES_GEN	
			WHERE RES=@DIB

		FETCH NEXT FROM C1 INTO @MAES_TIT,@MAES_GEN,@DIB --GEN Y DIB
	END


CLOSE C1
DEALLOCATE C1