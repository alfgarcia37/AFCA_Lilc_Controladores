


CREATE PROCEDURE PR_Check_VACAS_MAYOR_01868130
--MIRO LOS CROTALES QUE SE ESTAN CONTROLANDO POR ESPH Y TENDRIA QUE SER EL DIB
	
AS
	
DECLARE @MAES_TIT CHAR(7),@MAES_GEN CHAR(14),@CONTROLADOR INT,@DIB AS CHAR(14)
DECLARE @TIT CHAR(7),@GEN CHAR(14),@NP INT,@NC INT,@FP SMALLDATETIME

DELETE FROM NUMGEN_MAYOR_01868130

	DECLARE C1 CURSOR  FOR
	SELECT MAES_TIT,MAES_GEN,NUMCONTROLER 
	FROM MAESTRO,LECTURASCONTROL
	WHERE MAES_TIT=ESTABLO
	AND LEFT(MAES_GEN,4)='ESPH'
	AND RIGHT(MAES_GEN,8)>'01868130'
	--AND MAES_FP>'01/01/06'
	--AND NUMCONTROLER=98
	OPEN C1
	FETCH NEXT FROM C1 INTO @MAES_TIT,@MAES_GEN,@CONTROLADOR
	
	WHILE ( @@FETCH_STATUS=0)
	BEGIN
		--RECUPERO EL DIB DE REGISTRO
		DECLARE C2 CURSOR  FOR
		SELECT  CODIGOIdentif 
		FROM RegGen..ANIMALES
		WHERE (PAIS+SEXO+PROANI+NUMERO) =@MAES_GEN
		
		OPEN C2
		FETCH NEXT FROM C2 INTO @DIB
		IF @@FETCH_STATUS=0
		BEGIN
		INSERT INTO NUMGEN_MAYOR_01868130
		VALUES (@MAES_TIT,@MAES_GEN,@DIB,@CONTROLADOR)

		END
		CLOSE C2
		DEALLOCATE C2
		FETCH NEXT FROM C1 INTO @MAES_TIT,@MAES_GEN,@CONTROLADOR		
	END --DEL WHILE

CLOSE C1
DEALLOCATE C1


