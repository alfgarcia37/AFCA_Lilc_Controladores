




CREATE PROCEDURE [dbo].[PR_CHECK_DATOS_FALTANTES_CONTROL] 
(@strESTABLO CHAR(7))
AS

DECLARE @wID CHAR(14), @wNP INT, @wNC INT, @wFP SMALLDATETIME, @RES_FPREV SMALLDATETIME
DECLARE @RES_TIT CHAR(7),@RES_GEN CHAR(14),@RES_FP SMALLDATETIME,@RES_NP INT,@RES_NC INT
DECLARE @RES_KLAM REAL,@RES_KLPM REAL,@RES_TGR REAL,@RES_TPR REAL --VALORES ACTUALES ...CUALQUIERA DE LOS 3 PUEDE SER 0
DECLARE @RES_KLAM1 REAL,@RES_KLAM2  REAL,@RES_KLPM1 REAL,@RES_KLPM2 REAL,@RES_TGR1 REAL,@RES_TPR1 REAL,@RES_TGR2 REAL,@RES_TPR2 REAL,@RES_FCTR SMALLDATETIME

DECLARE @COD_INCIDENCIA_KILOS CHAR (1),@COD_INCIDENCIA_GRASA CHAR(1),@COD_INCIDENCIA_PROT CHAR(1)
SET @COD_INCIDENCIA_KILOS='0';SET @COD_INCIDENCIA_GRASA='0';SET @COD_INCIDENCIA_PROT='0'
SET @strESTABLO='J390029'


--==================================================================
--   SELECCIONO LOS QUE TIENE LA PRODUCCION A 0 Y HAN SIDO SECADOS
--======================================================================
DECLARE C1 cursor for 
SELECT  RES_TIT,RES_GEN,RES_NP,RES_NC,RES_FPREV,RES_KLAM,RES_KLPM,RES_TGR,RES_TPR
FROM CONTROL
WHERE 
RES_TIT=@strESTABLO AND
RES_FP BETWEEN '01/01/2006' AND '31/12/2007' AND
RES_AB='A'
AND (RES_KLAM=0 OR RES_TGR=0 OR RES_TPR=0)
OPEN  C1 
FETCH NEXT FROM C1 INTO  @RES_TIT,@RES_GEN,@RES_NP,@RES_NC,@RES_FPREV,@RES_KLAM,@RES_KLPM,@RES_TGR,@RES_TPR

WHILE @@FETCH_STATUS=0
BEGIN
	DECLARE C4 CURSOR FOR
	SELECT RES_GEN FROM CONTROL 
	WHERE RES_GEN=@RES_GEN
	AND RES_NP=@RES_NP
	AND RES_AB='B'
	OPEN  C4 
	FETCH NEXT FROM C4 INTO  @wID
	IF  @@FETCH_STATUS=0  --HAY SECADO   -> ENTONCES PUEDO CALCULAR LOS FALTANTES
	BEGIN
	   IF @RES_NC=1  -- SI NC=1 YA SE QUE NO HAY ANTERIOR    ->  COJO EL SIGUIENTE
	     BEGIN
		DECLARE C3 CURSOR FOR --COJO EL POSTERIOR
 		SELECT TOP 1   RES_KLAM,RES_TGR,RES_TPR
		FROM CONTROL
 		WHERE RES_GEN=@RES_GEN
		AND RES_NP=@RES_NP
		AND RES_FPREV>@RES_FPREV
		ORDER BY RES_FPREV ASC
		OPEN C3
		FETCH NEXT FROM C3 INTO  @RES_KLAM2,@RES_TGR2,@RES_TPR2
		IF @@FETCH_STATUS=0 --SI HAY POSTERIOR ACTUALIZO
			BEGIN --SI NC=1 -> KILOS NO SE ACTUALIZA, SÓLO GRASA Y PROTEINA
			SET @RES_TGR2=(@RES_TGR2+@RES_TGR)/2; SET @RES_TPR2=(@RES_TPR2+@RES_TPR)/2 --MEDIA DEL ACTUAL Y EL SGTE.
			EXEC PR_CHK_FALTANTES_CONTROL @RES_GEN,@RES_NP,@RES_NC,@RES_KLAM,@RES_TGR,@RES_TPR,@RES_KLAM,@RES_TGR2,@RES_TPR2
			END--SI NO HAY POSTERIOR NO VALE LA PAENA HACER NADA (UNA LACTACION CON UN CONTROL NO VALE PA NA')
		CLOSE C3
		DEALLOCATE C3
	    END
       		ELSE
	    BEGIN --NC>1
  			DECLARE C2 CURSOR FOR --COJO EL ANTERIOR
 			SELECT TOP 1   RES_KLAM,RES_TGR,RES_TPR
	 		FROM CONTROL
 			WHERE RES_GEN=@RES_GEN
			AND RES_NP=@RES_NP
			AND RES_FPREV<@RES_FPREV
			ORDER BY RES_FPREV DESC
			OPEN C2
			FETCH NEXT FROM C2 INTO  @RES_KLAM1,@RES_TGR1,@RES_TPR1
	 		IF @@FETCH_STATUS=0 -- SI HAY ANTERIOR MIRO SI HAY POSTERIOR
			BEGIN
				DECLARE C3 CURSOR FOR --COJO EL POSTERIOR
 				SELECT TOP 1   RES_KLAM,RES_KGR,RES_TPR
		 		FROM CONTROL
 				WHERE RES_GEN=@RES_GEN
				AND RES_NP=@RES_NP
				AND RES_FPREV>@RES_FPREV
				ORDER BY RES_FPREV ASC
				OPEN C3
				
				FETCH NEXT FROM C3 INTO  @RES_KLAM2,@RES_TGR2,@RES_TPR2
				IF @@FETCH_STATUS=0 -- SI HAY  POSTERIOR.. -> HAGO MEDIA
					BEGIN
						SET @RES_KLAM1=(@RES_KLAM1 + @RES_KLAM2)/2; SET @RES_TGR1=(@RES_TGR1+@RES_TGR2)/2 ; SET @RES_TPR1=(@RES_TPR1+@RES_TPR2)/2
						EXEC PR_CHK_FALTANTES_UPDATE @RES_GEN,@RES_NP,@RES_NC,@RES_KLAM,@RES_TGR,@RES_TPR,@RES_KLAM1,@RES_TGR1,@RES_TPR1
					END
				ELSE
					BEGIN -- SI NO, COJO EL ANTERIOR
						EXEC PR_CHK_FALTANTES_UPDATE @RES_GEN,@RES_NP,@RES_NC,@RES_KLAM,@RES_TGR,@RES_TPR,@RES_KLAM1,@RES_TGR1,@RES_TPR1
					END
				
				CLOSE C3
				DEALLOCATE C3

			END --IF DEL SI HAY ANTERIOR MIRO SI HAY POSTERIOR
			CLOSE C2
			DEALLOCATE C2

	            END -- IF HAY SECADO   -> ENTONCES PUEDO CALCULAR LOS FALTANTES
	
    	END--DEL NC>1
		CLOSE C4
		DEALLOCATE C4

   FETCH NEXT FROM C1 INTO  @RES_TIT,@RES_GEN,@RES_NP,@RES_NC,@RES_FPREV,@RES_KLAM,@RES_KLPM,@RES_TGR,@RES_TPR
END --WHILE1

CLOSE C1
DEALLOCATE C1




