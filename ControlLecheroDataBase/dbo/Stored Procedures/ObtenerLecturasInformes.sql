









CREATE PROCEDURE ObtenerLecturasInformes
 AS
SELECT 'CAN' ESTABLO,'1','CANTABRIA' RAZONSOCIAL,'1' TAMANOESTABLO
UNION
SELECT ESTABLO,INFORME,RAZONSOCIAL,TAMANOESTABLO 
FROM LECTURASCONTROL,REGGEN..GANADERIAS_MAESTRO
WHERE
ESTABLO=CODGAN
AND FBAJA IS NULL
AND TAMANOESTABLO IS NOT NULL
AND
INFORME='1'
ORDER BY ESTABLO





