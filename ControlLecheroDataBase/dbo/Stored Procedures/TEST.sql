






CREATE PROCEDURE TEST AS


DECLARE @RES_GEN CHAR(14),@RES_NP INT

--==============================DEPURACION DE LACTACIONES EN DOS ESTABLOS======================
--COMO NORMA GENERAL, ASIGNO LA LACTACION AL ULTIMO ESTABLO EN QUE SE ENCUENTRA LA VACA
--================================================================================================

DECLARE C1 cursor for 
SELECT MAX(RES),MAX(NP)FROM LACTACIONES
GROUP BY RES,NP
HAVING COUNT(*)>1

OPEN  C1 
FETCH NEXT FROM C1 INTO @RES_GEN,@RES_NP

WHILE (@@FETCH_STATUS=0)
BEGIN
	DELETE FROM LACTACIONES
	WHERE RES=@RES_GEN AND NP=@RES_NP
	AND FSECADO IN (SELECT MIN(FSECADO) FROM LACTACIONES WHERE RES=@RES_GEN AND NP=@RES_NP)


	FETCH NEXT FROM C1 INTO @RES_GEN,@RES_NP
END
CLOSE C1
DEALLOCATE C1






