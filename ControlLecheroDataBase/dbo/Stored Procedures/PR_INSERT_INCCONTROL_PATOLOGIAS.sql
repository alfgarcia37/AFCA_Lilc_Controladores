CREATE PROCEDURE [dbo].[PR_INSERT_INCCONTROL_PATOLOGIAS]
	(@Desde smalldatetime,@Hasta smalldatetime,@EstabloControl char(7))
AS


DECLARE @ESTABLO CHAR(7),@RES CHAR(14),@CONTROLADOR INT,@FECHA SMALLDATETIME,@NUMERO INT,@FCONTROL SMALLDATETIME,@INC AS CHAR(2)

--set @Desde='01/01/2013'
--set @Hasta='01/09/2013'
IF  @EstabloControl='*'
BEGIN
	DECLARE C1 CURSOR FOR
	SELECT RES_TIT,RES_GEN,RES_INC,RES_FCTR,CONTROLADOR  FROM CONTROL
	WHERE  RES_FPREV BETWEEN @Desde AND @Hasta
	AND RES_INC<>'00' AND RES_INC<>''
END
ELSE
BEGIN
	DECLARE C1 CURSOR FOR
	SELECT RES_TIT,RES_GEN,RES_INC,RES_FCTR,CONTROLADOR  FROM CONTROL
	WHERE  RES_FPREV BETWEEN @Desde AND @Hasta
	AND res_tit=@EstabloControl
	AND RES_INC<>'00' AND RES_INC<>''
END

OPEN  C1 
FETCH NEXT FROM C1 INTO @ESTABLO,@RES,@INC,@FCONTROL,@CONTROLADOR
WHILE (@@FETCH_STATUS=0)
BEGIN
	--MIRO SI EXISTE EN PATOLOGIAS
	DECLARE C2 CURSOR FOR
	SELECT COUNT(*)  FROM PATOLOGIAS 
	WHERE  RES=@RES AND FPATOLOGIA=@FCONTROL AND TIPOPATOLOGIA=@INC
	OPEN  C2
	FETCH NEXT FROM C2 INTO @NUMERO
	IF @NUMERO=0 --NO ESTA EN PATOLOGIAS -> LA METO
	BEGIN --
		INSERT INTO PATOLOGIAS (RES,ESTABLO,FPATOLOGIA,TIPOPATOLOGIA,CONTROLADOR,FREGISTROPATOLOGIA) 
		VALUES (@RES,@ESTABLO,@FCONTROL,@INC,@CONTROLADOR,GETDATE()) 
	END
	ELSE
	BEGIN
		PRINT @RES +'-'+@INC
	END
	CLOSE C2
	DEALLOCATE C2
	FETCH NEXT FROM C1 INTO @ESTABLO,@RES,@INC,@FCONTROL,@CONTROLADOR
END
CLOSE C1
DEALLOCATE C1