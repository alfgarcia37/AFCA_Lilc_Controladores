CREATE PROCEDURE [dbo].[PR_REORDENA_INSEMINACION_PARTO]
(@ESTABLO char(7))
AS
-- DESPUES TENGO QUE VOLVER A RENUMERAR INSEMINACIONES
DECLARE @P_ID CHAR(14),@P_WID CHAR(14),@NINS INT,
@P_WNP INT,@P_NP INT,@FINS SMALLDATETIME,@P_FP SMALLDATETIME,@WFINS  SMALLDATETIME,@W_FINS SMALLDATETIME,@WESTABLO char(7)

IF @ESTABLO<>'*'
	BEGIN
		DECLARE C3 CURSOR FOR 
		SELECT ESTABLO FROM LECTURASCONTROL WHERE ESTABLO=@ESTABLO
		AND FBAJA IS NULL
		OPEN  C3
	END
ELSE
	BEGIN
		DECLARE C3 CURSOR FOR 
		SELECT ESTABLO FROM LECTURASCONTROL WHERE FBAJA IS NULL
		ORDER BY Establo
		OPEN  C3
	END
	

FETCH NEXT FROM C3 INTO @WESTABLO
WHILE (@@FETCH_STATUS=0)
BEGIN
		DECLARE C1 cursor LOCAL SCROLL OPTIMISTIC FOR
		SELECT ID,NP,FPARTO FROM PARTOS
		WHERE ESTABLO=@WESTABLO
		--AND ID='ES000603441696'
		ORDER BY ID,FPARTO
		OPEN C1 
		FETCH NEXT FROM C1 INTO @P_ID,@P_NP,@P_FP
		SET @P_WID=''; SET @P_WNP=@P_NP;SET @WFINS='01/01/2000'
		WHILE (@@FETCH_STATUS=0)
		   BEGIN
			--IF  @P_WID<>@P_ID 
			--BEGIN
			--	SET @P_WID=@P_ID
			--	SET @P_WNP=@P_NP
			--	SET @WFINS='01/01/2000'
			--END
				--UPDATE INSEMINACIONES
				--SET NP=@P_NP
				--WHERE ID=@P_WID
				--AND FINSEMINACION< @P_FP AND FINSEMINACION>@WFINS
				--AND DATEDIFF( MONTH,FINSEMINACION,@P_FP) BETWEEN 6 AND 18
				
				UPDATE INSEMINACIONES
				SET NP=@P_NP
				WHERE ID=@P_ID
				AND FINSEMINACION< @P_FP --AND FINSEMINACION>@WFINS
				AND DATEDIFF( MONTH,FINSEMINACION,@P_FP) BETWEEN 6 AND 18
				
				PRINT 'vACA: ' + @P_ID + '..  NP:' + CONVERT(CHAR, @P_NP) + '    FINS:' + CONVERT(CHAR,@P_FP)

			--COJO LA UTLIMA FECHA DE INSEMINACION PARA NO VOLVER A ACTUALIZAR
			DECLARE C2  CURSOR LOCAL SCROLL OPTIMISTIC FOR
			SELECT MAX(FINSEMINACION) FROM INSEMINACIONES
			WHERE ID=@P_WID
			AND NP=@P_WNP
			OPEN C2 
			FETCH NEXT FROM C2 INTO @WFINS
			
			IF (@@FETCH_STATUS=0)
			BEGIN
			  SET @WFINS='01/01/2000'
			END
			CLOSE C2;DEALLOCATE C2
			FETCH NEXT FROM C1 INTO @P_ID,@P_NP,@P_FP
		END
		
		CLOSE C1
		DEALLOCATE C1
			
	FETCH NEXT FROM C3 INTO @WESTABLO
END

CLOSE C3
DEALLOCATE C3