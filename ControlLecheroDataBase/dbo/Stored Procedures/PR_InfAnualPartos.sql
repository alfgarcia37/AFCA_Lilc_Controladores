






CREATE PROCEDURE  PR_InfAnualPartos 
 (@ESTABLO char(7),@DESDE SMALLDATETIME,@HASTA SMALLDATETIME)
AS

DECLARE @NUM_ESTABLOS INT,@TAMANOESTABLO CHAR(1)
DECLARE @NUM_VACAS REAL,@TOTAL_VACAS INT,@NUM_REGISTROS INT,@NUM_VACAS2 REAL,@NUM_VACAS3 REAL
DECLARE @NUM_PARTOS INT,@NUM_DIAS INT

IF @ESTABLO<>' '
BEGIN
	/*===================PARTOS EN ESTABLO=======================*/
		
	DECLARE C1 CURSOR FOR 
	SELECT COUNT(*)
	FROM PARTOS
	WHERE 
	FPARTO BETWEEN @DESDE AND @HASTA
	AND PARTOS.ESTABLO=@ESTABLO
		
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @NUM_PARTOS
	CLOSE C1
	DEALLOCATE C1
		
	/*.......EDAD AL PARTO ESTABLO...............................................................................................*/
	DECLARE C1 CURSOR FOR 
	SELECT SUM(DATEDIFF(DAY,MAESTRO.MAES_FN,PARTOS.FPARTO))/COUNT(*)
	FROM PARTOS,MAESTRO
	WHERE 
	FPARTO BETWEEN @DESDE AND @HASTA
	AND PARTOS.ESTABLO=@ESTABLO
	AND PARTOS.ID=MAES_GEN
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @NUM_DIAS
	CLOSE C1
	DEALLOCATE C1
			
	/*================================PORCENTAJE PARTOS ESTABLO - VACAS(>24) =======================*/
	
		 /*===================ANIMALES EN ESTABLO=======================*/
				
			DECLARE C2 cursor  FOR
			SELECT COUNT(DISTINCT (CASE WHEN NUMERO >'01868130'    THEN CODIGOIdentif 
			ELSE (PAIS+SEXO+PROANI+NUMERO) END))
			FROM MAESTRO,RegGen..ANIMALES
			WHERE
			GANPRO=MAES_TIT
			AND GANPRO=@ESTABLO
			AND NUMLAC=0 and AÑOBAJ=0
			AND  SEXO='H'
			AND DATEDIFF(month, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), getdate())>24
			
			OPEN C2
			FETCH NEXT FROM C2 INTO @NUM_VACAS2 /* ANIMALES ESTABLO*/
			CLOSE C2
			DEALLOCATE C2
		
			/*===================VACAS CONTROLADAS EN ESTABLO=======================*/
			DECLARE C1 CURSOR FOR 
			SELECT COUNT(*)
			FROM LECTURASFINALIZADAS
			WHERE 
			LECTURASFINALIZADAS.ESTABLO=@ESTABLO
			AND LECTURASFINALIZADAS.FPREVISTA BETWEEN @DESDE AND @HASTA
			OPEN  C1 
			FETCH NEXT FROM C1 INTO @NUM_ESTABLOS
			CLOSE C1
			DEALLOCATE C1
			
			DECLARE C2 cursor  FOR
			SELECT COUNT(*)
			FROM CONTROL
			WHERE 
			RES_TIT=@ESTABLO
			AND RES_FPREV BETWEEN @DESDE AND @HASTA
			AND RES_AB='A'
			
			OPEN C2
			FETCH NEXT FROM C2 INTO @NUM_VACAS3 /*ANIMALES CONTROLADOS*/
			CLOSE C2
			DEALLOCATE C2
		
SELECT @NUM_PARTOS AS NUMPARTOS,@NUM_DIAS AS NUMDIAS,(@NUM_PARTOS*100/@NUM_VACAS2) AS PORCENTAJEPARTOSVACAS,(@NUM_PARTOS*100/(@NUM_VACAS3/@NUM_ESTABLOS)) AS PORCENTAJEPARTOSVACASCONTROLADAS

END
ELSE
BEGIN
	/*===================PARTOS EN CANTABRIA=======================*/
	DECLARE C1 cursor for 
	SELECT COUNT(DISTINCT MAES_TIT) FROM MAESTRO,LECTURASCONTROL
	WHERE 
	FBAJA IS  NULL
	AND TAMANOESTABLO IS NOT NULL
	AND MAES_TIT=ESTABLO
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @NUM_ESTABLOS
	CLOSE C1
	DEALLOCATE C1
	
	DECLARE C1 CURSOR FOR 
	SELECT COUNT(*)
	FROM PARTOS,LECTURASCONTROL
	WHERE 
	FPARTO BETWEEN @DESDE AND @HASTA
	AND LECTURASCONTROL.FBAJA IS  NULL
	AND LECTURASCONTROL.ESTABLO=PARTOS.ESTABLO /*cojo solo los activos actualmente*/
	AND TAMANOESTABLO IS NOT NULL
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @NUM_PARTOS
	CLOSE C1
	DEALLOCATE C1
	
		UPDATE INFORMEANUAL SET VALOR=@NUM_PARTOS/@NUM_ESTABLOS
		WHERE GRUPO='CANTABRIA' 
		AND CONCEPTO='PROMEDIO NUMERO PARTOS'
	
	/*.......EDAD AL PARTO CANTABRIA...............................................................................................*/
	DECLARE C1 CURSOR FOR 
	SELECT SUM(DATEDIFF(DAY,MAESTRO.MAES_FN,PARTOS.FPARTO))/COUNT(*)
	FROM PARTOS,LECTURASCONTROL,MAESTRO
	WHERE 
	FPARTO BETWEEN @DESDE AND @HASTA
	AND LECTURASCONTROL.FBAJA IS  NULL
	AND LECTURASCONTROL.ESTABLO=PARTOS.ESTABLO /*cojo solo los activos actualmente*/
	AND TAMANOESTABLO IS NOT NULL
	AND PARTOS.ID=MAES_GEN
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @NUM_DIAS
	CLOSE C1
	DEALLOCATE C1
	
		UPDATE INFORMEANUAL SET VALOR=@NUM_DIAS
		WHERE GRUPO='CANTABRIA' 
		AND CONCEPTO='PROMEDIO EDAD AL PARTO'
	
	
	/*=====================PARTOS EN TRAMOS==================================================*/
	
	DECLARE C1 cursor for 
	SELECT TAMANOESTABLO,COUNT(DISTINCT MAES_TIT) FROM MAESTRO,LECTURASCONTROL
	WHERE 
	FBAJA IS  NULL
	AND TAMANOESTABLO IS NOT NULL
	AND MAES_TIT=ESTABLO
	GROUP BY TAMANOESTABLO
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	WHILE (@@FETCH_STATUS=0)
	BEGIN
		DECLARE C2 cursor  FOR
		SELECT COUNT(*)
		FROM PARTOS,LECTURASCONTROL
		WHERE 
		FPARTO BETWEEN @DESDE AND @HASTA
		AND LECTURASCONTROL.FBAJA IS  NULL
		AND LECTURASCONTROL.ESTABLO=PARTOS.ESTABLO /*cojo solo los activos actualmente*/
		AND TAMANOESTABLO IS NOT NULL
		AND TAMANOESTABLO=@TAMANOESTABLO
		OPEN C2
		FETCH NEXT FROM C2 INTO  @NUM_PARTOS
			UPDATE INFORMEANUAL SET VALOR=@NUM_PARTOS/@NUM_ESTABLOS
			WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
			AND CONCEPTO='PROMEDIO NUMERO PARTOS'
	
			CLOSE C2
			DEALLOCATE C2
		/*............................................................PROMEDIO EDAD AL PARTO..........................*/
		DECLARE C2  CURSOR FOR 
		SELECT SUM(DATEDIFF(DAY,MAESTRO.MAES_FN,PARTOS.FPARTO))/COUNT(*)
		FROM PARTOS,LECTURASCONTROL,MAESTRO
		WHERE 
		FPARTO BETWEEN @DESDE AND @HASTA
		AND LECTURASCONTROL.FBAJA IS  NULL
		AND LECTURASCONTROL.ESTABLO=PARTOS.ESTABLO /*cojo solo los activos actualmente*/
		AND TAMANOESTABLO IS NOT NULL
		AND PARTOS.ID=MAES_GEN
		AND TAMANOESTABLO=@TAMANOESTABLO
			
		OPEN C2
		FETCH NEXT FROM C2 INTO  @NUM_PARTOS
			UPDATE INFORMEANUAL SET VALOR=@NUM_PARTOS
			WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
			AND CONCEPTO='PROMEDIO EDAD AL PARTO'
			CLOSE C2
			DEALLOCATE C2
	
		FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	END
	CLOSE C1
	DEALLOCATE C1
	/*================================PORCENTAJE PARTOS - VACAS(>24) =======================*/
	/* CANTABRIA................................................*/
	
	DECLARE C2  CURSOR FOR 
		SELECT VALOR FROM INFORMEANUAL WHERE GRUPO='CANTABRIA' AND CONCEPTO='PROMEDIO NUMERO PARTOS'
		OPEN C2
		FETCH NEXT FROM C2 INTO  @NUM_PARTOS
		CLOSE C2
		DEALLOCATE C2
	DECLARE C2  CURSOR FOR 
		SELECT VALOR FROM INFORMEANUAL WHERE GRUPO='CANTABRIA' AND CONCEPTO='MED VACAS EN EL ESTABLO(>24)'
		OPEN C2
		FETCH NEXT FROM C2 INTO  @NUM_VACAS
		CLOSE C2
		DEALLOCATE C2
		
		UPDATE INFORMEANUAL SET VALOR=@NUM_PARTOS*100/@NUM_VACAS
		WHERE GRUPO='CANTABRIA' 
		AND CONCEPTO='PORCENTAJE PARTOS VACAS'
		
	
	DECLARE C2  CURSOR FOR 
		SELECT VALOR FROM INFORMEANUAL WHERE GRUPO='CANTABRIA' AND CONCEPTO='MED VACAS CONTROLADAS'
		OPEN C2
		FETCH NEXT FROM C2 INTO  @NUM_VACAS
		CLOSE C2
		DEALLOCATE C2
		
	
		UPDATE INFORMEANUAL SET VALOR=@NUM_PARTOS*100/@NUM_VACAS
		WHERE GRUPO='CANTABRIA'  
		AND CONCEPTO='PORCENTAJE PARTOS CONTROL'
	
	/* ..................................................TRAMOS..............................................*/
	
	DECLARE C1 cursor for 
	SELECT TAMANOESTABLO,COUNT(DISTINCT MAES_TIT) FROM MAESTRO,LECTURASCONTROL
	WHERE 
	FBAJA IS  NULL
	AND TAMANOESTABLO IS NOT NULL
	AND MAES_TIT=ESTABLO
	GROUP BY TAMANOESTABLO
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	WHILE (@@FETCH_STATUS=0)
	BEGIN
		DECLARE C2  CURSOR FOR 
		SELECT VALOR FROM INFORMEANUAL 
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='PROMEDIO NUMERO PARTOS'
		OPEN C2
		FETCH NEXT FROM C2 INTO  @NUM_PARTOS
		CLOSE C2
		DEALLOCATE C2
	
		DECLARE C2  CURSOR FOR 
		SELECT VALOR FROM INFORMEANUAL 
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='MED VACAS EN EL ESTABLO(>24)'
		OPEN C2
		FETCH NEXT FROM C2 INTO  @NUM_VACAS
		CLOSE C2
		DEALLOCATE C2
		
		UPDATE INFORMEANUAL SET VALOR=@NUM_PARTOS*100/@NUM_VACAS
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='PORCENTAJE PARTOS VACAS'
		
	
		DECLARE C2  CURSOR FOR 
		SELECT VALOR FROM INFORMEANUAL 
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='MED VACAS CONTROLADAS'
		OPEN C2
		FETCH NEXT FROM C2 INTO  @NUM_VACAS
		CLOSE C2
		DEALLOCATE C2
		
	
		UPDATE INFORMEANUAL SET VALOR=@NUM_PARTOS*100/@NUM_VACAS
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='PORCENTAJE PARTOS CONTROL'
		
	
		FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	END
	CLOSE C1
	DEALLOCATE C1
END






