create PROCEDURE [dbo].[PR_RIIA_PARTOS]
AS
DECLARE @Fecha_Referencia  smalldatetime

DELETE FROM RIIA_PARTOS

INSERT INTO RIIA_PARTOS (MADRE,HIJO,FNAC_HIJO)
SELECT MADRE,HIJO,FECHA_NACIMIENTO 
FROM V_SITRANC.RIIA.DBO.V_PARTOS
WHERE FECHA_NACIMIENTO>dateadd(year,-2,@Fecha_Referencia)

UPDATE RIIA_PARTOS
SET SEXO=an_co_sexo,
raza=an_co_raza
from V_SITRANC.RIIA.DBO.T_ANIMALES
where hijo COLLATE Modern_Spanish_CI_AS=an_id

