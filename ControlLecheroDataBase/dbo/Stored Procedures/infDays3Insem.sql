








CREATE PROCEDURE DBO.infDays3Insem 
(
	@Establo char(7)
		)
AS
delete from View_MaxPartos

Insert into View_MaxPartos(ID,NP,FPARTO) select max(id) as ID,max(NP) as NP,MAX(FPARTO)
from PARTOS where establo=@Establo
group by ID

select VIEW_MAXPARTOS.ID,VIEW_MAXPARTOS.NP as NP,FPARTO,FINSEMINACION
FROM VIEW_MAXPARTOS,INSEMINACIONES
WHERE VIEW_MAXPARTOS.ID=INSEMINACIONES.ID
AND INSEMINACIONES.NP=0
AND INSEMINACIONES.NINS>3
AND DATEDIFF(DAY,FPARTO,FINSEMINACION)<100
ORDER BY VIEW_MAXPARTOS.ID








