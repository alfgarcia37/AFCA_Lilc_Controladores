






CREATE PROCEDURE PR_InfAnualProduccion 
 (@ESTABLO char(7),@DESDE SMALLDATETIME,@HASTA SMALLDATETIME)
AS

DECLARE @NUM_ESTABLOS INT,@TAMANOESTABLO CHAR(1)
DECLARE @NUM_VACAS REAL,@TOTAL_VACAS REAL,@NUM_REGISTROS REAL,@NUM_LECTURAS REAL
DECLARE @NUM_KILOS REAL,@NUM_GRASA REAL,@NUM_PROTEINA REAL,@NUM_RCS REAL

DECLARE @WESTABLO CHAR(7),@RS_ESTABLO CHAR(7)

DECLARE @wTOTALKILOS REAL,@wTOTALGRASA REAL, @wTOTALPROT REAL,@wTOTALRCS REAL,@wDIASLac INT
DECLARE @wDIAS INT,@VALOR REAL
DECLARE @RES_AB CHAR(1),@RES_KL REAL,@RES_TGR REAL,@RES_TPR REAL,@FPREVISTA SMALLDATETIME,@wFecha SMALLDATETIME

IF @ESTABLO<>' '
BEGIN
/*===================PRODUCCION VACAS CONTROLADAS EN ESTABLO=======================*/
		
	DECLARE C1 cursor for 
	SELECT LECTURASFINALIZADAS.ESTABLO,LECTURASFINALIZADAS.FPREVISTA
	FROM LECTURASCONTROL,LECTURASFINALIZADAS
	WHERE 
	LECTURASCONTROL.ESTABLO=LECTURASFINALIZADAS.ESTABLO
	AND FBAJA IS NULL
	AND LECTURASFINALIZADAS.ESTABLO=@ESTABLO
	AND LECTURASFINALIZADAS.FPREVISTA BETWEEN @DESDE AND @HASTA
	ORDER BY LECTURASFINALIZADAS. ESTABLO,LECTURASFINALIZADAS.FPREVISTA
	OPEN  C1 
	FETCH NEXT FROM C1 INTO  @RS_ESTABLO,@FPREVISTA
	SET @WDIAS=30
	SET @wTOTALKILOS=0;SET @wTOTALGRASA=0;SET @wTOTALPROT=0;SET @TOTAL_VACAS=0;SET @NUM_LECTURAS=0;SET @TOTAL_VACAS=0;SET @wTOTALRCS=0
	WHILE (@@FETCH_STATUS=0) --WILE 1
		BEGIN
		SET @NUM_LECTURAS=@NUM_LECTURAS + 1
		DECLARE C2 cursor for 
		SELECT CASE WHEN SUM(RES_KLAM+RES_KLPM) IS NULL THEN 0 ELSE SUM(RES_KLAM+RES_KLPM) END,
			 CASE WHEN SUM(RES_TGR*(RES_KLAM+RES_KLPM)/100) IS NULL THEN 0 ELSE SUM(RES_TGR*(RES_KLAM+RES_KLPM)/100) END,
			 CASE WHEN SUM(RES_TPR*(RES_KLAM+RES_KLPM)/100) IS NULL THEN 0 ELSE SUM(RES_TPR*(RES_KLAM+RES_KLPM)/100) END,
			 CASE WHEN SUM(RES_TRC) IS NULL THEN 0 ELSE SUM(RES_TRC) END,
			COUNT(*)
		FROM CONTROL
		WHERE
		RES_TIT=@RS_ESTABLO 
		AND RES_FPrev=@FPREVISTA
		AND RES_AB='A'
			
		OPEN  C2 
		FETCH NEXT FROM C2 INTO  @RES_KL,@RES_TGR,@RES_TPR,@NUM_RCS,@NUM_VACAS
		SET @wTOTALKILOS=@wTOTALKILOS + @RES_KL*@WDIAS
		SET @wTOTALGRASA=@wTOTALGRASA + @RES_TGR*@WDIAS
		SET @wTOTALPROT=@wTOTALPROT + @RES_TPR*@WDIAS
		SET @wTOTALRCS=@wTOTALRCS + @NUM_RCS
		SET @TOTAL_VACAS=@TOTAL_VACAS + @NUM_VACAS
		SET @wFecha=@FPREVISTA
		SET @wESTABLO=@RS_ESTABLO
		CLOSE C2
		DEALLOCATE C2

		FETCH NEXT FROM C1 INTO  @RS_ESTABLO,@FPREVISTA
		IF @wESTABLO<>@RS_ESTABLO
		BEGIN
			SET @WDIAS=30
		END
		ELSE
		BEGIN
			SET @WDIAS=DATEDIFF(DAY,@wFecha,@FPREVISTA)
		END
	END
CLOSE C1
DEALLOCATE C1



		SELECT (@wTOTALKILOS) AS KILOSLECHE,(@wTOTALGRASA) AS KILOSGRASA,@wTOTALPROT AS KILOSPROTEINA, @wTOTALRCS/@TOTAL_VACAS AS RCS,
			(@wTOTALKILOS/DATEDIFF(DAY,@DESDE,@HASTA))/(@TOTAL_VACAS/@NUM_LECTURAS) AS KILOSLECHEDIARIO,
			(@wTOTALGRASA/DATEDIFF(DAY,@DESDE,@HASTA))/(@TOTAL_VACAS/@NUM_LECTURAS) AS KILOSGRASADIARIO,
			(@wTOTALPROT/DATEDIFF(DAY,@DESDE,@HASTA)) /(@TOTAL_VACAS/@NUM_LECTURAS) AS KILOSPROTEINADIARIO,
			(@wTOTALRCS/@TOTAL_VACAS) AS RCS
		
		
END
ELSE
BEGIN
	/*===================PRODUCCION VACAS CONTROLADAS EN CANTABRIA=======================*/
	DECLARE C1 CURSOR FOR 
	SELECT COUNT(DISTINCT MAES_TIT) FROM MAESTRO,LECTURASCONTROL
	WHERE FBAJA IS  NULL
	AND MAES_TIT=ESTABLO /*cojo solo los activos actualmente*/
	AND TAMANOESTABLO IS NOT NULL
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @NUM_ESTABLOS
	CLOSE C1
	DEALLOCATE C1
	
	DECLARE C1 cursor for 
	SELECT LECTURASFINALIZADAS.ESTABLO,LECTURASFINALIZADAS.FPREVISTA
	FROM LECTURASCONTROL,LECTURASFINALIZADAS
	WHERE 
	LECTURASCONTROL.ESTABLO=LECTURASFINALIZADAS.ESTABLO
	AND FBAJA IS NULL
	--AND LECTURASFINALIZADAS.ESTABLO='J390024'
	AND LECTURASFINALIZADAS.FPREVISTA BETWEEN @DESDE AND @HASTA
	ORDER BY LECTURASFINALIZADAS. ESTABLO,LECTURASFINALIZADAS.FPREVISTA
	OPEN  C1 
	FETCH NEXT FROM C1 INTO  @RS_ESTABLO,@FPREVISTA
	SET @WDIAS=30
	SET @wTOTALKILOS=0;SET @wTOTALGRASA=0;SET @wTOTALPROT=0;SET @TOTAL_VACAS=0;SET @wTOTALRCS=0
	WHILE (@@FETCH_STATUS=0) --WILE 1
		BEGIN
		DECLARE C2 cursor for 
		SELECT CASE WHEN SUM(RES_KLAM+RES_KLPM) IS NULL THEN 0 ELSE SUM(RES_KLAM+RES_KLPM) END,
			 CASE WHEN SUM(RES_TGR*(RES_KLAM+RES_KLPM)/100) IS NULL THEN 0 ELSE SUM(RES_TGR*(RES_KLAM+RES_KLPM)/100) END,
			 CASE WHEN SUM(RES_TPR*(RES_KLAM+RES_KLPM)/100) IS NULL THEN 0 ELSE SUM(RES_TPR*(RES_KLAM+RES_KLPM)/100) END,
			 CASE WHEN SUM(RES_TRC) IS NULL THEN 0 ELSE SUM(RES_TRC) END,
			COUNT(*)
		FROM CONTROL
		WHERE
		RES_TIT=@RS_ESTABLO 
		AND RES_FPrev=@FPREVISTA
		AND RES_AB='A'
			
		OPEN  C2 
		FETCH NEXT FROM C2 INTO  @RES_KL,@RES_TGR,@RES_TPR,@NUM_RCS,@NUM_VACAS
		SET @wTOTALKILOS=@wTOTALKILOS + @RES_KL*@WDIAS
		SET @wTOTALGRASA=@wTOTALGRASA + @RES_TGR*@WDIAS
		SET @wTOTALRCS=@wTOTALRCS + @NUM_RCS
		SET @wTOTALPROT=@wTOTALPROT + @RES_TPR*@WDIAS
		SET @TOTAL_VACAS=@TOTAL_VACAS + @NUM_VACAS
		SET @wFecha=@FPREVISTA
		SET @wESTABLO=@RS_ESTABLO
		CLOSE C2
		DEALLOCATE C2

		FETCH NEXT FROM C1 INTO  @RS_ESTABLO,@FPREVISTA
		IF @wESTABLO<>@RS_ESTABLO
		BEGIN
			SET @WDIAS=30
		END
		ELSE
		BEGIN
			SET @WDIAS=DATEDIFF(DAY,@wFecha,@FPREVISTA)
		END
	END
	CLOSE C1
	DEALLOCATE C1

		UPDATE INFORMEANUAL SET VALOR=@wTOTALKILOS/@NUM_ESTABLOS
		WHERE GRUPO='CANTABRIA' 
		AND CONCEPTO='KILOS LECHE'
	
		UPDATE INFORMEANUAL SET VALOR=@wTOTALGRASA/@NUM_ESTABLOS
		WHERE GRUPO='CANTABRIA' 
		AND CONCEPTO='KILOS GRASA'
	
		UPDATE INFORMEANUAL SET VALOR=@wTOTALPROT/@NUM_ESTABLOS
		WHERE GRUPO='CANTABRIA'
		AND CONCEPTO='KILOS PROTEINA'
	
		UPDATE INFORMEANUAL SET VALOR=@wTOTALRCS/@TOTAL_VACAS
		WHERE GRUPO='CANTABRIA'
		AND CONCEPTO='RCS'
		-- HALLO LA MEDIA DE VACAS EN ESTABLO EN ESE PERIODO

				DECLARE C1 CURSOR FOR 
				SELECT VALOR FROM INFORMEANUAL
				WHERE GRUPO='CANTABRIA' AND CONCEPTO='MED VACAS CONTROLADAS' 
				OPEN  C1 
				FETCH NEXT FROM C1 INTO @VALOR
				CLOSE C1
				DEALLOCATE C1

		UPDATE INFORMEANUAL SET VALOR=(@wTOTALKILOS/@NUM_ESTABLOS)/(DATEDIFF(DAY,@DESDE,@HASTA)*@VALOR)
		WHERE GRUPO='CANTABRIA' 
		AND CONCEPTO='KILOS LECHE DIARIO'
	
		UPDATE INFORMEANUAL SET VALOR=(@wTOTALGRASA/@NUM_ESTABLOS)/(DATEDIFF(DAY,@DESDE,@HASTA)*@VALOR)
		WHERE GRUPO='CANTABRIA' 
		AND CONCEPTO='KILOS GRASA DIARIO'
	
		UPDATE INFORMEANUAL SET VALOR=(@wTOTALPROT/@NUM_ESTABLOS)/(DATEDIFF(DAY,@DESDE,@HASTA)*@VALOR)
		WHERE GRUPO='CANTABRIA'
		AND CONCEPTO='KILOS PROTEINA DIARIO'
	
	/*========PRODUCCION VACAS CONTROLADAS EN TRAMOS================*/
	
	DECLARE C1 cursor for 
	SELECT TAMANOESTABLO,COUNT(DISTINCT MAES_TIT) FROM MAESTRO,LECTURASCONTROL
	WHERE 
	FBAJA IS  NULL
	AND TAMANOESTABLO IS NOT NULL
	AND MAES_TIT=ESTABLO
	GROUP BY TAMANOESTABLO
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	WHILE (@@FETCH_STATUS=0)
	BEGIN-------WHILE PRINCIPAL
			
		DECLARE C2 cursor for 
		SELECT LECTURASFINALIZADAS.ESTABLO,LECTURASFINALIZADAS.FPREVISTA
		FROM LECTURASCONTROL,LECTURASFINALIZADAS
		WHERE 
		LECTURASCONTROL.ESTABLO=LECTURASFINALIZADAS.ESTABLO
		AND FBAJA IS NULL
		--AND LECTURASFINALIZADAS.ESTABLO='J390024'
		AND LECTURASFINALIZADAS.FPREVISTA BETWEEN @DESDE AND @HASTA
		AND TAMANOESTABLO=@TAMANOESTABLO
		ORDER BY LECTURASFINALIZADAS. ESTABLO,LECTURASFINALIZADAS.FPREVISTA
		OPEN  C2 
		FETCH NEXT FROM C2 INTO  @RS_ESTABLO,@FPREVISTA

			SET @WDIAS=30
			SET @wTOTALKILOS=0;SET @wTOTALGRASA=0;SET @wTOTALPROT=0;SET @TOTAL_VACAS=0;SET @wTOTALRCS=0
			WHILE (@@FETCH_STATUS=0) --WILE LECTURAS
				BEGIN
				DECLARE C3 cursor for 
				SELECT CASE WHEN SUM(RES_KLAM+RES_KLPM) IS NULL THEN 0 ELSE SUM(RES_KLAM+RES_KLPM) END,
					 CASE WHEN SUM(RES_TGR*(RES_KLAM+RES_KLPM)/100) IS NULL THEN 0 ELSE SUM(RES_TGR*(RES_KLAM+RES_KLPM)/100) END,
					 CASE WHEN SUM(RES_TPR*(RES_KLAM+RES_KLPM)/100) IS NULL THEN 0 ELSE SUM(RES_TPR*(RES_KLAM+RES_KLPM)/100) END,
					 CASE WHEN SUM(RES_TRC) IS NULL THEN 0 ELSE SUM(RES_TRC) END,
					COUNT(*)
				FROM CONTROL
				WHERE
				RES_TIT=@RS_ESTABLO 
				AND RES_FPrev=@FPREVISTA
				AND RES_AB='A'
					
				OPEN  C3 
				FETCH NEXT FROM C3 INTO  @RES_KL,@RES_TGR,@RES_TPR,@NUM_RCS,@NUM_VACAS
				SET @wTOTALKILOS=@wTOTALKILOS + @RES_KL*@WDIAS
				SET @wTOTALGRASA=@wTOTALGRASA + @RES_TGR*@WDIAS				SET @wTOTALPROT=@wTOTALPROT + @RES_TPR*@WDIAS
				SET @wTOTALRCS=@wTOTALRCS + @NUM_RCS
				SET @TOTAL_VACAS=@TOTAL_VACAS + @NUM_VACAS
				SET @wFecha=@FPREVISTA
				SET @wESTABLO=@RS_ESTABLO
				CLOSE C3
				DEALLOCATE C3
		
				FETCH NEXT FROM C2 INTO  @RS_ESTABLO,@FPREVISTA
				IF @wESTABLO<>@RS_ESTABLO
				BEGIN
					SET @WDIAS=30
				END
				ELSE
				BEGIN
					SET @WDIAS=DATEDIFF(DAY,@wFecha,@FPREVISTA)
				END
			END------WHILE LECTURAS
			CLOSE C2
			DEALLOCATE C2	
			
			UPDATE INFORMEANUAL SET VALOR=@wTOTALKILOS/@NUM_ESTABLOS
			WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
			AND CONCEPTO='KILOS LECHE'
	
			UPDATE INFORMEANUAL SET VALOR=@wTOTALGRASA/@NUM_ESTABLOS
			WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
			AND CONCEPTO='KILOS GRASA'
	
			UPDATE INFORMEANUAL SET VALOR=@wTOTALPROT/@NUM_ESTABLOS
			WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
			AND CONCEPTO='KILOS PROTEINA'
	
			UPDATE INFORMEANUAL SET VALOR=@wTOTALRCS/@TOTAL_VACAS
			WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
			AND CONCEPTO='RCS'

				-- HALLO LA MEDIA DE VACAS EN ESTABLO EN ESE PERIODO

				DECLARE C3 CURSOR FOR 
				SELECT VALOR FROM INFORMEANUAL
				WHERE GRUPO='TRAMO'   + CAST(@TAMANOESTABLO as char(1))  
				AND CONCEPTO='MED VACAS CONTROLADAS' 
				OPEN  C3 
				FETCH NEXT FROM C3 INTO @VALOR
				CLOSE C3
				DEALLOCATE C3
			
			UPDATE INFORMEANUAL SET VALOR=(@wTOTALKILOS/@NUM_ESTABLOS)/(DATEDIFF(DAY,@DESDE,@HASTA)*@VALOR)
			WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
			AND CONCEPTO='KILOS LECHE DIARIO'
	
			UPDATE INFORMEANUAL SET VALOR=(@wTOTALGRASA/@NUM_ESTABLOS)/(DATEDIFF(DAY,@DESDE,@HASTA)*@VALOR)
			WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
			AND CONCEPTO='KILOS GRASA DIARIO'
	
			UPDATE INFORMEANUAL SET VALOR=(@wTOTALPROT/@NUM_ESTABLOS)/(DATEDIFF(DAY,@DESDE,@HASTA)*@VALOR)
			WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
			AND CONCEPTO='KILOS PROTEINA DIARIO'
	
			
		
		FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	END------WHILE PRINCIPAL
	CLOSE C1
	DEALLOCATE C1
END






