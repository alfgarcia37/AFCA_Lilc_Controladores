CREATE PROCEDURE [dbo].[PR_ConversionUEa14Digitos]
	@ID AS VARCHAR(14)
AS
BEGIN
	SET NOCOUNT ON;
DECLARE @PAIS AS CHAR(2)
SET @PAIS=SUBSTRING(@ID,1,2)

	--Formato de Crotales Estados Miembros
	UPDATE TMP_CENSORIIA
	SET VACA= 
	(Case 
		WHEN @PAIS IN('BG', 'SI', 'LT', 'LU') THEN @PAIS+'0000'+SUBSTRING(@ID,3,8) -- 8 POS
		WHEN @PAIS IN('AT', 'CZ', 'CY', 'SK', 'FI', 'NL', 'PT', 'BE') THEN @PAIS+'000'+SUBSTRING(@ID,3,9)--9 POS
		WHEN @PAIS IN('DE', 'EE', 'FR', 'HU', 'AD') THEN @PAIS+'00'+SUBSTRING(@ID,3,10)--10 POS
		WHEN @PAIS IN('DK', 'SE') THEN @PAIS+'0'+SUBSTRING(@ID,3,11)--11 POS
		
	 END
	 )
	WHERE VACA=@ID

END

