






CREATE PROCEDURE PR_InfAnualAbiertas
 (@ESTABLO char(7),
@DESDE SMALLDATETIME,@HASTA SMALLDATETIME ) 
AS

DECLARE @GEN CHAR(14),@NP  INT,@FPARTO SMALLDATETIME,@TOTALDIAS REAL,@FPARTO_ANTERIOR SMALLDATETIME,@NUM_VACAS REAL,@A INT
DECLARE @TAMANOESTABLO CHAR(1),@NUM_ESTABLOS REAL,@DIAS_OPEN AS REAL,@NINS AS INT,@FINS SMALLDATETIME
DECLARE @TOTALDIAS100 REAL,@TOTALDIAS100130 REAL,@TOTALDIAS130 REAL,@NUM_VACAS100 REAL,@NUM_VACAS100130 REAL,@NUM_VACAS130 REAL

IF @ESTABLO<>' '
BEGIN
	DECLARE C1 CURSOR FOR
	SELECT     ID,NP,NINS,FINS
	FROM         PARTOS
	WHERE     (FINS IS NOT NULL) 
	AND ESTABLO=@ESTABLO
	AND FPARTO>=@DESDE
	AND FPARTO<=@HASTA
	AND NP>1

	SET @TOTALDIAS=0;SET @NUM_VACAS=0;SET @TOTALDIAS100=0;SET @NUM_VACAS100=0;SET @TOTALDIAS100130=0;SET @NUM_VACAS100130=0
	SET @TOTALDIAS130=0;SET @NUM_VACAS130=0
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @GEN,@NP,@NINS,@FINS
	WHILE (@@FETCH_STATUS=0)
	  BEGIN
		
		DECLARE C2 CURSOR FOR
		SELECT DATEDIFF(DAY,FPARTO,@FINS)
		 FROM PARTOS
		WHERE 
		ID=@GEN
		AND  NP=@NP-1
		AND ESTABLO=@ESTABLO
		AND DATEDIFF(DAY,FPARTO,@FINS) <250
		
		OPEN  C2 
		FETCH NEXT FROM C2 INTO @DIAS_OPEN 
		IF @@FETCH_STATUS=0
		BEGIN
			SET @TOTALDIAS=@TOTALDIAS+@DIAS_OPEN
			SET @NUM_VACAS=@NUM_VACAS+1
		

			IF @DIAS_OPEN<100
			BEGIN
				SET @TOTALDIAS100=@TOTALDIAS100+@DIAS_OPEN
				SET @NUM_VACAS100=@NUM_VACAS100+1
			END
			IF @DIAS_OPEN>=100 AND @DIAS_OPEN<=130
			BEGIN
				SET @TOTALDIAS100130=@TOTALDIAS100130+@DIAS_OPEN
				SET @NUM_VACAS100130=@NUM_VACAS100130+1
			END
			IF @DIAS_OPEN>130
			BEGIN
				SET @TOTALDIAS130=@TOTALDIAS130+@DIAS_OPEN
				SET @NUM_VACAS130=@NUM_VACAS130+1
			END
		END		
		CLOSE C2
		DEALLOCATE C2
				
		FETCH NEXT FROM C1 INTO   @GEN,@NP,@NINS,@FINS
	 END
	
	CLOSE C1
	DEALLOCATE C1
	
	SELECT @NUM_VACAS AS NUMVACAS,@TOTALDIAS/@NUM_VACAS AS DIASABIERTOS,
		@NUM_VACAS100*100/@NUM_VACAS AS VACAS100,@TOTALDIAS100/@NUM_VACAS100 AS DIASABIERTOS100,
		@NUM_VACAS100130*100/@NUM_VACAS AS VACAS100130,@TOTALDIAS100130/@NUM_VACAS100130 AS DIASABIERTOS100130,
		@NUM_VACAS130*100/@NUM_VACAS AS VACAS130,@TOTALDIAS130/@NUM_VACAS130 AS DIASABIERTOS130
END

ELSE

BEGIN
	--====================CANTABRIA=================================
	-- NO DIVIDO ENTRE NUM_ESTABLOS PORQUE HAY MUY POCOS DATOS
	DECLARE C1 CURSOR FOR
	SELECT     ID,NP,NINS,FINS
	FROM       PARTOS,LECTURASCONTROL
	WHERE     (FINS IS NOT NULL) 
	AND FPARTO>=@DESDE
	AND FPARTO<=@HASTA
	AND NP>1
	AND LECTURASCONTROL.FBAJA IS  NULL
	AND LECTURASCONTROL.ESTABLO=PARTOS.ESTABLO /*cojo solo los activos actualmente*/
	AND TAMANOESTABLO IS NOT NULL
	AND NP>1


	SET @TOTALDIAS=0;SET @NUM_VACAS=0;SET @TOTALDIAS100=0;SET @NUM_VACAS100=0;SET @TOTALDIAS100130=0;SET @NUM_VACAS100130=0
	SET @TOTALDIAS130=0;SET @NUM_VACAS130=0
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @GEN,@NP,@NINS,@FINS
	WHILE (@@FETCH_STATUS=0)
	  BEGIN
		
		DECLARE C2 CURSOR FOR
		SELECT DATEDIFF(DAY,FPARTO,@FINS) FROM PARTOS
		WHERE 
		ID=@GEN
		AND  NP=@NP-1
		AND DATEDIFF(DAY,FPARTO,@FINS) <250
				
		OPEN  C2 
		FETCH NEXT FROM C2 INTO @DIAS_OPEN 
		IF @@FETCH_STATUS=0
		BEGIN
				SET @TOTALDIAS=@TOTALDIAS+@DIAS_OPEN
				SET @NUM_VACAS=@NUM_VACAS+1
			
			IF @DIAS_OPEN<100
			BEGIN
				SET @TOTALDIAS100=@TOTALDIAS100+@DIAS_OPEN
				SET @NUM_VACAS100=@NUM_VACAS100+1
			END
			IF @DIAS_OPEN>=100 AND @DIAS_OPEN<=130
			BEGIN
				SET @TOTALDIAS100130=@TOTALDIAS100130+@DIAS_OPEN
				SET @NUM_VACAS100130=@NUM_VACAS100130+1
			END
			IF @DIAS_OPEN>130
			BEGIN
				SET @TOTALDIAS130=@TOTALDIAS130+@DIAS_OPEN
				SET @NUM_VACAS130=@NUM_VACAS130+1
			END
		END--FETCH STATUS
			


		CLOSE C2
		DEALLOCATE C2
		
		FETCH NEXT FROM C1 INTO  @GEN,@NP,@NINS,@FINS
	 END
	
	CLOSE C1
	DEALLOCATE C1

		
		UPDATE INFORMEANUAL SET VALOR=@TOTALDIAS/@NUM_VACAS
		WHERE GRUPO='CANTABRIA' 
		AND CONCEPTO='PROMEDIO DIAS ABIERTOS'

		UPDATE INFORMEANUAL SET VALOR=@TOTALDIAS100/@NUM_VACAS100		WHERE GRUPO='CANTABRIA' 
		AND CONCEPTO='PROMEDIO VACAS ABIERTAS<100'

		UPDATE INFORMEANUAL SET VALOR=@NUM_VACAS100*100/@NUM_VACAS
		WHERE GRUPO='CANTABRIA' 
		AND CONCEPTO='PORCENTAJE VACAS ABIERTAS<100'

		UPDATE INFORMEANUAL SET VALOR=@TOTALDIAS100130/@NUM_VACAS100130
		WHERE GRUPO='CANTABRIA' 
		AND CONCEPTO='PROMEDIO VACAS ABIERTAS>100<130'

		UPDATE INFORMEANUAL SET VALOR=@NUM_VACAS100130*100/@NUM_VACAS
		WHERE GRUPO='CANTABRIA' 
		AND CONCEPTO='PORCENTAJE VACAS ABIERTAS>100<130'

		UPDATE INFORMEANUAL SET VALOR=@TOTALDIAS130/@NUM_VACAS130
		WHERE GRUPO='CANTABRIA' 
		AND CONCEPTO='PROMEDIO VACAS ABIERTAS>130'

		UPDATE INFORMEANUAL SET VALOR=@NUM_VACAS130*100/@NUM_VACAS
		WHERE GRUPO='CANTABRIA' 
		AND CONCEPTO='PORCENTAJE VACAS ABIERTAS>130'

/*========INTERVALO ENTRE PARTOS EN TRAMOS================*/
	
	DECLARE C1 cursor for 
	SELECT TAMANOESTABLO,COUNT(DISTINCT MAES_TIT) FROM MAESTRO,LECTURASCONTROL
	WHERE 
	FBAJA IS  NULL
	AND TAMANOESTABLO IS NOT NULL
	AND MAES_TIT=ESTABLO
	GROUP BY TAMANOESTABLO
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	WHILE (@@FETCH_STATUS=0)
	BEGIN
		DECLARE C2 cursor  FOR
		SELECT     ID,NP,NINS,FINS
		FROM       PARTOS,LECTURASCONTROL
		WHERE     (FINS IS NOT NULL) 
		AND FPARTO>=@DESDE
		AND FPARTO<=@HASTA
		AND NP>1
		AND LECTURASCONTROL.FBAJA IS  NULL
		AND LECTURASCONTROL.ESTABLO=PARTOS.ESTABLO /*cojo solo los activos actualmente*/
		AND TAMANOESTABLO IS NOT NULL
		AND TAMANOESTABLO=@TAMANOESTABLO
		

		SET @TOTALDIAS=0;SET @NUM_VACAS=0;SET @TOTALDIAS100=0;SET @NUM_VACAS100=0;SET @TOTALDIAS100130=0;SET @NUM_VACAS100130=0
		SET @TOTALDIAS130=0;SET @NUM_VACAS130=0
	
		OPEN  C2 
		FETCH NEXT FROM C2 INTO @GEN,@NP,@NINS,@FINS
		WHILE (@@FETCH_STATUS=0)
		  BEGIN
		
			DECLARE C3 CURSOR FOR
			SELECT DATEDIFF(DAY,FPARTO,@FINS) FROM PARTOS
			WHERE 
			ID=@GEN
			AND  NP=@NP-1
			AND DATEDIFF(DAY,FPARTO,@FINS) <250
					
			OPEN  C3 
			FETCH NEXT FROM C3 INTO @DIAS_OPEN 
			IF @@FETCH_STATUS=0
			BEGIN
				SET @TOTALDIAS=@TOTALDIAS+@DIAS_OPEN
				SET @NUM_VACAS=@NUM_VACAS+1
			
				

				IF @DIAS_OPEN<100
				BEGIN
					SET @TOTALDIAS100=@TOTALDIAS100+@DIAS_OPEN
					SET @NUM_VACAS100=@NUM_VACAS100+1
				END
				IF @DIAS_OPEN>=100 AND @DIAS_OPEN<=130
				BEGIN
					SET @TOTALDIAS100130=@TOTALDIAS100130+@DIAS_OPEN
					SET @NUM_VACAS100130=@NUM_VACAS100130+1
				END
				IF @DIAS_OPEN>130
				BEGIN
					SET @TOTALDIAS130=@TOTALDIAS130+@DIAS_OPEN
					SET @NUM_VACAS130=@NUM_VACAS130+1
				END
			END--FETCH STATUS

			CLOSE C3
			DEALLOCATE C3
			
			FETCH NEXT FROM C2 INTO  @GEN,@NP,@NINS,@FINS
		END--WHILE DE PARTOS
		CLOSE C2
		DEALLOCATE C2

		UPDATE INFORMEANUAL SET VALOR=@NUM_VACAS
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='NUMERO VACAS ABIERTAS'

		UPDATE INFORMEANUAL SET VALOR=@TOTALDIAS/@NUM_VACAS
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='PROMEDIO DIAS ABIERTOS'

		UPDATE INFORMEANUAL SET VALOR=@TOTALDIAS100/@NUM_VACAS100
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='PROMEDIO VACAS ABIERTAS<100'

		UPDATE INFORMEANUAL SET VALOR=@NUM_VACAS100*100/@NUM_VACAS
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='PORCENTAJE VACAS ABIERTAS<100'

		UPDATE INFORMEANUAL SET VALOR=@TOTALDIAS100130/@NUM_VACAS100130
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='PROMEDIO VACAS ABIERTAS>100<130'

		UPDATE INFORMEANUAL SET VALOR=@NUM_VACAS100130*100/@NUM_VACAS
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='PORCENTAJE VACAS ABIERTAS>100<130'

		UPDATE INFORMEANUAL SET VALOR=@TOTALDIAS130/@NUM_VACAS130
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='PROMEDIO VACAS ABIERTAS>130'

		UPDATE INFORMEANUAL SET VALOR=@NUM_VACAS130*100/@NUM_VACAS
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='PORCENTAJE VACAS ABIERTAS>130'

		FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	 END--WHILE DE TRAMOS
	
	CLOSE C1
	DEALLOCATE C1
	
	
		
			
	
END






