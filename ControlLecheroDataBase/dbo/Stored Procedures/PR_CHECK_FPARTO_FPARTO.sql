CREATE PROCEDURE PR_CHECK_FPARTO_FPARTO

	
(@datFPREV smalldatetime,@DIAS INT)

AS


DECLARE @RES_TIT CHAR(7),@RES_GEN CHAR(14),@RES_NP INT,@RES_NC INT,@RES_FP SMALLDATETIME,@RES_AB CHAR(2),@PARAM1 CHAR(4),@PARAM2 CHAR(4)
DECLARE @WRES_TIT CHAR(7),@WRES_GEN CHAR(14),@WRES_NP INT,@WRES_NC INT,@WRES_FP SMALLDATETIME,@WRES_AB CHAR(1),@RES_FBA SMALLDATETIME,@WRES_FBA  SMALLDATETIME

	DELETE  FROM CONTROLTXT


	DECLARE C1 CURSOR  FOR
	SELECT ID,FPARTO,NP
	FROM PARTOS
	WHERE FPARTO>@datFPREV
	OPEN C1
	FETCH NEXT FROM C1 INTO @RES_GEN,@RES_FP,@RES_NP
	

	WHILE ( @@FETCH_STATUS=0)
	BEGIN
		DECLARE C2 CURSOR  FOR
		SELECT TOP 1 FPARTO FROM PARTOS
		WHERE ID = @RES_GEN
		AND FPARTO<@RES_FP
  		ORDER BY FPARTO DESC
		OPEN C2
		FETCH NEXT FROM C2 INTO @WRES_FP
		IF  @@FETCH_STATUS=0 --LO ENCONTRÓ
		BEGIN		
				IF DATEDIFF(DAY, @WRES_FP, @RES_FP) < 0   OR DATEDIFF(DAY, @WRES_FP, @RES_FP) >@DIAS
				BEGIN
					INSERT INTO CONTROLTXT (GEN,FPREV,FP,NP)
					VALUES(@RES_GEN,@WRES_FP,@RES_FP,@RES_NP) --METO EN FPREV EL PARTO ANTERIOR
					--AHORA ACTUALIZO LOS DEMAS VALORES QUE ME INTERESAN
					UPDATE CONTROLTXT
					SET FBAJA=PARTOS.FBAJA,
					CONTROLTXT.CBAJA=PARTOS.CBAJA,
					CONTROLTXT.NOMBRE=PARTOS.DET,
					CONTROLTXT.CONTROLADOR=PARTOS.NUMCONTROLADOR
					FROM PARTOS
					WHERE CONTROLTXT.GEN=PARTOS.ID
					AND CONTROLTXT.FPREV=PARTOS.FPARTO --'COJO EL ANTERIOR PARTO
				END
		END
		CLOSE C2
		DEALLOCATE C2
		FETCH NEXT FROM C1 INTO @RES_GEN,@RES_FP,@RES_NP
	END
CLOSE C1
DEALLOCATE C1