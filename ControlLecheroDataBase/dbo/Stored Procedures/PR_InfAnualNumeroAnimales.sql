






CREATE PROCEDURE PR_InfAnualNumeroAnimales

 (@ESTABLO char(7),
@DESDE SMALLDATETIME,@HASTA SMALLDATETIME ) 

AS


DECLARE @NUM_ESTABLOS INT,@TOTAL_VACAS REAL
DECLARE @NUM_VACAS REAL,@NUM_VACAS2 REAL,@NUM_VACAS3 REAL,@RES CHAR(14)

IF @ESTABLO<>' '
BEGIN
	 /*===================ANIMALES EN ESTABLO=======================*/
	--Cojo la media entre las que habia en DESDE y las de HASTA.	
	
	--SET @DESDE='31/12/2004'
	--SET @HASTA='31/12/2004'
	--set @Establo='j390029'
	SET @TOTAL_VACAS=0

	DECLARE C2 cursor  FOR
	SELECT COUNT(*) FROM REGGEN..ANIMALES
	WHERE ganpro=@Establo
	AND  SEXO='H'
	AND DATEDIFF(month, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), @DESDE)>=24
	OPEN C2
	FETCH NEXT FROM C2 INTO @NUM_VACAS
	CLOSE C2
	DEALLOCATE C2

	DECLARE C2 cursor  FOR
	SELECT COUNT(*)  FROM REGGEN..TRANSFERENCIAS T,REGGEN..ANIMALES A 
	WHERE CODCOM=@Establo
	AND  T.SEXO='H'
	AND AÑOTR>2003
	AND (T.PAIS+T.SEXO+T.PROANI+T.NUMERO)=(A.PAIS+A.SEXO+A.PROANI+A.NUMERO)
	AND DATEDIFF(month, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), @DESDE)>=24
	AND (CASE WHEN MESTR=0    THEN NULL 
	ELSE  (cast(DIATR as char(2)) + '/' + cast(MESTR as char(2)) + '/'+ cast(AÑOTR as char(4))) END) >@DESDE
	OPEN C2
	FETCH NEXT FROM C2 INTO @NUM_VACAS2
	CLOSE C2
	DEALLOCATE C2

	DECLARE C2 cursor  FOR
	SELECT  COUNT(*) FROM REGGEN..TRANSFERENCIAS T,REGGEN..ANIMALES A 
	WHERE CODVEN=@Establo
	AND  T.SEXO='H'
	AND AÑOTR>2003
	AND (T.PAIS+T.SEXO+T.PROANI+T.NUMERO)=(A.PAIS+A.SEXO+A.PROANI+A.NUMERO)
	AND DATEDIFF(month, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), @DESDE)>=24
	AND (CASE WHEN MESTR=0    THEN NULL 
	ELSE  (cast(DIATR as char(2)) + '/' + cast(MESTR as char(2)) + '/'+ cast(AÑOTR as char(4))) END) >@DESDE
	OPEN C2
	FETCH NEXT FROM C2 INTO @NUM_VACAS3
	CLOSE C2
	DEALLOCATE C2
	SELECT (@NUM_VACAS-@NUM_VACAS2+@NUM_VACAS3) AS CENSO
		
	
END
ELSE
	BEGIN
	/*===================ANIMALES EN CANTABRIA=======================*/
	 DECLARE C1 cursor for 
	SELECT COUNT(DISTINCT MAES_TIT) FROM MAESTRO,LECTURASCONTROL
	WHERE LECTURASCONTROL.FBAJA IS  NULL
	AND MAES_TIT=ESTABLO /*cojo solo los activos actualmente*/
	AND TAMANOESTABLO IS NOT NULL
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @NUM_ESTABLOS
	CLOSE C1
	DEALLOCATE C1

	DECLARE C2 cursor  FOR
	SELECT COUNT(*) FROM LECTURASCONTROL,REGGEN..ANIMALES 
	WHERE 
	ESTABLO=GANPRO
	AND  SEXO='H'
	AND DATEDIFF(month, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), @DESDE)>=24 
	AND FBAJA IS NULL
	AND TAMANOESTABLO IS NOT NULL
	AND NUMLAC=0 and AÑOBAJ=0
	AND  SEXO='H'
	AND DATEDIFF(month, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), getdate())>24
	OPEN C2
	FETCH NEXT FROM C2 INTO @NUM_VACAS
	CLOSE C2
	DEALLOCATE C2


	DECLARE C2 cursor  FOR
	SELECT COUNT(*)  FROM REGGEN..TRANSFERENCIAS T,REGGEN..ANIMALES A
	WHERE CODCOM=GANPRO
	AND  T.SEXO='H'
	AND AÑOTR>2003
	AND (T.PAIS+T.SEXO+T.PROANI+T.NUMERO)=(A.PAIS+A.SEXO+A.PROANI+A.NUMERO)
	AND DATEDIFF(month, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), @DESDE)>=24
	AND (CASE WHEN MESTR=0    THEN NULL 
	ELSE  (cast(DIATR as char(2)) + '/' + cast(MESTR as char(2)) + '/'+ cast(AÑOTR as char(4))) END) >@DESDE
	OPEN C2
	FETCH NEXT FROM C2 INTO @NUM_VACAS2
	CLOSE C2
	DEALLOCATE C2

	DECLARE C2 cursor  FOR
	SELECT  COUNT(*) FROM REGGEN..TRANSFERENCIAS T,REGGEN..ANIMALES A 
	WHERE CODVEN=GANPRO
	AND AÑOTR>2003
	AND  T.SEXO='H'
	AND (T.PAIS+T.SEXO+T.PROANI+T.NUMERO)=(A.PAIS+A.SEXO+A.PROANI+A.NUMERO)
	AND DATEDIFF(month, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), @DESDE)>=24
	AND (CASE WHEN MESTR=0    THEN NULL 
	ELSE  (cast(DIATR as char(2)) + '/' + cast(MESTR as char(2)) + '/'+ cast(AÑOTR as char(4))) END) >@DESDE
	OPEN C2
	FETCH NEXT FROM C2 INTO @NUM_VACAS3
	CLOSE C2
	DEALLOCATE C2

	
	UPDATE INFORMEANUAL SET VALOR=@NUM_VACAS
	WHERE GRUPO='CANTABRIA' 
	AND CONCEPTO='TOTAL VACAS(>24)'
	
	UPDATE INFORMEANUAL SET VALOR=(@NUM_VACAS-@NUM_VACAS2+@NUM_VACAS3)/@NUM_ESTABLOS
	WHERE GRUPO='CANTABRIA' 
	AND CONCEPTO='MED VACAS EN EL ESTABLO(>24)'	
	
	
	/*========ANIMALES EN TRAMOS================*/
	
	DECLARE @TAMANOESTABLO CHAR(1)
	DECLARE @MED_NUM_VACAS REAL
	
	DECLARE C1 cursor for 
	SELECT TAMANOESTABLO,COUNT(DISTINCT MAES_TIT) 
	FROM MAESTRO,LECTURASCONTROL
	WHERE 
	FBAJA IS  NULL
	AND TAMANOESTABLO IS NOT NULL
	AND MAES_TIT=ESTABLO
	GROUP BY TAMANOESTABLO
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	WHILE (@@FETCH_STATUS=0)
	BEGIN
		DECLARE C2 cursor  FOR
		SELECT COUNT(*) FROM LECTURASCONTROL,REGGEN..ANIMALES 
		WHERE 
		ESTABLO=GANPRO
		AND DATEDIFF(month, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), @DESDE)>=24 
		AND FBAJA IS NULL
		AND TAMANOESTABLO IS NOT NULL
		AND TAMANOESTABLO=@TAMANOESTABLO
		AND NUMLAC=0 and AÑOBAJ=0
		AND  SEXO='H'
		AND DATEDIFF(month, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), getdate())>24
		OPEN C2
		FETCH NEXT FROM C2 INTO @NUM_VACAS
		CLOSE C2
		DEALLOCATE C2
	
		DECLARE C2 cursor  FOR
		SELECT COUNT(*)  FROM REGGEN..TRANSFERENCIAS T,REGGEN..ANIMALES A,LECTURASCONTROL
		WHERE  CODCOM=ESTABLO
		AND GANPRO=ESTABLO
		AND  T.SEXO='H'
		AND AÑOTR>2003
		AND TAMANOESTABLO=@TAMANOESTABLO
		AND (T.PAIS+T.SEXO+T.PROANI+T.NUMERO)=(A.PAIS+A.SEXO+A.PROANI+A.NUMERO)
		AND DATEDIFF(month, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), @DESDE)>=24
		AND (CASE WHEN MESTR=0    THEN NULL 
		ELSE  (cast(DIATR as char(2)) + '/' + cast(MESTR as char(2)) + '/'+ cast(AÑOTR as char(4))) END) >@DESDE
		OPEN C2
		FETCH NEXT FROM C2 INTO @NUM_VACAS2
		CLOSE C2
		DEALLOCATE C2

		DECLARE C2 cursor  FOR
		SELECT  COUNT(*) FROM REGGEN..TRANSFERENCIAS T,REGGEN..ANIMALES A,LECTURASCONTROL
		WHERE CODVEN=ESTABLO
		AND GANPRO=ESTABLO
		AND  T.SEXO='H'
		AND AÑOTR>2003
		AND TAMANOESTABLO=@TAMANOESTABLO
		AND (T.PAIS+T.SEXO+T.PROANI+T.NUMERO)=(A.PAIS+A.SEXO+A.PROANI+A.NUMERO)
		AND DATEDIFF(month, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), @DESDE)>=24
		AND (CASE WHEN MESTR=0    THEN NULL 
		ELSE  (cast(DIATR as char(2)) + '/' + cast(MESTR as char(2)) + '/'+ cast(AÑOTR as char(4))) END) >@DESDE
		OPEN C2
		FETCH NEXT FROM C2 INTO @NUM_VACAS3
		CLOSE C2
		DEALLOCATE C2
				
			UPDATE INFORMEANUAL SET VALOR=(@NUM_VACAS-@NUM_VACAS2+@NUM_VACAS3)/@NUM_ESTABLOS
			WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
			AND CONCEPTO='MED VACAS EN EL ESTABLO(24)'
	
			UPDATE INFORMEANUAL SET VALOR=(@NUM_VACAS-@NUM_VACAS2+@NUM_VACAS3)
			WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
			AND CONCEPTO='TOTAL VACAS(>24)'
				
		FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	END
	CLOSE C1
	DEALLOCATE C1
		
END






