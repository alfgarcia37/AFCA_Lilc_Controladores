



CREATE PROCEDURE  PR_ControlesIncidencias 
(@RES_GEN CHAR(14),
@RES_NP INT
)
AS 

DECLARE @GRASA REAL,@PROTEINA REAL,@KILOS REAL,@WKILOS REAL
DECLARE @INC CHAR(10)
--MIRO SI TIENE VACACIONES (UN CONTROL FALTANTE)
--MIRO SI FALTA ANALITICA OTRO CONTROL
--MIRO SI 50% DE LECHE DE UN CONTROL AL ANTERIOR
SET @INC=''

DECLARE C1 CURSOR  FOR
SELECT RES_KLAM+RES_KLPM,RES_TGR,RES_TPR FROM CONTROL
WHERE 
RES_AB='A'
AND RES_GEN=@RES_GEN
AND RES_NP=@RES_NP
ORDER BY RES_NP

FOR UPDATE OF RES_INCRECAL

OPEN C1
FETCH NEXT FROM C1 INTO @KILOS,@GRASA,@PROTEINA

WHILE ( @@FETCH_STATUS=0)
	BEGIN 
		SET @INC=RTRIM(LTRIM(@INC))
		SET @WKILOS=@KILOS
		IF @GRASA=0 AND @PROTEINA<>0 
			BEGIN
				SET @INC=RTRIM(LTRIM(@INC)) + '03'
			END
		IF @GRASA<>0 AND @PROTEINA=0 
			BEGIN
				SET @INC=RTRIM(LTRIM(@INC))+'04'
			END
		IF @GRASA=0 AND @PROTEINA=0 
		BEGIN
			SET @INC=RTRIM(LTRIM(@INC))+'05'
		END
	  
		UPDATE CONTROL
		SET RES_INCRECAL=@INC
	 	WHERE CURRENT OF C1
		SET @INC=''
		FETCH NEXT FROM C1 INTO @KILOS,@GRASA,@PROTEINA
		IF @KILOS<(@WKILOS/2) 
		BEGIN
			SET @INC=RTRIM(LTRIM(@INC))+'50'
		END
	END


CLOSE C1
DEALLOCATE C1



