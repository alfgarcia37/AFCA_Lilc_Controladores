CREATE PROCEDURE PR_VacasMaestroControl
	(@intNUMERO int,
	 @wESTADO CHAR(1))
AS
	/* SET NOCOUNT ON  */

-- VACAS QUE ESTAN EN MAESTRO COMO ALTA Y HACE 'n' MESES QUE NO SE CONTROLAN
delete from VacasMaestroControl


DECLARE @MAES_TIT CHAR(7),@MAES_GEN CHAR(14),@MAES_FP SMALLDATETIME,@MAES_NP INT,@MAES_NC INT,@MAES_FBA SMALLDATETIME
DECLARE @RES_TIT CHAR(7),@RES_NP INT,@RES_NC INT,@RES_FPREV SMALLDATETIME,@CONTROLADOR INT

declare C1 cursor for 
SELECT MAES_TIT,MAES_GEN,MAES_FP,MAES_NP,MAES_NC,MAES_FBA  FROM MAESTRO
WHERE 
MAES_ESTADO=@wESTADO
--AND MAES_TIT<'J390100'
AND DATEDIFF([MONTH], Maes_FBA, GETDATE()) > @intNUMERO

OPEN  C1 
FETCH NEXT FROM C1 INTO @MAES_TIT,@MAES_GEN ,@MAES_FP,@MAES_NP,@MAES_NC ,@MAES_FBA
WHILE (@@FETCH_STATUS=0)
  BEGIN
	declare C2 cursor  FOR
	SELECT  TOP 1 RES_TIT,RES_NP,RES_NC,RES_FPREV,CONTROLADOR FROM CONTROL
	WHERE RES_GEN=@MAES_GEN
	ORDER BY RES_FPREV DESC
	OPEN C2
	FETCH NEXT FROM C2 INTO @RES_TIT,@RES_NP,@RES_NC,@RES_FPREV,@CONTROLADOR
		
	IF @@FETCH_STATUS=0  
		BEGIN
			INSERT INTO VACASMAESTROCONTROL (ESTABLOMAES,ID ,MAES_FP,MAES_NP,MAES_NC,ESTABLOCONTROL,RES_NP,RES_NC,RES_FPREV,CONTROLADOR,MAES_FBA)
			VALUES (@MAES_TIT,@MAES_GEN,@MAES_FP,@MAES_NP,@MAES_NC,@RES_TIT,@RES_NP,@RES_NC,@RES_FPREV,@CONTROLADOR,@MAES_FBA)
	 		/*WHERE CURRENT OF C2*/
		END
	CLOSE C2
	DEALLOCATE C2

	FETCH NEXT FROM C1 INTO  @MAES_TIT,@MAES_GEN ,@MAES_FP,@MAES_NP,@MAES_NC,@MAES_FBA

  END

CLOSE C1
DEALLOCATE C1