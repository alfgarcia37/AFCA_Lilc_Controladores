SELECT CONTROLADOR 'ID',RES_INC 'DET',CAST (COUNT(RES_INC) AS CHAR(4)) 'PARAM1',0 'PARAM2' FROM CONTROL
WHERE RES_FPREV BETWEEN @FDESDE AND @FHASTA
