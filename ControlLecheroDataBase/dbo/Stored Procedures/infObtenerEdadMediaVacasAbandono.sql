





CREATE PROCEDURE dbo.infObtenerEdadMediaVacasAbandono
	(
		@Establo char(7),
		@AnoMes char(3),
		@WFECHA SMALLDATETIME

	)
AS

DECLARE @FLECTURA SMALLDATETIME

IF @Establo<>''
BEGIN
	
	Declare C1 cursor LOCAL SCROLL OPTIMISTIC FOR
	SELECT TOP 1 FPrevista FROM LecturasFinalizadas 
	WHERE Establo = @Establo ORDER BY fprevista DESC
	OPEN C1 
	FETCH NEXT FROM C1 INTO @FLECTURA
	WHILE (@@FETCH_STATUS=0)
	BEGIN
		IF @AnoMes='MES'
			  BEGIN
				SELECT avg(DATEDIFF(DAY,RES_FN,GETDATE())) AS NUMERODIAS FROM CONTROL
				WHERE RES_TIT=@Establo
				AND RES_FPREV=@FLECTURA
				AND RES_CBA IN ('02','03','04','05','06','07','08','09')
			  END
		ELSE
			  BEGIN
				SELECT avg(DATEDIFF(DAY,RES_FN,GETDATE())) AS NUMERODIAS FROM CONTROL
				WHERE RES_TIT=@Establo
				AND YEAR(RES_FPREV)= YEAR(@FLECTURA) 
				AND RES_CBA IN ('02','03','04','05','06','07','08','09')
				
			  END
	FETCH NEXT FROM C1 INTO @FLECTURA
	END
	CLOSE C1
	DEALLOCATE C1
END

ELSE

	BEGIN
		IF @AnoMes='MES'
			  BEGIN
				SELECT avg(DATEDIFF(DAY,RES_FN,GETDATE())) AS NUMERODIAS FROM CONTROL
				WHERE  RES_FPREV >=@WFECHA
				AND RES_FPREV < DATEADD(MONTH,1,@WFECHA)
				AND RES_CBA IN ('02','03','04','05','06','07','08','09')
			  END
		ELSE
			  BEGIN
				SELECT avg(DATEDIFF(DAY,RES_FN,GETDATE())) AS NUMERODIAS FROM CONTROL
				WHERE RES_FPREV>= '01/01/' + CAST(YEAR(@WFECHA) AS CHAR(4))
				AND RES_FPREV<='31/12/' + CAST(YEAR(@WFECHA) AS CHAR(4)) 
				AND RES_CBA IN ('02','03','04','05','06','07','08','09')
				
			  END
	END




