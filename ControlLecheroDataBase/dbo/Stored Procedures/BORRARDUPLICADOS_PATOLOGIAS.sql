CREATE PROCEDURE [dbo].[BORRARDUPLICADOS_PATOLOGIAS]

	
AS

DECLARE @RES CHAR(14),@WRES CHAR(14),@CONTADOR INT,@FPATOLOGIA SMALLDATETIME,@WFPATOLOGIA SMALLDATETIME,@TIPOPATOLOGIA CHAR(2),@WTIPOPATOLOGIA CHAR(2)



DECLARE C1 CURSOR LOCAL SCROLL OPTIMISTIC FOR
SELECT RES,TIPOPATOLOGIA,FPATOLOGIA
FROM PATOLOGIAS
WHERE  FPATOLOGIA>'01/01/2014'
GROUP BY RES,TIPOPATOLOGIA,FPATOLOGIA
HAVING COUNT(*)>1
OPEN C1 
FETCH NEXT FROM C1 INTO @RES,@TIPOPATOLOGIA,@FPATOLOGIA
WHILE (@@FETCH_STATUS=0)
BEGIN
	DECLARE C2 CURSOR LOCAL SCROLL 
	OPTIMISTIC 
	DYNAMIC
	FOR
	SELECT RES,TIPOPATOLOGIA,FPATOLOGIA
	FROM PATOLOGIAS
	WHERE RES= @RES AND TIPOPATOLOGIA=@TIPOPATOLOGIA AND FPATOLOGIA=@FPATOLOGIA
	OPEN C2
	FETCH NEXT FROM C2 INTO @WRES,@WTIPOPATOLOGIA,@WFPATOLOGIA
	/*PRINT CONVERT(CHAR,@@FETCH_STATUS) + ' '+@ID*/
	IF @@FETCH_STATUS=0  
		BEGIN
			DELETE PATOLOGIAS
			WHERE CURRENT OF C2
		END
	CLOSE C2
	DEALLOCATE C2
	FETCH NEXT FROM C1 INTO @RES,@TIPOPATOLOGIA,@FPATOLOGIA
END
CLOSE C1
DEALLOCATE C1
