
CREATE PROCEDURE [dbo].[BORRARDUPLICADOS_ID_DET]  AS

DECLARE @ID CHAR(14),@WID CHAR(14),@CONTADOR INT,@FP CHAR(10),@WFP CHAR(10),@ESTABLO CHAR(7),@WESTABLO CHAR(7)



DECLARE C1 CURSOR LOCAL SCROLL OPTIMISTIC FOR
SELECT ID,ESTABLO
FROM BuzonLaboratorio
GROUP BY ID,ESTABLO
HAVING COUNT(*)>1
OPEN C1 
FETCH NEXT FROM C1 INTO @ID,@ESTABLO
WHILE (@@FETCH_STATUS=0)
BEGIN
	DECLARE C2 CURSOR LOCAL SCROLL 
	OPTIMISTIC 
	DYNAMIC
	FOR
	SELECT ID,ESTABLO
	FROM BuzonLaboratorio
	WHERE ESTABLO= @ESTABLO AND ID=@ID
	
	
	
	OPEN C2
	FETCH NEXT FROM C2 INTO @WID,@WESTABLO
	/*PRINT CONVERT(CHAR,@@FETCH_STATUS) + ' '+@ID*/
	IF @@FETCH_STATUS=0  
		BEGIN
			DELETE BuzonLaboratorio
			WHERE CURRENT OF C2
		END
	CLOSE C2
	DEALLOCATE C2
	FETCH NEXT FROM C1 INTO @ID,@ESTABLO
END
CLOSE C1
DEALLOCATE C1