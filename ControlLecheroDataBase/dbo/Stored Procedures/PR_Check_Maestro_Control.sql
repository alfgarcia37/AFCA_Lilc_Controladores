




CREATE PROCEDURE [dbo].[PR_Check_Maestro_Control]
(@WESTABLO CHAR(7))
	
AS
	

DECLARE @MAES_TIT CHAR(7),@MAES_GEN CHAR(14),@MAES_FP SMALLDATETIME,@MAES_NP INT,@MAES_NC INT,@MAES_ESTADO CHAR(1)
DECLARE @RES_TIT CHAR(7),@RES_GEN CHAR(14),@RES_NP INT,@RES_NC INT,@RES_AB CHAR(1),@FPREVISTA SMALLDATETIME
DECLARE @CADENA VARCHAR(200),@num INT

SET @CADENA=''

declare C1 cursor for 
SELECT TOP 1 FPREVISTA
FROM LECTURASFINALIZADAS
WHERE 
ESTABLO=@WESTABLO
ORDER BY FPREVISTA DESC


OPEN  C1 
FETCH NEXT FROM C1 INTO @FPREVISTA 
WHILE (@@FETCH_STATUS=0)
  BEGIN
	DECLARE C2 CURSOR  FOR
	SELECT RES_GEN,RES_NP,RES_NC FROM CONTROL
	WHERE RES_TIT=@WESTABLO
	AND RES_FPREV=@FPREVISTA
	AND RES_AB='A'
	--prueba
	--and RES_GEN='ES090604369961'
	--
	ORDER BY RES_GEN,RES_NP,RES_NC,RES_AB 
	OPEN C2
	FETCH NEXT FROM C2 INTO @RES_GEN,@RES_NP,@RES_NC 

	IF @@FETCH_STATUS=0
	BEGIN

		DECLARE C3 CURSOR  FOR
		SELECT MAES_GEN,MAES_NP,MAES_NC
		FROM MAESTRO
		WHERE MAES_TIT=@WESTABLO
		AND MAES_ESTADO='A'
		ORDER BY MAES_GEN,MAES_NP,MAES_NC
		OPEN C3
		FETCH NEXT FROM C3 INTO @MAES_GEN,@MAES_NP,@MAES_NC
		--print 	 @MAES_GEN + ' ' + cast(@MAES_NP as char(2)) + ' ' +cast( @MAES_NC as char(2))
		WHILE (@@FETCH_STATUS=0)  --DE MAESTRO
		BEGIN
		
			IF @RES_GEN=@MAES_GEN 
			BEGIN
			--print 'Entra en IF @RES_GEN=@MAES_GEN'
				IF  not(@RES_NP=@MAES_NP AND @RES_NC=@MAES_NC)
				BEGIN
					SET @CADENA=@CADENA + @MAES_GEN +'PARTO ó CONTROL,' 
					
				END
				
					FETCH NEXT FROM C2 INTO @RES_GEN,@RES_NP,@RES_NC
					FETCH NEXT FROM C3 INTO @MAES_GEN,@MAES_NP,@MAES_NC
			END
	
			ELSE
			BEGIN
				IF @MAES_GEN<@RES_GEN
				BEGIN
					SET @CADENA=@CADENA + @MAES_GEN +'NO EXISTE EN CONTROL,'
					FETCH NEXT FROM C3 INTO @MAES_GEN,@MAES_NP,@MAES_NC
				END
				IF @RES_GEN<@MAES_GEN
				BEGIN
					-- miro que no se dio de baja en el libro 
					DECLARE C4 CURSOR  FOR
					SELECT count(*) from [reggen].[dbo].[BAJAS DEL LIBRO]
					where codigoidentif=@RES_GEN
					OPEN C4
					FETCH NEXT FROM C4 INTO @num
						
					if @num>0  --DE [BAJAS DEL LIBRO]
					begin
						SET @CADENA=@CADENA +  @RES_GEN +'...BAJA EN EL LIBRO..,'
						FETCH NEXT FROM C2 INTO @RES_GEN,@RES_NP,@RES_NC
					end
					else
					begin
						SET @CADENA=@CADENA +  @RES_GEN +'NO EXISTE EN MAESTRO,'
						FETCH NEXT FROM C2 INTO @RES_GEN,@RES_NP,@RES_NC
					end
					CLOSE C4
					DEALLOCATE C4
					-- fin baja libro
					
				END
	
			END
		
		END--DEL FETCH DE MAESTRO
		CLOSE C3
		DEALLOCATE C3
		FETCH NEXT FROM C1 INTO  @FPREVISTA
		
		END  --DEL FETCH DE CONTROL
		CLOSE C2
		DEALLOCATE C2
	
END --DEL FETCH DE LECTURASFINALIZADAS
CLOSE C1
DEALLOCATE C1
--===================================== PRUEBA =========================
IF @RES_GEN<>@MAES_GEN 
			BEGIN
				SET @CADENA=@CADENA + @RES_GEN
			END
--===================================================================

SELECT  @CADENA