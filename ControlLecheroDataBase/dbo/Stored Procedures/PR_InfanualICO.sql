





CREATE PROCEDURE PR_InfanualICO 
 (@ESTABLO char(7))
AS

DECLARE @NUM_ESTABLOS INT,@TAMANOESTABLO CHAR(1)
DECLARE @NUM_VACAS REAL,@TOTAL_VACAS INT,@NUM_REGISTROS INT,@NUM_VACAS2 REAL,@NUM_VACAS3 REAL
DECLARE @NUM_PARTOS INT,@NUM_DIAS INT

IF @ESTABLO<>''
BEGIN
			
	select AVG(CAST(IG.IcoT AS INTEGER)) AS ICOT,AVG(CAST(IG.Ico AS INTEGER)) AS ICO
	from Maestro M,reggen..animales A,reggen..indicesG IG
	where Maes_tit=@ESTABLO AND MAES_ESTADO<>'0' and a.ganpro=@ESTABLO
	and 
	(Maes_gen=codigoidentif or Maes_gen=a.Pais+a.sexo+a.proani+a.numero)
	and
	a.Pais+a.sexo+a.proani+a.numero=ig.Pais+ig.sexo+ig.proani+ig.numero
	AND 
	(ISNUMERIC(INDGLOBALT)=1  AND ISNUMERIC(ICO)=1 AND KLEVG IS NOT NULL AND  PGRAVG IS NOT NULL AND  PPROVG IS NOT NULL
	 AND  REPTIP IS NOT NULL AND  ICOT IS NOT NULL)
		
	--SELECT @NUM_PARTOS AS NUMPARTOS,@NUM_DIAS AS NUMDIAS,(@NUM_PARTOS*100/@NUM_VACAS2) AS PORCENTAJEPARTOSVACAS,(@NUM_PARTOS*100/(@NUM_VACAS3/@NUM_ESTABLOS)) AS PORCENTAJEPARTOSVACASCONTROLADAS

END
ELSE
BEGIN
	DECLARE C1 cursor for 
	select AVG(CAST(IG.IcoT AS INTEGER)) AS ICOT,AVG(CAST(IG.Ico AS INTEGER)) AS ICO
	from Maestro M,reggen..animales A,reggen..indicesG IG
	where Maes_tit=ganpro
	AND MAES_ESTADO<>'0'
	and 
	(Maes_gen=codigoidentif or Maes_gen=a.Pais+a.sexo+a.proani+a.numero)
	and
	a.Pais+a.sexo+a.proani+a.numero=ig.Pais+ig.sexo+ig.proani+ig.numero
	AND 
	(ISNUMERIC(INDGLOBALT)=1  AND ISNUMERIC(ICO)=1 AND KLEVG IS NOT NULL AND  PGRAVG IS NOT NULL AND  PPROVG IS NOT NULL
	 AND  REPTIP IS NOT NULL AND  ICOT IS NOT NULL)
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @NUM_VACAS2,@NUM_VACAS3
	CLOSE C1
	DEALLOCATE C1

		UPDATE INFORMEANUAL SET VALOR=@NUM_VACAS2
		WHERE GRUPO='CANTABRIA' 
		AND CONCEPTO='ICOT'
		
	
		UPDATE INFORMEANUAL SET VALOR=@NUM_VACAS3
		WHERE GRUPO='CANTABRIA' 
		AND CONCEPTO='ICO'
	
		
	/* ..................................................TRAMOS..............................................*/
	
	DECLARE C1 cursor for 
	SELECT TAMANOESTABLO,COUNT(DISTINCT MAES_TIT) FROM MAESTRO,LECTURASCONTROL
	WHERE 
	FBAJA IS  NULL
	AND TAMANOESTABLO IS NOT NULL
	AND MAES_TIT=ESTABLO
	GROUP BY TAMANOESTABLO
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	WHILE (@@FETCH_STATUS=0)
	BEGIN
		DECLARE C2  CURSOR FOR 
		select AVG(CAST(IG.IcoT AS INTEGER)) AS ICOT,AVG(CAST(IG.Ico AS INTEGER)) AS ICO
		from Maestro M,reggen..animales A,reggen..indicesG IG,LECTURASCONTROL
		where Maes_tit=ganpro
		AND MAES_ESTADO<>'0'
		AND MAES_TIT=LECTURASCONTROL.ESTABLO /*cojo solo los activos actualmente*/
		AND TAMANOESTABLO IS NOT NULL
		AND TAMANOESTABLO=@TAMANOESTABLO
		and 
		(Maes_gen=codigoidentif or Maes_gen=a.Pais+a.sexo+a.proani+a.numero)
		and
		a.Pais+a.sexo+a.proani+a.numero=ig.Pais+ig.sexo+ig.proani+ig.numero
		AND 
		(ISNUMERIC(INDGLOBALT)=1  AND ISNUMERIC(ICO)=1 AND KLEVG IS NOT NULL AND  PGRAVG IS NOT NULL AND  PPROVG IS NOT NULL
		 AND  REPTIP IS NOT NULL AND  ICOT IS NOT NULL)
		
		OPEN  C2 
		FETCH NEXT FROM C2 INTO @NUM_VACAS2,@NUM_VACAS3
		CLOSE C2
		DEALLOCATE C2
		
		UPDATE INFORMEANUAL SET VALOR=@NUM_VACAS2
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='ICOT'

		UPDATE INFORMEANUAL SET VALOR=@NUM_VACAS3
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='ICO'
		
		FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
				
	END
END





