
CREATE PROCEDURE PR_INSEMINACIONES_ESTADISTICA AS
DECLARE @ESTABLO CHAR(7)

DELETE FROM INSEMINACIONESESTADISTICAS

INSERT INTO INSEMINACIONESESTADISTICAS(CONTROLADOR,NOMBRE,ESTABLO,NOMBREESTABLO,INSEMINACIONES)
(select numcontrolador,det,I.ESTABLO,RAZONSOCIAL,count(*) 
from inseminaciones I,controladores,REGGEN..ganaderias_maestro
where finseminacion>'15/12/2006'
and numcontrolador=controladores.id
AND I.ESTABLO=CODGAN
group by numcontrolador,det,I.ESTABLO,RAZONSOCIAL
)

--AHORA TENGO QUE ACTUALIZAR EL CAMPO REPRODUCTORAS

DECLARE C1 CURSOR LOCAL SCROLL OPTIMISTIC FOR
SELECT ESTABLO
FROM INSEMINACIONESESTADISTICAS

OPEN C1 
FETCH NEXT FROM C1 INTO @ESTABLO
WHILE (@@FETCH_STATUS=0)
BEGIN
UPDATE INSEMINACIONESESTADISTICAS
SET REPRODUCTORAS=(SELECT COUNT(*) FROM MAESTRO WHERE MAES_TIT=@ESTABLO AND MAES_ESTADO<>'0')
WHERE ESTABLO=@ESTABLO


FETCH NEXT FROM C1 INTO @ESTABLO
END
