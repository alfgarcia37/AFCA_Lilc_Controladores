




CREATE PROCEDURE PR_CHK_FALTANTES_UPDATE 
(	@RES_GEN CHAR(14),
	@RES_NP INT,
	@RES_NC INT,
	@KILOS REAL,
	@GRASA REAL,
	@PROTEINA REAL,
	@KILOSACTU REAL,
	@GRASAACTU REAL,
	@PROTEINAACTU REAL
 )
AS
DECLARE @KILOSAM REAL,@WINC CHAR(2)

--SELECT @RES_GEN,@RES_NP,@RES_NC,@GRASA,@PROTEINA

	UPDATE CONTROL
	SET RES_KLAM=@KILOSACTU,
	RES_KLPM=@KILOSACTU,
	RES_TGR=@GRASAACTU,
	RES_TPR=@PROTEINAACTU
	WHERE RES_GEN=@RES_GEN
	AND RES_NP=@RES_NP
	AND RES_NC=@RES_NC


IF @KILOS=0 AND @GRASA=0 AND @PROTEINA=0 
BEGIN
	SET @WINC='01'
END

IF @KILOS=0 AND @GRASA<>0 AND @PROTEINA<>0 
BEGIN
	SET @WINC='02'
END

IF @KILOS<>0 AND @GRASA=0 AND @PROTEINA=0 
BEGIN
	SET @WINC='03'
END

IF @KILOS=0 AND @GRASA<>0 AND @PROTEINA=0 
BEGIN
	SET @WINC='04'
END

IF @KILOS=0 AND @GRASA<>0 AND @PROTEINA<>0 
BEGIN
	SET @WINC='05'
END
UPDATE CONTROL
	SET RES_INCRECAL=@WINC
	WHERE RES_GEN=@RES_GEN
	AND RES_NP=@RES_NP
	AND RES_NC=@RES_NC