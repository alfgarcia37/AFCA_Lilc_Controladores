CREATE PROCEDURE PR_CHECK_SECADO_SGTE_PARTO

	
(@datFPREV smalldatetime)

AS

DELETE FROM CONTROLTXT

DECLARE @RES_TIT CHAR(7),@RES_GEN CHAR(14),@RES_NP INT,@RES_NC INT,@RES_FP SMALLDATETIME,@RES_AB CHAR(2),@PARAM1 CHAR(4),@PARAM2 CHAR(4)
DECLARE @WRES_TIT CHAR(7),@WRES_GEN CHAR(14),@WRES_NP INT,@WRES_NC INT,@WRES_FP SMALLDATETIME,@WRES_AB CHAR(1),@RES_FBA SMALLDATETIME,@WRES_FBA  SMALLDATETIME

	DECLARE C3 CURSOR  FOR
	SELECT PARAM1,PARAM2
	FROM PARAMETROSGENERALES
	WHERE ID='ISEPA' 
	OPEN C3
	FETCH NEXT FROM C3 INTO @PARAM1,@PARAM2
	CLOSE C3
	DEALLOCATE C3


	DECLARE C1 CURSOR  FOR
	SELECT RES_TIT, RES_GEN,RES_FP,RES_NP,RES_NC,RES_AB
	FROM CONTROL
	WHERE RES_FPREV>@datFPREV
	--AND RES_TIT='J390916'
	AND ((RES_NC = 1 OR RES_NC=2) AND RES_AB = 'A)'  OR  ((RES_NC = 1 OR RES_NC = 2) AND RES_XAB = 'B'))
	ORDER BY RES_GEN,RES_NP,RES_NC,RES_AB
	OPEN C1
	FETCH NEXT FROM C1 INTO @RES_TIT,@RES_GEN,@RES_FP,@RES_NP,@RES_NC,@RES_AB
	

	WHILE ( @@FETCH_STATUS=0)
	BEGIN
		DECLARE C2 CURSOR  FOR
		SELECT MAX(RES_FBA) FROM CONTROL
		 WHERE RES_TIT = @RES_TIT
  		AND RES_GEN=@RES_GEN
  		AND RES_NP=@RES_NP -1
		OPEN C2
		FETCH NEXT FROM C2 INTO @WRES_FBA
		IF  @@FETCH_STATUS=0 --LO ENCONTRÓ
		BEGIN		
			--IF DATEDIFF(DAY, @WRES_FBA, @RES_FP) < CAST(@PARAM1 AS INT) OR DATEDIFF(DAY, @WRES_FBA, @RES_FP) > CAST(@PARAM2 AS INT) 
			IF DATEDIFF(DAY, @WRES_FBA, @RES_FP) < 0  OR DATEDIFF(DAY, @WRES_FBA, @RES_FP) > @PARAM2
				BEGIN
					INSERT INTO CONTROLTXT (GEN,FP,FBAJA,NP,NC)
					VALUES(@RES_GEN,@RES_FP,@WRES_FBA,@RES_NP,@RES_NC)
				END
			FETCH NEXT FROM C1 INTO @RES_TIT,@RES_GEN,@RES_FP,@RES_NP,@RES_NC,@RES_AB
		END 
		CLOSE C2
		DEALLOCATE C2
	END
CLOSE C1
DEALLOCATE C1