








CREATE PROCEDURE infAvgAgeCAlving
	(
		@Establo char(7)
	)
AS

/* INFORME - REBAÑO TOTAL */
IF @Establo<>''
BEGIN
	SELECT  MAES_GEN,MAES_NP,MAES_FN, FPARTO,DATEDIFF(day, MAES_FN, FPARTO) AS EDAD
	FROM Maestro,Partos 
	WHERE MAES_TIT =@Establo
	AND MAES_TIT =ESTABLO 
	AND MAES_ESTADO<>'0'
	AND MAES_GEN=ID
	AND MAES_NP=PARTOS.NP
	ORDER BY MAES_NP
END
ELSE
BEGIN
	SELECT  MAES_GEN,MAES_NP,MAES_FN, FPARTO,DATEDIFF(day, MAES_FN, FPARTO) AS EDAD
	FROM Maestro,Partos 
	WHERE 
	MAES_TIT =ESTABLO 
	AND MAES_ESTADO<>'0'
	AND MAES_GEN=ID
	AND MAES_NP=PARTOS.NP
	AND MAES_FN IS not NULL
	ORDER BY MAES_NP
END





