






CREATE PROCEDURE  PR_InfAnualPico 
(@ESTABLO char(7),@DESDE SMALLDATETIME,@HASTA SMALLDATETIME)
AS


DECLARE @GEN CHAR(14),@NP INT,@NC INT,@KILOS REAL,@DIAS INT
DECLARE @NUM_ESTABLOS INT,@TAMANOESTABLO CHAR(1)
DECLARE @NUM_VACAS REAL,@TOTAL_VACAS INT,@NUM_REGISTROS INT,@TOTAL_KILOS REAL,@TOTAL_DEL REAL

IF @ESTABLO<>' '
BEGIN
	SET @TOTAL_KILOS=0
	SET @TOTAL_DEL=0
	SET @NUM_REGISTROS=0
	DECLARE C1 CURSOR FOR 
	SELECT RES_GEN,RES_NP
	FROM CONTROL
	WHERE 
	RES_FBA BETWEEN @DESDE AND @HASTA
	AND CONTROL.RES_TIT =@ESTABLO
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @GEN,@NP
	WHILE (@@FETCH_STATUS=0)
	BEGIN
		DECLARE C2 cursor  FOR
		SELECT (RES_KLAM+RES_KLPM) AS  'KILOS',DATEDIFF(DAY,RES_FP,RES_FCTR),RES_NC
		FROM CONTROL
		WHERE 
		RES_GEN=@GEN
		AND RES_NP=@NP
		AND CONTROL.RES_TIT=@ESTABLO 
		ORDER BY (RES_KLAM+RES_KLPM) DESC
				
		OPEN C2
		FETCH NEXT FROM C2 INTO  @KILOS,@DIAS,@NC
		SET @NUM_REGISTROS=@NUM_REGISTROS+1
		SET @TOTAL_KILOS=@TOTAL_KILOS+@KILOS
		IF @DIAS>0  SET @TOTAL_DEL=@TOTAL_DEL+@DIAS
		
		CLOSE C2
		DEALLOCATE C2
	     FETCH NEXT FROM C1 INTO @GEN,@NP
	END
	CLOSE C1
	DEALLOCATE C1
	SELECT (@TOTAL_KILOS/@NUM_REGISTROS) AS PICOKILOS,(@TOTAL_DEL/@NUM_REGISTROS) AS PICODIAS
	END
ELSE
BEGIN
	/*==================PICO PRODUCCION EN CANTABRIA=============================================================*/
	SET @TOTAL_KILOS=0
	SET @TOTAL_DEL=0
	SET @NUM_REGISTROS=0
	DECLARE C1 CURSOR FOR 
	SELECT RES_GEN,RES_NP
	FROM CONTROL,LECTURASCONTROL
	WHERE 
	RES_FBA BETWEEN @DESDE AND @HASTA
	AND LECTURASCONTROL.FBAJA IS  NULL
	AND LECTURASCONTROL.ESTABLO=CONTROL.RES_TIT /*cojo solo los activos actualmente*/
	AND TAMANOESTABLO IS NOT NULL
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @GEN,@NP
	WHILE (@@FETCH_STATUS=0)
	BEGIN
		DECLARE C2 cursor  FOR
		SELECT (RES_KLAM+RES_KLPM) AS  'KILOS',DATEDIFF(DAY,RES_FP,RES_FCTR),RES_NC
		FROM CONTROL,LECTURASCONTROL
		WHERE 
		RES_GEN=@GEN
		AND RES_NP=@NP
		AND LECTURASCONTROL.FBAJA IS  NULL
		AND LECTURASCONTROL.ESTABLO=CONTROL.RES_TIT /*cojo solo los activos actualmente*/
		AND TAMANOESTABLO IS NOT NULL
		ORDER BY (RES_KLAM+RES_KLPM) DESC
				
		OPEN C2
		FETCH NEXT FROM C2 INTO  @KILOS,@DIAS,@NC
		SET @NUM_REGISTROS=@NUM_REGISTROS+1
		SET @TOTAL_KILOS=@TOTAL_KILOS+@KILOS
		IF @DIAS>0  SET @TOTAL_DEL=@TOTAL_DEL+@DIAS
		
		CLOSE C2
		DEALLOCATE C2
	     FETCH NEXT FROM C1 INTO @GEN,@NP
	END
	
		UPDATE INFORMEANUAL SET VALOR=@TOTAL_DEL/@NUM_REGISTROS
		WHERE GRUPO='CANTABRIA' 
		AND CONCEPTO='PICO DIAS EN LECHE'
		UPDATE INFORMEANUAL SET VALOR=@TOTAL_KILOS/@NUM_REGISTROS
		WHERE GRUPO='CANTABRIA' 
		AND CONCEPTO='PICO PRODUCCION'
	
	CLOSE C1
	DEALLOCATE C1
	
	/*========PICO PRODUCCION  EN TRAMOS================*/
	
	
	DECLARE C1 CURSOR FOR 
	SELECT TAMANOESTABLO,COUNT(DISTINCT MAES_TIT)
	FROM MAESTRO,LECTURASCONTROL
	WHERE 
	LECTURASCONTROL.FBAJA IS  NULL
	AND TAMANOESTABLO IS NOT NULL
	AND MAES_TIT=ESTABLO
	GROUP BY TAMANOESTABLO
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	WHILE (@@FETCH_STATUS=0)
	BEGIN
		SET @TOTAL_KILOS=0
		SET @TOTAL_DEL=0
		SET @NUM_REGISTROS=0
		DECLARE C2 CURSOR FOR 
		SELECT RES_GEN,RES_NP
		FROM CONTROL,LECTURASCONTROL
		WHERE 
		RES_FBA BETWEEN @DESDE AND @HASTA
		AND RES_TIT=ESTABLO
		AND TAMANOESTABLO=@TAMANOESTABLO
		AND LECTURASCONTROL.FBAJA IS  NULL
		AND TAMANOESTABLO IS NOT NULL
		OPEN  C2 
		FETCH NEXT FROM C2 INTO @GEN,@NP
		WHILE (@@FETCH_STATUS=0)
		BEGIN
			DECLARE C3 CURSOR  FOR
			SELECT (RES_KLAM+RES_KLPM) AS  'KILOS',DATEDIFF(DAY,RES_FP,RES_FCTR),RES_NC
			FROM CONTROL,LECTURASCONTROL
			WHERE 
			RES_GEN=@GEN
			AND RES_NP=@NP
			AND LECTURASCONTROL.FBAJA IS  NULL
			AND LECTURASCONTROL.ESTABLO=CONTROL.RES_TIT /*cojo solo los activos actualmente*/
			AND TAMANOESTABLO IS NOT NULL
			ORDER BY (RES_KLAM+RES_KLPM) DESC
					
			OPEN C3
			FETCH NEXT FROM C3 INTO  @KILOS,@DIAS,@NC
			SET @NUM_REGISTROS=@NUM_REGISTROS+1
			SET @TOTAL_KILOS=@TOTAL_KILOS+@KILOS
			IF @DIAS>0  SET @TOTAL_DEL=@TOTAL_DEL+@DIAS
			
			CLOSE C3
			DEALLOCATE C3
	     	 FETCH NEXT FROM C2 INTO @GEN,@NP
		END
	   CLOSE C2
	   DEALLOCATE C2
		UPDATE INFORMEANUAL SET VALOR=@TOTAL_DEL/@NUM_REGISTROS
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='PICO DIAS EN LECHE'
	
		UPDATE INFORMEANUAL SET VALOR=@TOTAL_KILOS/@NUM_REGISTROS
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='PICO PRODUCCION'
		FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	END
	CLOSE C1
	DEALLOCATE C1
END






