

CREATE PROCEDURE PR_Check_Control_Igual_NC

	
(@datFPREV smalldatetime)

AS
	
DELETE FROM CONTROLTXT

--DECLARE @MAES_TIT CHAR(7),@MAES_GEN CHAR(14),@MAES_FP SMALLDATETIME,@MAES_NP INT,@MAES_NC INT,@MAES_ESTADO CHAR(1)
DECLARE @RES_TIT CHAR(7),@RES_GEN CHAR(14),@RES_NP INT,@RES_NC INT,@RES_FP SMALLDATETIME,@RES_AB CHAR(2)
DECLARE @WRES_TIT CHAR(7),@WRES_GEN CHAR(14),@WRES_NP INT,@WRES_NC INT,@WRES_FP SMALLDATETIME,@WRES_AB CHAR(1)



	DECLARE C1 CURSOR  FOR
	SELECT RES_GEN,RES_NP,RES_NC,RES_AB
	FROM CONTROL
	WHERE RES_FPREV>'01/10/2006'
	--AND RES_TIT='J390452'
	ORDER BY RES_GEN,RES_NP,RES_NC,RES_AB
	OPEN C1
	FETCH NEXT FROM C1 INTO @RES_GEN,@RES_NP,@RES_NC,@RES_AB
	SET @WRES_GEN=@RES_GEN
	SET @WRES_NP=@RES_NP
	SET @WRES_NC=@RES_NC

	WHILE ( @@FETCH_STATUS=0)
	BEGIN
		FETCH NEXT FROM C1 INTO @RES_GEN,@RES_NP,@RES_NC,@RES_AB
			IF @RES_GEN=@WRES_GEN AND  @RES_NP=@WRES_NP AND  @RES_NC=@WRES_NC AND  @RES_AB=@WRES_AB
			BEGIN
				BEGIN
					INSERT INTO CONTROLTXT (GEN,NP,NC)
					VALUES(@RES_GEN,@RES_NP,@RES_NC)
				END
			END
		SET @WRES_GEN=@RES_GEN
		SET @WRES_NP=@RES_NP
		SET @WRES_NC=@RES_NC
		SET @WRES_AB=@RES_AB
	END --DEL WHILE
CLOSE C1
DEALLOCATE C1

SELECT * FROM CONTROLTXT