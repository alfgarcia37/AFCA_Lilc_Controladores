CREATE PROCEDURE  [dbo].[PR_CONTROL_FALTANTE_ANALITICA]
(@RES_GEN CHAR(14),
@RES_NP INT,
@RES_NC INT,
@RES_TGR REAL,
@RES_TPR REAL,
@RES_INCRECAL CHAR(2)
)
AS 

DECLARE @GRASA REAL,@PROTEINA REAL
DECLARE @GRASA_ANTERIOR REAL,@PROTEINA_ANTERIOR REAL
DECLARE @GRASA_POSTERIOR REAL,@PROTEINA_POSTERIOR REAL

--POR DEFECTO
UPDATE FALTANTES SET GRASAFALTANTE=@RES_TGR,PROTEINAFALTANTE=@RES_TPR

--MIRO FALTANTES GRASA
IF @RES_TGR<1.5 OR @RES_TGR=0 OR @RES_INCRECAL='02'
BEGIN
	--HALLO EL ANTERIOR..............................................................
	DECLARE C11 CURSOR  FOR
	SELECT TOP 1 RES_TGR  FROM CONTROL
	WHERE RES_GEN=@RES_GEN
	AND RES_NP=@RES_NP
	AND RES_NC<@RES_NC
	ORDER BY RES_NC
	OPEN C11
	FETCH NEXT FROM C11 INTO @GRASA
	CLOSE C11
	DEALLOCATE C11

	IF ( @@FETCH_STATUS=0)
	
	BEGIN --TIENE ANTERIOR
		SET @GRASA_ANTERIOR=@GRASA
	END
	ELSE
	BEGIN
		SET @GRASA_ANTERIOR=0
	END
	--HALLO EL POSTERIOR
	DECLARE C11 CURSOR  FOR
	SELECT TOP 1 RES_TGR FROM CONTROL
	WHERE RES_GEN=@RES_GEN
	AND RES_NP=@RES_NP
	AND RES_NC>@RES_NC
	ORDER BY RES_NC 
	OPEN C11
	FETCH NEXT FROM C11 INTO @GRASA
	CLOSE C11
	DEALLOCATE C11
		IF ( @@FETCH_STATUS=0)
		BEGIN --TIENE POSTERIOR
			SET @GRASA_POSTERIOR=@GRASA
		END
	ELSE
		BEGIN
			SET @GRASA_POSTERIOR=0
		END
	--SI TIENE ANTERIOR Y POSTERIOR -> HALLO MEDIA
	IF @GRASA_ANTERIOR<>0 AND @GRASA_POSTERIOR<>0 
	BEGIN
		SET @GRASA=(@GRASA_ANTERIOR+@GRASA_POSTERIOR)/2
	END
	-- SI NO TIENE ANTERIOR  Y TIENE POSTERIOR -> VALOR DEL SIGUIENTE
	IF @GRASA_ANTERIOR=0 AND @GRASA_POSTERIOR<>0 
	BEGIN
		SET @GRASA=@GRASA_POSTERIOR
	END
	-- SI  TIENE ANTERIOR  Y NO TIENE POSTERIOR -> VALOR DEL ANTERIOR
	IF  @GRASA_ANTERIOR<>0 AND @GRASA_POSTERIOR=0
	BEGIN
		SET @GRASA=@GRASA_ANTERIOR
	END
	--SI NO TIENE ANTERIOR Y NO TIENE POSTERIOR 
	IF  @GRASA_ANTERIOR=0 AND @GRASA_POSTERIOR=0
	BEGIN
		SET @GRASA=1.5
	END
	UPDATE FALTANTES SET GRASAFALTANTE=@GRASA
END --DEL GRASA<1,5


--MIRO FALTANTES PROTEINA
IF @RES_TPR<2 OR @RES_TPR=0 OR @RES_INCRECAL='02'
BEGIN
	--HALLO EL ANTERIOR..............................................................
	DECLARE C11 CURSOR  FOR
	SELECT TOP 1 RES_TPR  FROM CONTROL
	WHERE RES_GEN=@RES_GEN
	AND RES_NP=@RES_NP
	AND RES_NC<@RES_NC
	ORDER BY RES_NC
	OPEN C11
	FETCH NEXT FROM C11 INTO @PROTEINA
	CLOSE C11
	DEALLOCATE C11

	IF ( @@FETCH_STATUS=0)
	BEGIN --TIENE ANTERIOR
		SET @PROTEINA_ANTERIOR=@PROTEINA
	END
	ELSE
	BEGIN
		SET @PROTEINA_ANTERIOR=0
	END
	--HALLO EL POSTERIOR
	DECLARE C11 CURSOR  FOR
	SELECT TOP 1 RES_TPR FROM CONTROL
	WHERE RES_GEN=@RES_GEN
	AND RES_NP=@RES_NP
	AND RES_NC>@RES_NC
	ORDER BY RES_NC 
	OPEN C11
	FETCH NEXT FROM C11 INTO @PROTEINA
	CLOSE C11
	DEALLOCATE C11
		IF ( @@FETCH_STATUS=0)
		
		BEGIN --TIENE POSTERIOR
			SET @PROTEINA_POSTERIOR=@PROTEINA
		END
	ELSE
		BEGIN
			SET @PROTEINA_POSTERIOR=0
		END
	--SI TIENE ANTERIOR Y POSTERIOR -> HALLO MEDIA
	IF @PROTEINA_ANTERIOR<>0 AND @PROTEINA_POSTERIOR<>0 
	BEGIN
		SET @PROTEINA=(@PROTEINA_ANTERIOR+@PROTEINA_POSTERIOR)/2
	END
	-- SI NO TIENE ANTERIOR  Y TIENE POSTERIOR -> VALOR DEL SIGUIENTE
	IF @PROTEINA_ANTERIOR=0 AND @PROTEINA_POSTERIOR<>0 
	BEGIN
		SET @PROTEINA=@PROTEINA_POSTERIOR
	END
	-- SI  TIENE ANTERIOR  Y NO TIENE POSTERIOR -> VALOR DEL ANTERIOR
	IF  @PROTEINA_ANTERIOR<>0 AND @PROTEINA_POSTERIOR=0
	BEGIN
		SET @PROTEINA=@PROTEINA_ANTERIOR
	END
	--SI NO TIENE ANTERIOR Y NO TIENE POSTERIOR 
	IF @PROTEINA_ANTERIOR=0 AND @PROTEINA_POSTERIOR=0 
	BEGIN
		SET @PROTEINA=2.0
	END
	UPDATE FALTANTES SET PROTEINAFALTANTE=@PROTEINA
END --DEL PROTEINA<2.00