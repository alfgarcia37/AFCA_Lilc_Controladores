CREATE PROCEDURE [dbo].[PR_RenumeraInsNP]
(@ESTABLO char(7))
AS
-- antes EJECUTO PR_REORDENA_INSEMINACION_PARTO	
		
DECLARE @ID CHAR(14),@NINS INT,@WID CHAR(14),@CONTADOR INT,@WNINS INT
declare @IDP CHAR(14),@NP INT,@FINS SMALLDATETIME,@WFINS SMALLDATETIME,@FPARTO SMALLDATETIME
declare @Registros real

/*ELIMINO DUPLICADOS*/
IF @ESTABLO<>'*'
BEGIN
	declare C1 cursor LOCAL SCROLL OPTIMISTIC FOR
	select max(id),max(np),MAX(FINSEMINACION)
	from inseminaciones
	where establo=@ESTABLO
	group by id,np,FINSEMINACION
	having count(*)>1
END
ELSE
BEGIN
	declare C1 cursor LOCAL SCROLL OPTIMISTIC FOR
	select max(id),max(np),MAX(FINSEMINACION)
	from inseminaciones
	--temporal 
		where fregistroins>='14/05/2018'
	-- fin temporal
	group by id,np,FINSEMINACION
	having count(*)>1
END

OPEN C1 
FETCH NEXT FROM C1 INTO @ID,@NP,@FINS
WHILE (@@FETCH_STATUS=0)
BEGIN
	DECLARE C2 cursor LOCAL SCROLL OPTIMISTIC FOR
	SELECT  ID,NINS FROM INSEMINACIONES
	WHERE ID=@ID
	AND NP=@NP
	/*AND NINS=@NINS*/
	AND FINSEMINACION=@FINS
	
	OPEN C2
	FETCH NEXT FROM C2 INTO @WID,@WNINS
	/*PRINT CONVERT(CHAR,@@FETCH_STATUS) + ' '+@ID*/
	IF @@FETCH_STATUS=0  
		BEGIN
			DELETE INSEMINACIONES
			WHERE CURRENT OF C2
		END
	CLOSE C2
	DEALLOCATE C2
	FETCH NEXT FROM C1 INTO @ID,@NP,@FINS
	set @Registros=@Registros+1
	PRINT 'Número: ' + CONVERT(CHAR,@Registros)
END
CLOSE C1
DEALLOCATE C1

/* DEPURO LOS QUE TIENEN MAL EL NP EN INSEM
SI EXISTE, ACTUALIZO
SI NO EXISTE, O LA FINS  > FP ENTONCES PONGO 0*/

IF @ESTABLO<>'*'
BEGIN
	declare C1 cursor LOCAL SCROLL OPTIMISTIC FOR
	SELECT ID,NP,FINSEMINACION FROM INSEMINACIONES
	WHERE ESTABLO=@ESTABLO
	ORDER BY ID
	FOR UPDATE OF NP
END
ELSE
BEGIN
	declare C1 cursor LOCAL SCROLL OPTIMISTIC FOR
	SELECT ID,NP,FINSEMINACION FROM INSEMINACIONES
	--temporal 
		--where fregistroins>='14/02/2014'
	-- fin temporal
	ORDER BY ID
	FOR UPDATE OF NP
END
set @Registros=0

OPEN C1 
FETCH NEXT FROM C1 INTO @ID,@NP,@FINS
WHILE (@@FETCH_STATUS=0)
BEGIN
	declare C2 cursor LOCAL SCROLL OPTIMISTIC FOR
	SELECT  ID,NP,FPARTO FROM PARTOS
	WHERE ID=@ID
	AND NP=@NP
	OPEN C2
	FETCH NEXT FROM C2 INTO @IDP,@NP,@FPARTO
	--PRINT CONVERT(CHAR,@@FETCH_STATUS) + ' '+@ID
	IF @@FETCH_STATUS<>0  OR @FINS>@FPARTO  /*NO EXISTE PARTO PARA ESE NP*/
		BEGIN
			UPDATE INSEMINACIONES
			SET NP=0
	 		WHERE CURRENT OF C1
	 		
	 		set @Registros=@Registros+1
			PRINT 'NP=0: ' + CONVERT(CHAR,@Registros)
		END
	CLOSE C2
	DEALLOCATE C2
	FETCH NEXT FROM C1 INTO @ID,@NP,@FINS
END
CLOSE C1
DEALLOCATE C1


set @Registros=0
PRINT 'AHORA REORDENO LOS NUMEROS DE INSEMINACION'


DECLARE @MyCounter INT
SET @MyCounter =0

WHILE (@MyCounter < 8)
BEGIN
	IF @ESTABLO<>'*'
		BEGIN
			DECLARE C1 cursor LOCAL SCROLL OPTIMISTIC FOR
			SELECT ID,NINS FROM INSEMINACIONES
			WHERE 
			fregistroins>='14/02/2006'
			--ID='ESPH3901860172' AND
			--and ESTABLO='J391191' or ESTABLO='J397000' 
			 
			
			AND	NP=@MyCounter
			AND ESTABLO=@ESTABLO
			ORDER BY ID,FINSEMINACION
			FOR UPDATE OF NINS
			print 'Pasa por IF @ESTABLO<>'
		END
	ELSE
		BEGIN
			DECLARE C1 cursor LOCAL SCROLL OPTIMISTIC FOR
			SELECT ID,NINS FROM INSEMINACIONES
			WHERE NP=@MyCounter
			--temporal 
				and fregistroins>='14/02/2014'
			-- fin temporal
			ORDER BY ID,FINSEMINACION
			FOR UPDATE OF NINS
		END
		
	
	OPEN C1 
	FETCH NEXT FROM C1 INTO @ID,@NINS
	
	SET @WNINS=0
	SET @WID=@ID
	WHILE (@@FETCH_STATUS=0)
	BEGIN
		IF @WID=@ID 
			BEGIN
				SET @WNINS=@WNINS+1
			END
		ELSE
			BEGIN
	 			SET @WNINS=1
				SET @WID=@ID
			END
		UPDATE INSEMINACIONES
		SET NINS=@WNINS
		 WHERE CURRENT OF C1
		FETCH NEXT FROM C1 INTO @ID,@NINS
		set @Registros=@Registros+1
			PRINT 'Mycounter: ' + CONVERT(CHAR,@MyCounter) + ' vaca ' + @WID + ' ... ' + CONVERT(CHAR,@Registros)
	  END
	
	
	SET @MyCounter = @MyCounter + 1
	CLOSE C1
	DEALLOCATE C1
END --del begin @Mycounter