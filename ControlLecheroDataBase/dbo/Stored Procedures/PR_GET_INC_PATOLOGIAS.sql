CREATE PROCEDURE PR_GET_INC_PATOLOGIAS

(@FDESDE SMALLDATETIME,@FHASTA SMALLDATETIME)

AS

SELECT CONTROLADOR 'ID',TIPOPATOLOGIA 'DET',CAST (COUNT(TIPOPATOLOGIA) AS CHAR(4)) 'PARAM1',0 'PARAM2' FROM PATOLOGIAS
WHERE FREGISTROPATOLOGIA BETWEEN @FDESDE AND @FHASTA
AND TIPOPATOLOGIA>'0'

GROUP BY CONTROLADOR,TIPOPATOLOGIA
ORDER BY CONTROLADOR,TIPOPATOLOGIA