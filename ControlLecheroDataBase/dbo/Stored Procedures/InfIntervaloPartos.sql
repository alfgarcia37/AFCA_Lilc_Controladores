
CREATE PROCEDURE [dbo].[InfIntervaloPartos]
 (@ESTABLO char(7),
@Desde smalldatetime,
@Hasta smalldatetime ) 
AS
--TOMO SOLO LOS PARTOS DIFERENCIA<730 DIAS
DECLARE @GEN CHAR(14),@NP  INT,@FPARTO SMALLDATETIME,@FPARTO_ANTERIOR SMALLDATETIME,@TOTALDIAS REAL,@NUM_VACAS REAL,@A INT
DECLARE @TOTALDIAS2 REAL,@NUM_VACAS2 REAL,@TOTALDIAS3 REAL,@NUM_VACAS3 REAL
IF @Establo='*'
BEGIN
	DECLARE C1 CURSOR FOR
	SELECT ID,NP,FPARTO FROM PARTOS
	WHERE 
	 NP>1
	AND FPARTO BETWEEN @Desde AND @Hasta
	-- lo hago par las pasiegas
	--SELECT ID,NP,FPARTO FROM PARTOS,maestro
	--WHERE 
	--Maes_Gen=ID
	--and maes_raza='62'
	-- and NP>1
	--AND FPARTO BETWEEN @Desde AND @Hasta
	-- fin  pasiegas

	SET @TOTALDIAS=0;SET @TOTALDIAS2=0;SET @TOTALDIAS3=0;
	SET @NUM_VACAS=0;SET @NUM_VACAS2=0;SET @NUM_VACAS3=0
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @GEN,@NP,@FPARTO
	WHILE (@@FETCH_STATUS=0)
	  BEGIN
		DECLARE C2 CURSOR FOR
		SELECT FPARTO FROM PARTOS
		WHERE 
		ID=@GEN
		AND  NP=@NP-1
		
		
		OPEN  C2 
		FETCH NEXT FROM C2 INTO @FPARTO_ANTERIOR 
		IF @@FETCH_STATUS=0 AND DATEDIFF(DAY,@FPARTO_ANTERIOR,@FPARTO)<730
		BEGIN
			IF @NP=2
				BEGIN
					SET @TOTALDIAS2=@TOTALDIAS2+DATEDIFF(DAY,@FPARTO_ANTERIOR,@FPARTO)
					SET @NUM_VACAS2=@NUM_VACAS2+1
				END
			IF @NP=3
				BEGIN
					SET @TOTALDIAS3=@TOTALDIAS3+DATEDIFF(DAY,@FPARTO_ANTERIOR,@FPARTO)
					SET @NUM_VACAS3=@NUM_VACAS3+1
				END
			IF @NP>3
				BEGIN
					SET @TOTALDIAS=@TOTALDIAS+DATEDIFF(DAY,@FPARTO_ANTERIOR,@FPARTO)
					SET @NUM_VACAS=@NUM_VACAS+1
				END
			
		END
		
			CLOSE C2
		DEALLOCATE C2
		
		FETCH NEXT FROM C1 INTO  @GEN,@NP,@FPARTO
	
	 END
	
	CLOSE C1
	DEALLOCATE C1
	
	SELECT 1 AS ID,@TOTALDIAS2 AS DET,@NUM_VACAS2 AS PARAM1,0 AS PARAM2
	UNION SELECT 2 AS ID,@TOTALDIAS3 AS DET,@NUM_VACAS3 AS PARAM1,0 AS PARAM2
	UNION SELECT 3 AS ID,@TOTALDIAS AS DET,@NUM_VACAS AS PARAM1,0 AS PARAM2
END
ELSE
BEGIN
	DECLARE C1 CURSOR FOR
	SELECT ID,NP,FPARTO FROM PARTOS,Maestro
	WHERE 
	ESTABLO=MAES_TIT
	AND ESTABLO=@ESTABLO
	AND FPARTO BETWEEN @Desde AND @Hasta
	AND ID=MAES_GEN
	--AND MAES_GEN<>'0'
	AND NP>1

	SET @TOTALDIAS=0;SET @TOTALDIAS2=0;SET @TOTALDIAS3=0;
	SET @NUM_VACAS=0;SET @NUM_VACAS2=0;SET @NUM_VACAS3=0
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @GEN,@NP,@FPARTO
	WHILE (@@FETCH_STATUS=0) 
	  BEGIN
		DECLARE C2 CURSOR FOR
		SELECT FPARTO FROM PARTOS
		WHERE 
		ID=@GEN
		AND  NP=@NP-1
		
		
		OPEN  C2 
		FETCH NEXT FROM C2 INTO @FPARTO_ANTERIOR 
		IF @@FETCH_STATUS=0 AND DATEDIFF(DAY,@FPARTO_ANTERIOR,@FPARTO)<730
		BEGIN
			IF @NP=2
				BEGIN
					SET @TOTALDIAS2=@TOTALDIAS2+DATEDIFF(DAY,@FPARTO_ANTERIOR,@FPARTO)
					SET @NUM_VACAS2=@NUM_VACAS2+1
				END
			IF @NP=3
				BEGIN
					SET @TOTALDIAS3=@TOTALDIAS3+DATEDIFF(DAY,@FPARTO_ANTERIOR,@FPARTO)
					SET @NUM_VACAS3=@NUM_VACAS3+1
				END
			IF @NP>3
				BEGIN
					SET @TOTALDIAS=@TOTALDIAS+DATEDIFF(DAY,@FPARTO_ANTERIOR,@FPARTO)
					SET @NUM_VACAS=@NUM_VACAS+1
				END
			
		END
		
			CLOSE C2
		DEALLOCATE C2
		
		FETCH NEXT FROM C1 INTO  @GEN,@NP,@FPARTO
	
	 END
	
	CLOSE C1
	DEALLOCATE C1
	
	SELECT 1 AS ID,@TOTALDIAS2 AS DET,@NUM_VACAS2 AS PARAM1,0 AS PARAM2
	UNION SELECT 2 AS ID,@TOTALDIAS3 AS DET,@NUM_VACAS3 AS PARAM1,0 AS PARAM2
	UNION SELECT 3 AS ID,@TOTALDIAS AS DET,@NUM_VACAS AS PARAM1,0 AS PARAM2

END