
CREATE PROCEDURE [dbo].[BORRARDUPLICADOS]  AS

DECLARE @BARRAS CHAR(14),@WBARRAS CHAR(14),@CONTADOR INT,@FP CHAR(10),@WFP CHAR(10),@ESTABLO CHAR(7),@WESTABLO CHAR(7)



DECLARE C1 CURSOR LOCAL SCROLL OPTIMISTIC FOR
SELECT ESTABLO,BARRAS
FROM rcs
WHERE   ltrim(rtrim(BARRAS))<>''
GROUP BY ESTABLO,BARRAS
HAVING COUNT(*)>1
OPEN C1 
FETCH NEXT FROM C1 INTO @ESTABLO,@BARRAS
WHILE (@@FETCH_STATUS=0)
BEGIN
	DECLARE C2 CURSOR LOCAL SCROLL 
	OPTIMISTIC 
	DYNAMIC
	FOR
	SELECT ESTABLO,BARRAS
	FROM rcs
	WHERE ESTABLO= @ESTABLO AND BARRAS=@BARRAS
	
	
	
	OPEN C2
	FETCH NEXT FROM C2 INTO @WESTABLO,@WBARRAS
	/*PRINT CONVERT(CHAR,@@FETCH_STATUS) + ' '+@BARRAS*/
	IF @@FETCH_STATUS=0  
		BEGIN
			DELETE rcs
			WHERE CURRENT OF C2
		END
	CLOSE C2
	DEALLOCATE C2
	FETCH NEXT FROM C1 INTO @ESTABLO,@BARRAS
END
CLOSE C1
DEALLOCATE C1