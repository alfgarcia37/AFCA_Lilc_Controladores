CREATE PROCEDURE  [dbo].[PR_CONTROL_FALTANTE_KILOS]
(@RES_GEN CHAR(14),
@RES_NP INT,
@RES_NC INT,
@RES_KILOS REAL

)
AS 

DECLARE @KILOS REAL
DECLARE @KILOS_ANTERIOR REAL
DECLARE @KILOS_POSTERIOR REAL

PRINT CAST( @RES_NP AS CHAR(2))
PRINT CAST( @RES_NC AS CHAR(2))
PRINT CAST( @RES_KILOS AS CHAR(12))

--MIRO FALTANTES KILOS

	UPDATE FALTANTES SET KILOSFALTANTE=@RES_KILOS--POR DEFECTO (SIGNIFICA QUE ESTA CORRECTO, NO HAY ANTERIOR
	--HALLO EL ANTERIOR..............................................................
	DECLARE C11 CURSOR  FOR
	SELECT TOP 1 (RES_KLAM + RES_KLPM)  FROM CONTROL
	WHERE RES_GEN=@RES_GEN
	AND RES_NP=@RES_NP
	AND RES_NC<@RES_NC
	--ORDER BY RES_NC
	ORDER BY RES_NC desc --AGC 04/04/2014
	OPEN C11
	FETCH NEXT FROM C11 INTO @KILOS_ANTERIOR
	CLOSE C11
	DEALLOCATE C11

	IF ( @@FETCH_STATUS=0)
	
	BEGIN --TIENE ANTERIOR > COMPRUEBO QUE LA DIFERENCIA NO SEA MENOR DEL 50% DEL CONTROL ANTERIOR 3.1.5.b del RD CL
		IF @RES_KILOS < @KILOS_ANTERIOR/2
		BEGIN --AHORA MIRO SI TIENE POSTERIOR
		PRINT 'KILOS ANTERIOR ' + CAST( @KILOS_ANTERIOR AS CHAR(12))
			DECLARE C11 CURSOR  FOR
			SELECT TOP 1 (RES_KLAM + RES_KLPM) FROM CONTROL
			WHERE RES_GEN=@RES_GEN
			AND RES_NP=@RES_NP
			AND RES_NC>@RES_NC
			ORDER BY RES_NC DESC
			OPEN C11
			FETCH NEXT FROM C11 INTO @KILOS_POSTERIOR
			CLOSE C11
			DEALLOCATE C11
				IF ( @@FETCH_STATUS=0)
		
				BEGIN --TIENE POSTERIOR
					SET @KILOS=(@KILOS_ANTERIOR + @KILOS_POSTERIOR)/2
				END
				ELSE --NO TIENE POSTERIOR
				BEGIN
					SET @KILOS=@KILOS_ANTERIOR -- PONGO EL ANTERIOR
				END
		UPDATE FALTANTES SET KILOSFALTANTE=@KILOS
		END -- DEL AHORA MIRO
	
	END --DEL TIENE ANTERIOR