CREATE PROCEDURE PR_ActualizaMarcaSicma
(@datDESDE smalldatetime,@datHASTA smalldatetime)
AS

	
DECLARE @ID CHAR(14),@MADRE_ESP CHAR(14),@MADRE_SAN CHAR(14),@FNACIMIENTO SMALLDATETIME,@FPARTO SMALLDATETIME,@FMARCA SMALLDATETIME

	DECLARE C1 CURSOR LOCAL SCROLL OPTIMISTIC FOR
	SELECT TERNERO,FNACIMIENTO,NUMAD1,FMARCA--NUMAD1 SERA SIEMPRE ESP, PORQUE SE REGISTRA ASI
	FROM REGGEN..TERNEROS_SICMA,REGGEN..ANIMALES
	WHERE FMARCA BETWEEN @datDESDE AND @datHASTA
	AND TERNERO=CODIGOIDENTIF
	--AND MARCA='*'
	
OPEN C1 
FETCH NEXT FROM C1 INTO @ID,@FNACIMIENTO,@MADRE_ESP,@FMARCA --@MADRE EN TEORIA SIEMPRE ES ESP..(POR FUNCIONAMIENTO DE REGISTRO)
WHILE (@@FETCH_STATUS=0)
BEGIN
	DECLARE C2 cursor LOCAL SCROLL OPTIMISTIC FOR
	SELECT  CODIGOIDENTIF FROM REGGEN..ANIMALES
	WHERE (PAIS+SEXO+PROANI+NUMERO)=@MADRE_ESP
	OPEN C2
	FETCH NEXT FROM C2 INTO @MADRE_SAN
	
	IF @@FETCH_STATUS=0  --.....VOY A REGISTRO ....LA MADRE SIEMPRE TENDRA ESP. TENGO QUE RECUPERAR TB EL SANITARIO PQ. NO SE COMO ESTA EN CL (CON ESP O SANITARIO)
		BEGIN
			UPDATE PARTOSSICMA
			SET FMARCA=@FMARCA
			WHERE (ID=@MADRE_ESP OR ID=@MADRE_SAN)
			AND FPARTOSICMA=@FNACIMIENTO
		END
				
	CLOSE C2
	DEALLOCATE C2
	FETCH NEXT FROM C1 INTO @ID,@FNACIMIENTO,@MADRE_ESP,@FMARCA
END
CLOSE C1
DEALLOCATE C1