
CREATE PROCEDURE PR_RES_FCTR_NULL AS

DECLARE @FCTR SMALLDATETIME,@FPREV SMALLDATETIME,@ESTABLO CHAR(7),@FREAL SMALLDATETIME


DECLARE C1 CURSOR LOCAL SCROLL OPTIMISTIC FOR

	SELECT RES_FCTR,RES_FPREV,RES_TIT FROM CONTROL
	WHERE RES_FCTR IS NULL
	AND RES_AB='A'
	AND RES_FP  BETWEEN '01/01/06' AND '31/12/2007'
	FOR UPDATE OF RES_FCTR
			
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @FCTR,@FPREV,@ESTABLO
	
WHILE (@@FETCH_STATUS=0)
  BEGIN
	DECLARE C2 CURSOR FOR 
		SELECT FREAL FROM LECTURASFINALIZADAS
		WHERE ESTABLO=@ESTABLO
		AND FPREVISTA=@FPREV
	OPEN  C2
	FETCH NEXT FROM C2 INTO @FREAL
	CLOSE C2
	DEALLOCATE C2
	
	UPDATE CONTROL
	SET RES_FCTR=@FREAL
	WHERE CURRENT OF  C1

	FETCH NEXT FROM C1 INTO @FCTR,@FPREV,@ESTABLO
 END

CLOSE C1
DEALLOCATE C1
