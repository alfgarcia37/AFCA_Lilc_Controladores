CREATE PROCEDURE PR_ACTUALIZA_CBA_A_09

(@FDESDE SMALLDATETIME,@FHASTA SMALLDATETIME)

AS
	DECLARE @RES_GEN CHAR(14),@RES_FBA SMALLDATETIME,@RES_CBA CHAR(2),@RES_NP AS SMALLINT,@RES_NC SMALLINT,@TOTAL SMALLINT

	DECLARE C1 CURSOR LOCAL SCROLL OPTIMISTIC FOR
	SELECT RES_GEN,RES_NP,RES_NC,RES_FBA,RES_CBA
	FROM CONTROL
	WHERE  RES_FPREV BETWEEN @FDESDE AND @FHASTA
	AND RES_AB='B'
	FOR UPDATE OF RES_CBA
	
OPEN C1 
FETCH NEXT FROM C1 INTO @RES_GEN,@RES_NP, @RES_NC,@RES_FBA,@RES_CBA
WHILE (@@FETCH_STATUS=0)
BEGIN
	DECLARE C2 CURSOR LOCAL SCROLL OPTIMISTIC FOR
	SELECT COUNT(*) FROM CONTROL
	WHERE  RES_GEN=@RES_GEN
	AND RES_AB='A'
	AND RES_NP=@RES_NP
	AND RES_NC=@RES_NC
	OPEN C2
	FETCH NEXT FROM C2 INTO @TOTAL
	IF @TOTAL>0
	BEGIN
		UPDATE CONTROL
		SET RES_CBA='09'
		 WHERE CURRENT OF C1
		
	END
	CLOSE C2
	DEALLOCATE C2
	FETCH NEXT FROM C1 INTO @RES_GEN, @RES_NP,@RES_NC,@RES_FBA,@RES_CBA
END
CLOSE C1
DEALLOCATE C1