
CREATE PROCEDURE [dbo].[BORRARDUPLICADOS_VELORD]

AS

DECLARE @ID CHAR(14),@WID CHAR(14),@CONTADOR INT,@FP CHAR(10),@WFP CHAR(10),@ESTABLO CHAR(7),@WESTABLO CHAR(7),@NP INT,@NC INT

	DECLARE C1 CURSOR LOCAL SCROLL OPTIMISTIC FOR
	SELECT MAX(RES_GEN),MAX(RES_NP),MIN(RES_NC)  FROM CONTROL
	WHERE RES_VELORD<>'' AND RES_VELORD IS NOT NULL
	AND RES_tit='J390306'
	--AND RES_FPREV>'01/01/2008'---kkkkkkkkkkk
	GROUP BY RES_GEN,RES_NP
	OPEN C1 
 
FETCH NEXT FROM C1 INTO @ID,@NP,@NC
WHILE (@@FETCH_STATUS=0)
BEGIN
	UPDATE CONTROL
	SET RES_VELORD='' 
	WHERE RES_GEN=@ID
	AND RES_NP=@NP
	AND RES_NC>@NC
	FETCH NEXT FROM C1 INTO @ID,@NP,@NC
END
CLOSE C1
DEALLOCATE C1
