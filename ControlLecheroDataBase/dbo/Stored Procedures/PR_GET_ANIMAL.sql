CREATE PROCEDURE [dbo].[PR_GET_ANIMAL] 
(
		@strEstablo char(7),
		@strRES CHAR(14)
	)
AS

IF @strEstablo IS NULL 
BEGIN

SELECT ID = CASE WHEN (NUMERO >01868130 OR PROANI='PA' OR PROANI='PS' )   THEN CODIGOIdentif 
ELSE (PAIS+SEXO+PROANI+NUMERO) END,
NOMBRE as det,
AÑONA1,MESNA1,DIANA1
FROM RegGen..ANIMALES
Where  Sexo='H'
and CASE WHEN  (NUMERO >01868130 OR PROANI='PA'  OR PROANI='PS')     THEN CODIGOIdentif
ELSE (PAIS+SEXO+PROANI+NUMERO) END=@strRES
END
ELSE
BEGIN

SELECT ID = CASE WHEN (NUMERO >01868130 OR PROANI='PA'  OR PROANI='PS')   THEN CODIGOIdentif 
ELSE (PAIS+SEXO+PROANI+NUMERO) END,
NOMBRE as det,
AÑONA1,MESNA1,DIANA1
FROM RegGen..ANIMALES
Where GANPRO = @strEstablo
--and NUMLAC=0
--and AÑOBAJ=0
and Sexo='H'
and CASE WHEN  (NUMERO >01868130 OR PROANI='PA'  OR PROANI='PS')     THEN CODIGOIdentif
ELSE (PAIS+SEXO+PROANI+NUMERO) END=@strRES

END