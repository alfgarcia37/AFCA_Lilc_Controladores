CREATE PROCEDURE [dbo].[PR_ACTUALIZA_ANALITICA_0]

(@FPREVISTA SMALLDATETIME,@ESTABLO CHAR(7))

AS
	DECLARE @RES_GEN CHAR(14),@RES_TGR REAL,@RES_TPR REAL,@RES_TLA REAL,@RES_INC CHAR(2)

	DECLARE C1 CURSOR LOCAL SCROLL OPTIMISTIC FOR
	SELECT RES_GEN,RES_TGR,RES_TPR,RES_TLA ,RES_INCRECAL
	FROM CONTROL,LECTURASFINALIZADAS
	WHERE ESTABLO=@ESTABLO
	AND ESTABLO=RES_TIT
	AND FPREVISTA=@FPREVISTA
	AND FPREVISTA=RES_FPREV
	AND RES_AB='A'
	AND CORREGIDO='1'
	AND ANALITICA='1'
	AND INFORME='1'
	AND (RES_TGR=0 OR RES_TPR=0)
	FOR UPDATE OF RES_GEN,RES_TGR,RES_TPR,RES_TLA,RES_INCRECAL
	
OPEN C1 
FETCH NEXT FROM C1 INTO @RES_GEN, @RES_TGR,@RES_TPR,@RES_TLA,@RES_INC
WHILE (@@FETCH_STATUS=0)
BEGIN
	UPDATE CONTROL
	SET 
	--RES_TGR=3.03 + CAST(RIGHT(@RES_GEN,2)  AS REAL)/100,
	--RES_TPR=2.8 + CAST(RIGHT(@RES_GEN,2)  AS REAL)/100,
	--RES_TLA=4.05 + CAST(RIGHT(@RES_GEN,2)  AS REAL)/100,
		RES_INCRECAL='02'
	 WHERE CURRENT OF C1
	FETCH NEXT FROM C1 INTO @RES_GEN,@RES_TGR,@RES_TPR,@RES_TLA,@RES_INC
END
CLOSE C1
DEALLOCATE C1