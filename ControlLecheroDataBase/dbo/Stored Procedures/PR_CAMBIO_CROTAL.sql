CREATE PROCEDURE [dbo].[PR_CAMBIO_CROTAL]

(@ACTUAL_CROTAL CHAR(14),@NEW_CROTAL CHAR(14))

AS
	
DECLARE @MAES_TIT CHAR(7),@MAES_GEN CHAR(14),@CONTROLADOR INT,@DIB AS CHAR(14)
DECLARE @TIT CHAR(7),@GEN CHAR(14),@NP INT,@NC INT,@FP SMALLDATETIME

--AHORA ACTUALIZO LOS VALORES DE TODAS LAS TABLAS

		--ACTUALIZO MAESTRO
			UPDATE MAESTRO
			SET MAES_GEN=@NEW_CROTAL
			WHERE MAES_GEN=@ACTUAL_CROTAL
		--ACTUALIZO CONTROL
			UPDATE CONTROL
			SET RES_GEN=@NEW_CROTAL	
			WHERE RES_GEN=@ACTUAL_CROTAL
		--ACTUALIZO LACTACIONES
			UPDATE LACTACIONES
			SET RES=@NEW_CROTAL
			WHERE RES=@ACTUAL_CROTAL
		--ACTUALIZO INSEMINACIONES
			UPDATE INSEMINACIONES
			SET ID=@NEW_CROTAL	
			WHERE ID=@ACTUAL_CROTAL
		--ACTUALIZO PARTOS
			UPDATE PARTOS
			SET ID=@NEW_CROTAL	
			WHERE ID=@ACTUAL_CROTAL
		--ACTUALIZO CELOS
			UPDATE CELOS
			SET VACA=@NEW_CROTAL	
			WHERE VACA=@ACTUAL_CROTAL
		--ACTUALIZO INCIDENCIAS GENERALES
			UPDATE INCIDENCIASGENERALES
			SET RES=@NEW_CROTAL	
			WHERE RES=@ACTUAL_CROTAL
		--ACTUALIZO PATLOGIAS
			UPDATE PATOLOGIAS
			SET RES=@NEW_CROTAL
			WHERE RES=@ACTUAL_CROTAL
		-- GRABO EN INCIDENCIAS GENERALES
		
		INSERT INTO IncidenciasGenerales 
		(DET,Tipo,FechaIncid)
		VALUES (@ACTUAL_CROTAL + '>' + @NEW_CROTAL,'04',GETDATE())		