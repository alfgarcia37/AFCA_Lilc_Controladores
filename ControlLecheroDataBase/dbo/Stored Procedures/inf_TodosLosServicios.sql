





CREATE PROCEDURE [dbo].[inf%TodosLosServicios] 

(
	@Establo char(7),
	@NumParto int
	
		)
AS
IF @Establo<>''
BEGIN
	IF @NumParto=3 
	BEGIN
		SELECT count(*) AS NUMEROVACAS
		FROM MAESTRO,PARTOS P,INSEMINACIONES I
		WHERE
		MAES_TIT=@Establo
		AND MAES_GEN=P.ID
		AND P.NP>2 
		and P.ID=I.ID AND P.NP=I.NP
		--AND I.NINS=1
		AND ((P.ID=I.ID AND P.NP=I.NP) OR I.FECUNDANTE='1')
	
	END
	IF @NumParto<>99 AND  @NumParto<>3 
	BEGIN
		SELECT count(*) AS NUMEROVACAS
		FROM MAESTRO,PARTOS P,INSEMINACIONES I
		WHERE
		MAES_TIT=@Establo
		AND MAES_GEN=P.ID
		AND P.NP=@numparto
		and P.ID=I.ID AND P.NP=I.NP
		--AND I.NINS=1
		AND ((P.ID=I.ID AND P.NP=I.NP) OR I.FECUNDANTE='1')
	END
	
	IF @NumParto=99
	BEGIN
		SELECT count(*) AS NUMEROVACAS
		FROM MAESTRO,PARTOS P,INSEMINACIONES I
		WHERE
		MAES_TIT=@Establo
		AND MAES_GEN=P.ID
		and P.ID=I.ID AND P.NP=I.NP
		--AND I.NINS=1
		AND ((P.ID=I.ID AND P.NP=I.NP) OR I.FECUNDANTE='1')
	END
END
ELSE
BEGIN
IF @NumParto=3 
	BEGIN
		SELECT count(*) AS NUMEROVACAS
		FROM MAESTRO,PARTOS P,INSEMINACIONES I
		WHERE
		MAES_GEN=P.ID
		AND P.NP>2 
		and P.ID=I.ID AND P.NP=I.NP
		--AND I.NINS=1
		AND ((P.ID=I.ID AND P.NP=I.NP) OR I.FECUNDANTE='1')
	
	END
	IF @NumParto<>99 AND  @NumParto<>3 
	BEGIN
		SELECT count(*) AS NUMEROVACAS
		FROM MAESTRO,PARTOS P,INSEMINACIONES I
		WHERE
		MAES_GEN=P.ID
		AND P.NP=@numparto
		and P.ID=I.ID AND P.NP=I.NP
		--AND I.NINS=1
		AND ((P.ID=I.ID AND P.NP=I.NP) OR I.FECUNDANTE='1')
	END
	
	IF @NumParto=99
	BEGIN
		SELECT count(*) AS NUMEROVACAS
		FROM MAESTRO,PARTOS P,INSEMINACIONES I
		WHERE
		MAES_GEN=P.ID
		and P.ID=I.ID AND P.NP=I.NP
		--AND I.NINS=1
		AND ((P.ID=I.ID AND P.NP=I.NP) OR I.FECUNDANTE='1')
	END
END





