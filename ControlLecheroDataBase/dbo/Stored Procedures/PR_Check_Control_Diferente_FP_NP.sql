CREATE PROCEDURE PR_Check_Control_Diferente_FP_NP

(@datFPREV smalldatetime,@RES CHAR(14))

AS
--DECLARE @MAES_TIT CHAR(7),@MAES_GEN CHAR(14),@MAES_FP SMALLDATETIME,@MAES_NP INT,@MAES_NC INT,@MAES_ESTADO CHAR(1)
DECLARE @RES_TIT CHAR(7),@RES_GEN CHAR(14),@RES_NP INT,@RES_NC INT,@RES_FP SMALLDATETIME
DECLARE @WRES_TIT CHAR(7),@WRES_GEN CHAR(14),@WRES_NP INT,@WRES_NC INT,@WRES_FP SMALLDATETIME

DELETE VACASTEMP
IF @RES='*'
BEGIN
	DECLARE C1 CURSOR  SCROLL FOR
	SELECT RES_GEN,RES_NP,RES_FP
	FROM CONTROL
	WHERE RES_FPREV>@datFPREV
	--AND RES_TIT='J390452'
	ORDER BY RES_GEN,RES_NP,RES_NC,RES_FP 
	OPEN C1
END
ELSE
BEGIN
	DECLARE C1 CURSOR  SCROLL FOR
	SELECT RES_GEN,RES_NP,RES_FP
	FROM CONTROL
	WHERE  RES_GEN=@RES
	ORDER BY RES_GEN,RES_NP,RES_NC,RES_FP 
	OPEN C1
END
	FETCH NEXT FROM C1 INTO @RES_GEN,@RES_NP,@RES_FP
	SET @WRES_GEN=@RES_GEN
	SET @WRES_NP=@RES_NP
	SET @WRES_FP=@RES_FP

	WHILE ( @@FETCH_STATUS=0)
	BEGIN
		FETCH NEXT FROM C1 INTO @RES_GEN,@RES_NP,@RES_FP
			IF @RES_GEN=@WRES_GEN AND  @RES_NP=@WRES_NP
			BEGIN
				IF  not(@RES_FP=@WRES_FP)
				BEGIN
					
					INSERT INTO VACASTEMP (ESTABLOMAES,ID ,MAES_FP,MAES_NP,MAES_NC,ESTABLOCONTROL,RES_NP,RES_NC,RES_FPREV,CONTROLADOR)
					VALUES('X',@RES_GEN,@RES_FP,@RES_NP,0,'X',@WRES_NP,0,@WRES_FP,0)
				END
			END
		SET @WRES_GEN=@RES_GEN
		SET @WRES_NP=@RES_NP
		SET @WRES_FP=@RES_FP
	END --DEL WHILE
	--==========================================================================
	--   AHORA VUELVO A RECORRER EL CURSOR PARA VER LOS NP DIFERENTES
	--==========================================================================
	FETCH FIRST FROM C1 INTO @RES_GEN,@RES_NP,@RES_FP
	SET @WRES_GEN=@RES_GEN
	SET @WRES_NP=@RES_NP
	SET @WRES_FP=@RES_FP

	WHILE ( @@FETCH_STATUS=0)
	BEGIN
		FETCH NEXT FROM C1 INTO @RES_GEN,@RES_NP,@RES_FP
			IF @RES_GEN=@WRES_GEN AND  @RES_FP=@WRES_FP
			BEGIN
				IF  not(@RES_NP=@WRES_NP)
				BEGIN
					--PRINT @RES_GEN + cast(@RES_FP
					INSERT INTO VACASTEMP (ESTABLOMAES,ID ,MAES_FP,MAES_NP,MAES_NC,ESTABLOCONTROL,RES_NP,RES_NC,RES_FPREV,CONTROLADOR)
					VALUES('X',@RES_GEN,@RES_FP,@RES_NP,0,'X',@WRES_NP,0,@WRES_FP,0)
				END
			END

		SET @WRES_GEN=@RES_GEN
		SET @WRES_NP=@RES_NP
		SET @WRES_FP=@RES_FP
				
	END --DEL WHILE

CLOSE C1
DEALLOCATE C1