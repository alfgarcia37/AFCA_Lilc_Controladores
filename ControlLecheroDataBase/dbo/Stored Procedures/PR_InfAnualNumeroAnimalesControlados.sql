






CREATE PROCEDURE PR_InfAnualNumeroAnimalesControlados

 (@ESTABLO char(7),
@DESDE SMALLDATETIME,@HASTA SMALLDATETIME ) 

AS


DECLARE @NUM_ESTABLOS INT,@TOTAL_VACAS REAL,@TAMANOESTABLO char(1)
DECLARE @NUM_VACAS REAL,@NUM_VACAS2 REAL,@NUM_VACAS3 REAL,@RES CHAR(14)

IF @ESTABLO<>' '
BEGIN
	
	/*===================VACAS CONTROLADAS EN ESTABLO=======================*/
	DECLARE C1 CURSOR FOR 
	SELECT COUNT(*)
	FROM LECTURASFINALIZADAS,LECTURASCONTROL
	WHERE 
	LECTURASFINALIZADAS.ESTABLO=@ESTABLO
	AND LECTURASFINALIZADAS.ESTABLO=LECTURASCONTROL.ESTABLO
	AND FBAJA IS NULL
	AND LECTURASFINALIZADAS.FPREVISTA BETWEEN @DESDE AND @HASTA
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @NUM_ESTABLOS
	CLOSE C1
	DEALLOCATE C1
	
	DECLARE C2 cursor  FOR
	SELECT COUNT(*)
	FROM CONTROL
	WHERE 
	RES_TIT=@ESTABLO
	AND RES_FPREV BETWEEN @DESDE AND @HASTA
	AND RES_AB='A'
	
	OPEN C2
	FETCH NEXT FROM C2 INTO @NUM_VACAS2
	CLOSE C2
	DEALLOCATE C2

	SELECT @NUM_VACAS AS NUMVACAS,(@NUM_VACAS2/@NUM_ESTABLOS) AS NUMVACAS2
	
END
ELSE
	BEGIN
	
	/*===================VACAS CONTROLADAS EN CANTABRIA=======================*/
	DECLARE C1 CURSOR FOR 
	SELECT COUNT(*)
	FROM LECTURASFINALIZADAS,LECTURASCONTROL
	WHERE 
	LECTURASFINALIZADAS.ESTABLO=LECTURASCONTROL.ESTABLO
	AND FBAJA IS NULL
	AND LECTURASFINALIZADAS.FPREVISTA BETWEEN @DESDE AND @HASTA
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @NUM_ESTABLOS /* =NUM LECTURAS*/
	CLOSE C1
	DEALLOCATE C1
	
	DECLARE C2 cursor  FOR
	SELECT COUNT(*)
	FROM CONTROL,LECTURASFINALIZADAS,LECTURASCONTROL
	WHERE 
	RES_TIT=LECTURASFINALIZADAS.ESTABLO
	AND RES_TIT=LECTURASCONTROL.ESTABLO
	AND RES_FPREV=LECTURASFINALIZADAS.FPREVISTA
	AND RES_FPREV BETWEEN @DESDE AND @HASTA
	AND RES_AB='A'
	
	OPEN C2
	FETCH NEXT FROM C2 INTO @NUM_VACAS
		UPDATE INFORMEANUAL SET VALOR=(@NUM_VACAS/@NUM_ESTABLOS)
		WHERE GRUPO='CANTABRIA' 
		AND CONCEPTO='MED VACAS CONTROLADAS'
		CLOSE C2
		DEALLOCATE C2
	
	/*========VACAS CONTROLADAS EN TRAMOS================*/
	
	DECLARE C1 cursor for 
	
	SELECT TAMANOESTABLO, COUNT(*)
	FROM LECTURASFINALIZADAS,LECTURASCONTROL
	WHERE 
	LECTURASFINALIZADAS.ESTABLO=LECTURASCONTROL.ESTABLO
	AND FBAJA IS NULL
	AND LECTURASFINALIZADAS.FPREVISTA BETWEEN @DESDE AND @HASTA
	AND TAMANOESTABLO IS NOT NULL		
	GROUP BY TAMANOESTABLO
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	WHILE (@@FETCH_STATUS=0)
	BEGIN
		DECLARE C2 cursor  FOR
		SELECT COUNT(*)
		FROM CONTROL,LECTURASFINALIZADAS,LECTURASCONTROL
		WHERE 
		RES_TIT=LECTURASFINALIZADAS.ESTABLO
		AND RES_TIT=LECTURASCONTROL.ESTABLO
		AND FBAJA IS NULL
		AND RES_FPREV=LECTURASFINALIZADAS.FPREVISTA
		AND RES_FPREV BETWEEN @DESDE AND @HASTA
		AND RES_AB='A'
		AND TAMANOESTABLO=@TAMANOESTABLO
		
		
		OPEN C2
		FETCH NEXT FROM C2 INTO @TOTAL_VACAS
		
			UPDATE INFORMEANUAL SET VALOR=(@TOTAL_VACAS/@NUM_ESTABLOS)
			WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
			AND CONCEPTO='MED VACAS CONTROLADAS'
			
			CLOSE C2
			DEALLOCATE C2
		FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	END
	CLOSE C1
	DEALLOCATE C1
END






