
CREATE PROCEDURE [dbo].[PR_MAESTRO_ULT_LECTURA] AS

DECLARE @FPREV SMALLDATETIME,@ESTABLO CHAR(7),@CONTADOR REAL
DECLARE @RES_TIT CHAR(7),@RES_GEN CHAR(14),@RES_NP INT,@RES_NC INT,@RES_FP SMALLDATETIME,@RES_AB CHAR(1)
DECLARE @MAES_TIT CHAR(7),@MAES_GEN CHAR(14),@MAES_NP INT,@MAES_NC INT,@MAES_FP SMALLDATETIME,@MAES_ESTADO CHAR(1)
SET @CONTADOR= 1

DECLARE C1 cursor for 

SELECT MAX(Fprevista) AS FPrevista,MAX(Establo) as ID
FROM LECTURASFINALIZADAS
--WHERE Establo='J390162'
WHERE  FPREVISTA>='01/02/2014'
--Where NumControler IN (900,92,94,96 ,97)
GROUP by Establo order by fprevista desc


OPEN  C1 
FETCH NEXT FROM C1 INTO @FPREV,@ESTABLO

WHILE (@@FETCH_STATUS=0)
BEGIN
	DECLARE C2 cursor for 

	SELECT  RES_TIT,RES_GEN,RES_NP,RES_NC,RES_FP,RES_AB FROM  CONTROL
	WHERE RES_TIT=@ESTABLO
	AND RES_TIT=@ESTABLO
	AND RES_FPREV=@FPREV
	order by res_gen,res_np
	--and res_nc=1

	OPEN  C2 
	FETCH NEXT FROM C2 INTO @RES_TIT,@RES_GEN,@RES_NP,@RES_NC,@RES_FP,@RES_AB
	WHILE (@@FETCH_STATUS=0)
	BEGIN
		DECLARE C3 cursor for 
	
		SELECT  MAES_TIT,MAES_GEN,MAES_NP,MAES_NC,MAES_FP,MAES_ESTADO FROM  MAESTRO
		WHERE MAES_TIT=@ESTABLO
		AND MAES_TIT=@ESTABLO
		AND MAES_GEN=@RES_GEN
		FOR UPDATE
	
		OPEN  C3 
		FETCH NEXT FROM C3 INTO @MAES_TIT,@MAES_GEN,@MAES_NP,@MAES_NC,@MAES_FP,@MAES_ESTADO
			--IF (@@FETCH_STATUS<>0) /* NO EXISTE*/
				--BEGIN
					--INSERT INTO  MAESTRO (MAES_TIT,MAES_GEN,MAES_NP,MAES_NC,MAES_FP,MAES_ESTADO)
					--VALUES (@RES_TIT,@RES_GEN,@RES_NP,@RES_NC,@RES_FP,@RES_AB)
					
				--END
			--ELSE
			IF (@@FETCH_STATUS=0)
				BEGIN
					IF @MAES_NC<>@RES_NC OR @MAES_FP<>@RES_FP
					BEGIN
						UPDATE MAESTRO
						SET MAES_NP=@RES_NP,
						MAES_NC=@RES_NC,
						MAES_FP=@RES_FP,
						MAES_ESTADO=@RES_AB
						WHERE CURRENT OF C3
						
						
							PRINT 'VACA : ' + @RES_GEN 
							PRINT 'CONTADOR : ' + CAST(@CONTADOR AS VARCHAR(5))
							SET @CONTADOR= @CONTADOR + 1
					END
				END

		CLOSE C3
		DEALLOCATE C3

	FETCH NEXT FROM C2 INTO @RES_TIT,@RES_GEN,@RES_NP,@RES_NC,@RES_FP,@RES_AB
	END
	CLOSE C2
	DEALLOCATE C2

FETCH NEXT FROM C1 INTO  @FPREV,@ESTABLO
	
END
CLOSE C1
DEALLOCATE C1



