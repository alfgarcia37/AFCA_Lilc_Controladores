







CREATE PROCEDURE PR_ACTUALIZA_VACAS_MAYOR_01868130
--MIRO LOS CROTALES QUE SE ESTAN CONTROLANDO POR ESPH Y TENDRIA QUE SER EL DIB
(@intCONTROLADOR INT)

AS
	
DECLARE @MAES_TIT CHAR(7),@MAES_GEN CHAR(14),@CONTROLADOR INT,@DIB AS CHAR(14)
DECLARE @TIT CHAR(7),@GEN CHAR(14),@NP INT,@NC INT,@FP SMALLDATETIME

--AHORA ACTUALIZO LOS VALORES DE TODAS LAS TABLAS

DECLARE C1 CURSOR  FOR
	SELECT ESTABLOACTUAL,NUMGEN,DIB 
	FROM NUMGEN_MAYOR_01868130
	WHERE CONTROLADOR=@intCONTROLADOR
	OPEN C1
	FETCH NEXT FROM C1 INTO @MAES_TIT,@MAES_GEN,@DIB --GEN Y DIB
	
	WHILE ( @@FETCH_STATUS=0)
	BEGIN
		--ACTUALIZO MAESTRO
			UPDATE MAESTRO
			SET MAES_GEN=@DIB
			WHERE MAES_GEN=@MAES_GEN
		--ACTUALIZO CONTROL
			UPDATE CONTROL
			SET RES_GEN=@DIB	
			WHERE RES_GEN=@MAES_GEN
		--ACTUALIZO INSEMINACIONES
			UPDATE INSEMINACIONES
			SET ID=@DIB	
			WHERE ID=@MAES_GEN
		--ACTUALIZO PARTOS
			UPDATE PARTOS
			SET ID=@DIB	
			WHERE ID=@MAES_GEN
		--ACTUALIZO CELOS
			UPDATE CELOS
			SET VACA=@DIB	
			WHERE VACA=@MAES_GEN
		--ACTUALIZO INCIDENCIAS GENERALES
			UPDATE INCIDENCIASGENERALES
			SET RES=@DIB	
			WHERE RES=@MAES_GEN

		FETCH NEXT FROM C1 INTO @MAES_TIT,@MAES_GEN,@DIB --GEN Y DIB
	END


CLOSE C1
DEALLOCATE C1