CREATE PROCEDURE PR_GENERAR_MENSAJES
(@ESTABLO CHAR(7), @CONTROLADOR SMALLINT,@MENSAJE CHAR(100),@TODOS CHAR(1))
AS
		
DECLARE @LECTU_ESTABLO CHAR(7),@NUM_CONTROLADOR SMALLINT,@LECTU_MENSAJE CHAR(100)

IF @TODOS<>'S'
	BEGIN
		IF @ESTABLO<>''
			BEGIN--SACO ESE ESTABLO CONCRETO
				UPDATE LECTURASCONTROL
				SET OBSERVACIONES=@MENSAJE
				WHERE ESTABLO=@ESTABLO
			END
		ELSE
			BEGIN--VEO SI HAY CONTROLADOR
				IF @CONTROLADOR=0
				BEGIN--2 ESTABLOS DE TODOS LOS CONTROLADORES
					DECLARE C1 CURSOR  FOR
					SELECT ID FROM CONTROLADORES
					WHERE FBAJA IS NULL
					OPEN C1 
					FETCH NEXT FROM C1 INTO @NUM_CONTROLADOR
					WHILE (@@FETCH_STATUS=0) --WHILE 1
					BEGIN
						DECLARE C2 CURSOR LOCAL SCROLL OPTIMISTIC FOR
						SELECT TOP 2 OBSERVACIONES FROM LECTURASCONTROL
						WHERE FBAJA IS NULL
						AND ESTADOS='0'
						AND NUMCONTROLER=@NUM_CONTROLADOR
						ORDER BY FPREVISTA 
						FOR UPDATE OF OBSERVACIONES
						OPEN C2 
						FETCH NEXT FROM C2 INTO @LECTU_MENSAJE
						WHILE (@@FETCH_STATUS=0)--WHILE 2
						BEGIN
							UPDATE LECTURASCONTROL
							SET OBSERVACIONES=@MENSAJE
							WHERE CURRENT OF C2
							FETCH NEXT FROM C2 INTO @LECTU_MENSAJE
						END--WHILE 2
						CLOSE C2
						DEALLOCATE C2

					FETCH NEXT FROM C1 INTO @NUM_CONTROLADOR
					END --WHILE 1
				END
				ELSE
				BEGIN--2 ESTABLOS DE ESE CONTROLADOR
					DECLARE C2 CURSOR LOCAL SCROLL OPTIMISTIC FOR
					SELECT TOP 2 OBSERVACIONES FROM LECTURASCONTROL
					WHERE FBAJA IS NULL
					AND ESTADOS='0'
					AND NUMCONTROLER=@CONTROLADOR
					ORDER BY FPREVISTA 
					FOR UPDATE OF OBSERVACIONES
					OPEN C2 
					FETCH NEXT FROM C2 INTO @LECTU_MENSAJE
					WHILE (@@FETCH_STATUS=0)--WHILE 2
					BEGIN
						UPDATE LECTURASCONTROL
						SET OBSERVACIONES=@MENSAJE
						WHERE CURRENT OF C2
						FETCH NEXT FROM C2 INTO @LECTU_MENSAJE
					END--WHILE 2
					CLOSE C2
					DEALLOCATE C2
				END

			END
	

	END
ELSE
	BEGIN --TODOS LOS ESTABLOS DE TODOS LOS CONTROLADORES
		UPDATE LECTURASCONTROL
		SET OBSERVACIONES=@MENSAJE
		WHERE ESTADOS='0'

	END