




CREATE PROCEDURE PR_MAESTRO_ULT_LECTURA_BAJAS AS

DECLARE @FPREV SMALLDATETIME,@ESTABLO CHAR(7),@CONTROLADOR INT,@GEN CHAR(14),@TIT CHAR(7),@NP INT,@FP SMALLDATETIME
DECLARE @RES_TIT CHAR(7),@RES_GEN CHAR(14),@RES_NP INT,@RES_NC INT,@RES_FP SMALLDATETIME,@RES_AB CHAR(1),@RES_FBA SMALLDATETIME
DECLARE @MAES_TIT CHAR(7),@MAES_GEN CHAR(14),@MAES_NP INT,@MAES_NC INT,@MAES_FP SMALLDATETIME,@MAES_ESTADO CHAR(1)

				

--==================================== FALTA ACTUALIZAR LAS SECAS =======================================
DECLARE C1 cursor for 

SELECT tit,gen,np,fp
FROM VistapartosControlNoTXT,Lecturascontrol
Where NumControler IN (900,92,94,96,98)
and tit=establo
--AND TIT='J391311'
--AND GEN='ES060602951480'
order by tiT,gen

OPEN  C1 
FETCH NEXT FROM C1 INTO @ESTABLO,@GEN,@NP,@FP

WHILE (@@FETCH_STATUS=0)
BEGIN
	DECLARE C2 cursor for 

	select top 1 res_gen,res_np,res_nc,res_fp,res_ab,RES_FBA
	from control 
	where
	res_TIT=@ESTABLO
	AND res_gen=@GEN
	and res_np=@np
	AND RES_AB='B'
	AND RES_CBA='01'
	order by res_nc DESC

	OPEN  C2 
	FETCH NEXT FROM C2 INTO @res_gen,@res_np,@res_nc,@res_fp,@res_ab,@RES_FBA
	IF (@@FETCH_STATUS=0) /*  EXISTE*/
		BEGIN
			DECLARE C3 cursor for 
	
			SELECT  MAES_TIT,MAES_GEN,MAES_NP,MAES_NC,MAES_FP,MAES_ESTADO FROM  MAESTRO
			WHERE MAES_TIT=@ESTABLO
			AND MAES_TIT=@ESTABLO
			AND MAES_GEN=@RES_GEN
			AND MAES_NP=@RES_NP
			
	
			OPEN  C3 
			FETCH NEXT FROM C3 INTO @MAES_TIT,@MAES_GEN,@MAES_NP,@MAES_NC,@MAES_FP,@MAES_ESTADO
			IF (@@FETCH_STATUS<>0) /* NO EXISTE*/
				BEGIN
					INSERT INTO  MAESTRO (MAES_TIT,MAES_GEN,MAES_NP,MAES_NC,MAES_FP,MAES_ESTADO,MAES_FBA)
					VALUES (@ESTABLO,@RES_GEN,@RES_NP,@RES_NC,@RES_FP,@RES_AB,@RES_FBA)
					
				END
			
		CLOSE C3
		DEALLOCATE C3

							
		END
		CLOSE C2
		DEALLOCATE C2
FETCH NEXT FROM C1 INTO @ESTABLO,@GEN,@NP,@FP
END

--ACTUALIZO LAS FECHAS DE BAJA-----

UPDATE MAESTRO 
SET MAES_FBA=RES_FBA
FROM CONTROL
WHERE MAES_TIT=RES_TIT
AND MAES_GEN=RES_GEN
AND MAES_NP=RES_NP
AND MAES_NC=RES_NC
AND MAES_ESTADO='B'
AND MAES_FBA IS NULL



