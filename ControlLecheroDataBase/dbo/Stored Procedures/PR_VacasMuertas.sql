CREATE PROCEDURE [dbo].[PR_VacasMuertas]
AS
DELETE FROM VACASMUERTAS
DECLARE @ESTABLO CHAR(7),@RES CHAR(14),@CONTROLADOR INT,@FECHA SMALLDATETIME,@NUMERO INT,@FCONTROL SMALLDATETIME,@MAES_ESTADO CHAR(1)
--COJO TODAS LAS VACAS 'A' Y 'B' DE MAESTRO y las cruzo con los movimientos

INSERT INTO VACASMUERTAS (ID,det,ESTABLOMAES,ESTADO,FECHABAJAAFCA,MOTIVOAFCA) 
SELECT MAES_GEN,Maes_nom,MAES_TIT,MAES_ESTADO,FECHAMOVIMIENTO,CODIGOCOMPRADOR
FROM MAESTRO,REGGEN..VACAS V
WHERE MAES_ESTADO<>'0'
--AND MAES_TIT=@ESTABLO
AND MAES_TIT=CODIGOGANADERIA
AND TIPOMOVIMIENTO='03'
AND MAES_GEN=CODIGOIDENTIF

/* OJO A ESTE CASO:		VENDE Y LUEGO VUELVE A COMPRAR
13853	J390497	NULL	01	2009-12-21 
14849	J390497	K940006	03	2010-07-09 
16039	K940006	J390497	03	2011-10-15  */

DELETE VACASMUERTAS
FROM  REGGEN..VACAS
WHERE ID =CODIGOIDENTIF
AND CODIGOCOMPRADOR=ESTABLOMAES AND TIPOMOVIMIENTO='03' 
AND FECHAMOVIMIENTO>FECHABAJAAFCA --HAY INCORPORACION POSTERIOR


--ahora actualizao el controlador
UPDATE VACASMUERTAS
SET CONTROLADOR=NUMCONTROLER
FROM LECTURASCONTROL
WHERE ESTABLOMAES=ESTABLO
--ACTUALIZO EL ULTIMO CONTROL
DECLARE C1 CURSOR FOR
SELECT ID FROM VACASMUERTAS
OPEN  C1 
FETCH NEXT FROM C1 INTO @RES
WHILE (@@FETCH_STATUS=0)
BEGIN
	DECLARE C2 CURSOR FOR
	SELECT MAX(RES_FPREV) FROM CONTROL
	WHERE RES_GEN=@RES
	OPEN  C2 
	FETCH NEXT FROM C2 INTO @FCONTROL
	IF (@@FETCH_STATUS=0)
	BEGIN
		UPDATE VACASMUERTAS SET ULTIMOCONTROL=@FCONTROL
		WHERE ID=@RES
	END
	CLOSE C2
	DEALLOCATE C2
	FETCH NEXT FROM C1 INTO @RES
END

CLOSE C1
DEALLOCATE C1

UPDATE VACASMUERTAS
SET ESTABLORIIA=NUMSANITARIO
FROM REGGEN..GANADERIAS_MAESTRO
WHERE ESTABLOMAES=CODGAN


