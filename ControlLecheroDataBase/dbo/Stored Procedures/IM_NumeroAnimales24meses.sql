CREATE PROCEDURE [dbo].[IM_NumeroAnimales24meses]
 (@ESTABLO char(7),
@DESDE SMALLDATETIME ) 
AS
DECLARE @NUM_ESTABLOS INT,@TOTAL_VACAS REAL
DECLARE @NUM_VACAS1 REAL,@NUM_VACAS2 REAL,@NUM_VACAS3 REAL,@NUM_VACAS4 REAL,@RES CHAR(14)
 /*===================ANIMALES EN ESTABLO=======================*/
--1. Vacas>= 24 meses en esa fecha
--2. Resto muertas y ventas con anterioridad a esa fecha
--3. SUMO las que se han introducido con posterioridad a esa fecha (fecha mvto.)
--4. RESTO LAS ALTAS'01' O '07':COMPRADAS A OTRO ESTABLO 
--SET @@DESDE='31/12/2004'
set @NUM_VACAS1=0
set @NUM_VACAS2=0
set @NUM_VACAS3=0
set @NUM_VACAS4=0

IF LEFT(@ESTABLO,1)='J' 
BEGIN
	SET @TOTAL_VACAS=0
	--1. VACAS >=24 MESES
	DECLARE C2 cursor  FOR
	SELECT count(*) FROM REGGEN..ANIMALES
	WHERE ganpro=@Establo
	AND  SEXO='H'
	AND DATEDIFF(day, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), getdate())>=730
	OPEN C2
	FETCH NEXT FROM C2 INTO @NUM_VACAS1
	CLOSE C2
	DEALLOCATE C2
	--2. RESTO VACAS QUE ESTAN EN ANIMALES Y QUE EN ESA FECHA TENIAN<24 MESES
	DECLARE C2 cursor  FOR
	SELECT count(*) FROM REGGEN..ANIMALES
	WHERE ganpro=@Establo
	AND  SEXO='H'
	AND DATEDIFF(day, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), GETDATE())>=730
	AND CODIGOIDENTIF IN (SELECT CODIGOIDENTIF FROM REGGEN..ANIMALES WHERE ganpro=@Establo AND  SEXO='H'
	AND DATEDIFF(day, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), @DESDE)<730)
	OPEN C2
	FETCH NEXT FROM C2 INTO @NUM_VACAS2
	CLOSE C2
	DEALLOCATE C2
	--3.SUMO LAS VENDIDAS O MUERTAS EN ESE PERIODO  <24 MESES---
	DECLARE C2 cursor  FOR
	SELECT count(*) FROM REGGEN..VACAS
	WHERE CODIGOGANADERIA=@Establo
	AND  TIPOMOVIMIENTO='03' 
	AND DATEDIFF(day, FECHANACIMIENTO, @DESDE)>=730
	AND FECHAMOVIMIENTO>= @DESDE
	OPEN C2
	FETCH NEXT FROM C2 INTO @NUM_VACAS3
	CLOSE C2
	DEALLOCATE C2
	--4. RESTO LAS ALTAS'01' O '07':COMPRADAS A OTRO ESTABLO 
	DECLARE C2 cursor  FOR
	SELECT count(*) FROM REGGEN..VACAS
	WHERE CODIGOGANADERIA=@Establo 
	AND  ((TIPOMOVIMIENTO='01' OR TIPOMOVIMIENTO='02')  OR (TIPOMOVIMIENTO='07') OR (TIPOMOVIMIENTO='03' AND CODIGOCOMPRADOR=@Establo))
	AND DATEDIFF(day, FECHANACIMIENTO, @DESDE)>=730
	AND FECHAMOVIMIENTO>= @DESDE
	OPEN C2
	FETCH NEXT FROM C2 INTO @NUM_VACAS3
	CLOSE C2
	DEALLOCATE C2
	SELECT (@NUM_VACAS1-@NUM_VACAS2+@NUM_VACAS3-@NUM_VACAS4) AS CENSO
END		
ELSE
BEGIN
	--1. VACAS >=24 MESES
	DECLARE C2 cursor  FOR
	SELECT count(*) FROM REGGEN..ANIMALES A,HISTORICOGANADERIAS
	WHERE ganpro=Establo
	--AND (FBAJA IS NULL OR FBAJA>@DESDE)
	AND ( @DESDE between falta and fbaja or (@DESDE>=falta and fbaja is null))
	AND  SEXO='H'
	AND DATEDIFF(day, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), getdate())>=730
	OPEN C2
	FETCH NEXT FROM C2 INTO @NUM_VACAS1
	CLOSE C2
	DEALLOCATE C2
	--2. RESTO VACAS QUE ESTAN EN ANIMALES Y QUE EN ESA FECHA TENIAN<24 MESES
	DECLARE C2 cursor  FOR
	SELECT count(*) FROM REGGEN..ANIMALES A,HISTORICOGANADERIAS
	WHERE ganpro=Establo
	--AND (FBAJA IS NULL OR FBAJA>@DESDE)
	AND ( @DESDE between falta and fbaja or (@DESDE>=falta and fbaja is null))
	AND  SEXO='H'
	AND DATEDIFF(day, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), GETDATE())>=730
	AND CODIGOIDENTIF IN (SELECT CODIGOIDENTIF FROM REGGEN..ANIMALES WHERE ganpro=Establo AND (FBAJA IS NULL OR FBAJA>@DESDE) AND  SEXO='H'
	AND DATEDIFF(day, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), @DESDE)<730)
	OPEN C2
	FETCH NEXT FROM C2 INTO @NUM_VACAS2
	CLOSE C2
	DEALLOCATE C2
	--3.SUMO LAS VENDIDAS O MUERTAS EN ESE PERIODO  <24 MESES---
	DECLARE C2 cursor  FOR
	SELECT count(*) FROM REGGEN..VACAS,HISTORICOGANADERIAS
	WHERE CODIGOGANADERIA=Establo
	--AND (FBAJA IS NULL OR FBAJA>@DESDE)
	AND ( @DESDE between falta and fbaja or (@DESDE>=falta and fbaja is null))
	AND  TIPOMOVIMIENTO='03' 
	AND DATEDIFF(day, FECHANACIMIENTO, @DESDE)>=730
	AND FECHAMOVIMIENTO>=@DESDE
	OPEN C2
	FETCH NEXT FROM C2 INTO @NUM_VACAS3
	CLOSE C2
	DEALLOCATE C2
	--4. RESTO LAS ALTAS'01' O '07':COMPRADAS A OTRO ESTABLO 
	DECLARE C2 cursor  FOR
	SELECT count(*) FROM REGGEN..VACAS,HISTORICOGANADERIAS
	WHERE CODIGOGANADERIA=Establo 
	--AND (FBAJA IS NULL OR FBAJA>@DESDE)
	AND ( @DESDE between falta and fbaja or (@DESDE>=falta and fbaja is null))
	AND  ((TIPOMOVIMIENTO='01' OR TIPOMOVIMIENTO='02')  OR (TIPOMOVIMIENTO='07') OR (TIPOMOVIMIENTO='03' AND CODIGOCOMPRADOR=Establo))
	AND DATEDIFF(day, FECHANACIMIENTO, @DESDE)>=730
	AND FECHAMOVIMIENTO>= @DESDE
	OPEN C2
	FETCH NEXT FROM C2 INTO @NUM_VACAS4
	CLOSE C2
	DEALLOCATE C2
	SELECT (@NUM_VACAS1-@NUM_VACAS2+@NUM_VACAS3-@NUM_VACAS4) AS CENSO
	--SELECT (@NUM_VACAS1 ) AS '1'
	--SELECT (@NUM_VACAS2) AS '2'
	--SELECT (@NUM_VACAS3) AS '3'
	--SELECT (@NUM_VACAS4) AS '4'
	--SELECT 222 AS CENSO
END








