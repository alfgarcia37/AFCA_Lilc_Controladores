






CREATE PROCEDURE  PR_InfAnual1Insem
 (@ESTABLO char(7),
@DESDE SMALLDATETIME,@HASTA SMALLDATETIME ) 
AS

DECLARE @NUM_ESTABLOS INT,@TAMANOESTABLO CHAR(1)
DECLARE @NUM_VACAS REAL,@TOTAL_VACAS INT,@NUM_REGISTROS INT
DECLARE @NUM_PARTOS INT,@NUM_DIAS INT,@GEN CHAR(14),@FINS SMALLDATETIME,@TOTAL_DIAS INT

SET @TOTAL_DIAS=0
SET @NUM_REGISTROS=0

IF @ESTABLO<>' '
BEGIN
 /*===================DIAS PRIMERA INSEMINACION EN ESTABLO=======================*/
	
	DECLARE C1 CURSOR FOR 
	SELECT ID,NP,FINS
	FROM PARTOS
	WHERE 
	ESTABLO=@ESTABLO
	AND FPARTO BETWEEN @DESDE AND @HASTA
	AND FINS IS NOT NULL
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @GEN,@NUM_PARTOS,@FINS
	WHILE (@@FETCH_STATUS=0)
	BEGIN
		DECLARE C2 CURSOR FOR 
		SELECT (DATEDIFF(DAY,PARTOS.FPARTO,@FINS))
		FROM PARTOS
		WHERE 
		PARTOS.ID=@GEN
		AND PARTOS.NP=@NUM_PARTOS-1
		AND  DATEDIFF(DAY,PARTOS.FPARTO,@FINS)<100
		OPEN  C2 
		FETCH NEXT FROM C2 INTO @NUM_DIAS
		 IF @NUM_DIAS IS NULL
			BEGIN
				SET @NUM_DIAS=0
			END
		SET @TOTAL_DIAS=@TOTAL_DIAS+@NUM_DIAS
		SET @NUM_REGISTROS=@NUM_REGISTROS+1
	
		CLOSE C2
		DEALLOCATE C2
	
		FETCH NEXT FROM C1 INTO @GEN,@NUM_PARTOS,@FINS
	END
	CLOSE C1
	DEALLOCATE C1
	
	SELECT @TOTAL_DIAS/@NUM_REGISTROS  AS DIASINSEMINACION

END
ELSE
BEGIN
	/*===================DIAS PRIMERA INSEMINACIOIN EN CANTABRIA=======================*/
	-- NO DIVIDO ENTRE NUM_ESTABLOS PORQUE HAY MUY POCOS DATOS
	DECLARE C1 CURSOR FOR 
	SELECT ID,NP,FINS
	FROM PARTOS,LECTURASCONTROL
	WHERE 
	FPARTO BETWEEN @DESDE  AND @HASTA
	AND LECTURASCONTROL.FBAJA IS  NULL
	AND LECTURASCONTROL.ESTABLO=PARTOS.ESTABLO /*cojo solo los activos actualmente*/
	AND TAMANOESTABLO IS NOT NULL
	AND FINS IS NOT NULL
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @GEN,@NUM_PARTOS,@FINS
	WHILE (@@FETCH_STATUS=0)
	BEGIN
		DECLARE C2 CURSOR FOR 
		SELECT (DATEDIFF(DAY,PARTOS.FPARTO,@FINS))
		FROM PARTOS
		WHERE 
		PARTOS.ID=@GEN
		AND PARTOS.NP=@NUM_PARTOS-1
		AND  DATEDIFF(DAY,PARTOS.FPARTO,@FINS)<100
		OPEN  C2 
		FETCH NEXT FROM C2 INTO @NUM_DIAS
		 IF @NUM_DIAS IS NULL
			BEGIN
				SET @NUM_DIAS=0
			END
		SET @TOTAL_DIAS=@TOTAL_DIAS+@NUM_DIAS
		SET @NUM_REGISTROS=@NUM_REGISTROS+1
	
		CLOSE C2
		DEALLOCATE C2
	
		FETCH NEXT FROM C1 INTO @GEN,@NUM_PARTOS,@FINS
	END
	CLOSE C1
	DEALLOCATE C1
	
		UPDATE INFORMEANUAL SET VALOR=@TOTAL_DIAS/@NUM_REGISTROS
		WHERE GRUPO='CANTABRIA' 
		AND CONCEPTO='DIAS PRIMERA INSEMINACION'
	
	
	/*===================DIAS PRIMERA INSEMINACIOIN EN TRAMOS=======================*/
	
	
	DECLARE C1 CURSOR FOR 
	SELECT TAMANOESTABLO,COUNT(DISTINCT MAES_TIT) FROM MAESTRO,LECTURASCONTROL
	WHERE 
	FBAJA IS  NULL
	AND TAMANOESTABLO IS NOT NULL
	AND MAES_TIT=ESTABLO
	GROUP BY TAMANOESTABLO
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	WHILE (@@FETCH_STATUS=0)
	BEGIN
		SET @TOTAL_DIAS=0
		SET @NUM_REGISTROS=0
					
		DECLARE C2 CURSOR FOR 
		SELECT ID,NP,FINS
		FROM PARTOS,LECTURASCONTROL
		WHERE 
		FPARTO BETWEEN @DESDE  AND @HASTA
		AND LECTURASCONTROL.FBAJA IS  NULL
		AND LECTURASCONTROL.ESTABLO=PARTOS.ESTABLO /*cojo solo los activos actualmente*/
		AND TAMANOESTABLO=@TAMANOESTABLO
		AND TAMANOESTABLO IS NOT NULL
		AND FINS IS NOT NULL
	
		OPEN  C2 
		FETCH NEXT FROM C2 INTO @GEN,@NUM_PARTOS,@FINS
		WHILE (@@FETCH_STATUS=0)
		BEGIN
			DECLARE C3 CURSOR FOR 
			SELECT (DATEDIFF(DAY,PARTOS.FPARTO,@FINS))
			FROM PARTOS
			WHERE 
			PARTOS.ID=@GEN
			AND PARTOS.NP=@NUM_PARTOS-1
			AND  DATEDIFF(DAY,PARTOS.FPARTO,@FINS)<100
			OPEN  C3 
			FETCH NEXT FROM C3 INTO @NUM_DIAS
			 IF @NUM_DIAS IS NULL
			BEGIN
				SET @NUM_DIAS=0
			END
			SET @TOTAL_DIAS=@TOTAL_DIAS+@NUM_DIAS
			SET @NUM_REGISTROS=@NUM_REGISTROS+1
	
			CLOSE C3
			DEALLOCATE C3
		
			FETCH NEXT FROM C2 INTO @GEN,@NUM_PARTOS,@FINS
		END
			CLOSE C2
			DEALLOCATE C2
	
		UPDATE INFORMEANUAL SET VALOR=@TOTAL_DIAS/@NUM_REGISTROS
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='DIAS PRIMERA INSEMINACION'
		SET @TOTAL_DIAS=0
		SET @NUM_REGISTROS=0
		FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	END
	CLOSE C1
	DEALLOCATE C1
END






