






CREATE PROCEDURE PR_InfAnualIntervaloPartos 
 (@ESTABLO char(7),
@DESDE SMALLDATETIME,@HASTA SMALLDATETIME ) 
AS

DECLARE @GEN CHAR(14),@NP  INT,@FPARTO SMALLDATETIME,@TOTALDIAS REAL,@FPARTO_ANTERIOR SMALLDATETIME,@NUM_VACAS REAL,@A INT
DECLARE @TAMANOESTABLO CHAR(1),@NUM_ESTABLOS REAL

IF @ESTABLO<>' '
BEGIN

	DECLARE C1 CURSOR FOR
	SELECT ID,NP,FPARTO FROM PARTOS
	WHERE 
	ESTABLO=@ESTABLO
	AND FPARTO>=@DESDE
	AND FPARTO<=@HASTA
	AND NP>1
	SET @TOTALDIAS=0;SET @NUM_VACAS=0
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @GEN,@NP,@FPARTO
	WHILE (@@FETCH_STATUS=0)
	  BEGIN
		
		DECLARE C2 CURSOR FOR
		SELECT FPARTO FROM PARTOS
		WHERE 
		ID=@GEN
		AND  NP=@NP-1
		AND ESTABLO=@ESTABLO
		
		OPEN  C2 
		FETCH NEXT FROM C2 INTO @FPARTO_ANTERIOR 
		IF @@FETCH_STATUS=0
		BEGIN
			SET @TOTALDIAS=@TOTALDIAS+DATEDIFF(DAY,@FPARTO_ANTERIOR,@FPARTO)
			SET @NUM_VACAS=@NUM_VACAS+1
		END
		ELSE
		BEGIN
			SET @A=1
		END
	
		CLOSE C2
		DEALLOCATE C2
	
	
		FETCH NEXT FROM C1 INTO  @GEN,@NP,@FPARTO
	
	 END
	
	CLOSE C1
	DEALLOCATE C1
	
	SELECT @TOTALDIAS/@NUM_VACAS AS INTERVALOPARTOS
END

ELSE

BEGIN
	--====================CANTABRIA=================================

	DECLARE C1 CURSOR FOR
	SELECT ID,NP,FPARTO 
	FROM PARTOS,LECTURASCONTROL
	WHERE 
	FPARTO BETWEEN @DESDE  AND @HASTA
	AND LECTURASCONTROL.FBAJA IS  NULL
	AND LECTURASCONTROL.ESTABLO=PARTOS.ESTABLO /*cojo solo los activos actualmente*/
	AND TAMANOESTABLO IS NOT NULL
	AND NP>1


	SET @TOTALDIAS=0;SET @NUM_VACAS=0
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @GEN,@NP,@FPARTO
	WHILE (@@FETCH_STATUS=0)
	  BEGIN
		
		DECLARE C2 CURSOR FOR
		SELECT FPARTO FROM PARTOS
		WHERE 
		ID=@GEN
		AND  NP=@NP-1
				
		OPEN  C2 
		FETCH NEXT FROM C2 INTO @FPARTO_ANTERIOR 
		IF @@FETCH_STATUS=0
		BEGIN
			SET @TOTALDIAS=@TOTALDIAS+DATEDIFF(DAY,@FPARTO_ANTERIOR,@FPARTO)
			SET @NUM_VACAS=@NUM_VACAS+1
		END
			
		CLOSE C2
		DEALLOCATE C2
		
		FETCH NEXT FROM C1 INTO  @GEN,@NP,@FPARTO
	 END
	
	CLOSE C1
	DEALLOCATE C1
		UPDATE INFORMEANUAL SET VALOR=@TOTALDIAS/@NUM_VACAS
		WHERE GRUPO='CANTABRIA' 
		AND CONCEPTO='INTERVALO ENTRE PARTOS'


/*========INTERVALO ENTRE PARTOS EN TRAMOS================*/
	
	DECLARE C1 cursor for 
	SELECT TAMANOESTABLO,COUNT(DISTINCT MAES_TIT) FROM MAESTRO,LECTURASCONTROL
	WHERE 
	FBAJA IS  NULL
	AND TAMANOESTABLO IS NOT NULL
	AND MAES_TIT=ESTABLO
	GROUP BY TAMANOESTABLO
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	WHILE (@@FETCH_STATUS=0)
	BEGIN
		DECLARE C2 cursor  FOR
		SELECT ID,NP,FPARTO 
		FROM PARTOS,LECTURASCONTROL
		WHERE 
		FPARTO BETWEEN @DESDE  AND @HASTA
		AND LECTURASCONTROL.FBAJA IS  NULL
		AND LECTURASCONTROL.ESTABLO=PARTOS.ESTABLO /*cojo solo los activos actualmente*/
		AND TAMANOESTABLO IS NOT NULL
		AND TAMANOESTABLO=@TAMANOESTABLO
		AND NP>1

		SET @TOTALDIAS=0;SET @NUM_VACAS=0
	
		OPEN  C2 
		FETCH NEXT FROM C2 INTO @GEN,@NP,@FPARTO
		WHILE (@@FETCH_STATUS=0)
		  BEGIN
		
			DECLARE C3 CURSOR FOR
			SELECT FPARTO FROM PARTOS
			WHERE 
			ID=@GEN
			AND  NP=@NP-1
					
			OPEN  C3 
			FETCH NEXT FROM C3 INTO @FPARTO_ANTERIOR 
			IF @@FETCH_STATUS=0
			BEGIN
				SET @TOTALDIAS=@TOTALDIAS+DATEDIFF(DAY,@FPARTO_ANTERIOR,@FPARTO)
				SET @NUM_VACAS=@NUM_VACAS+1
			END
				
			CLOSE C3
			DEALLOCATE C3
			
			FETCH NEXT FROM C2 INTO  @GEN,@NP,@FPARTO
		END--WHILE DE PARTOS
		CLOSE C2
		DEALLOCATE C2

		UPDATE INFORMEANUAL SET VALOR=@TOTALDIAS/@NUM_VACAS
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='INTERVALO ENTRE PARTOS'
	

		FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	 END--WHILE DE TRAMOS
	
	CLOSE C1
	DEALLOCATE C1
		
			
	
END






