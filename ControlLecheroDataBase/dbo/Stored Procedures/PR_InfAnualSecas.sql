






CREATE PROCEDURE PR_InfAnualSecas 
 (@ESTABLO char(7),@DESDE SMALLDATETIME,@HASTA SMALLDATETIME)
AS




DECLARE @VACAS_CONTROLADAS REAL,@VACAS_SECADAS REAL,@TAMANOESTABLO INT,@NUM_ESTABLOS INT,@NUM_LECTURAS REAL



IF @ESTABLO<>' '
BEGIN
/* =============PROMEDIO Y PORCENTAJE DE  VACAS SECAS ESTABLO=================================*/

	
	DECLARE C1 CURSOR FOR 
	SELECT COUNT(*) FROM CONTROL
	WHERE 
	RES_TIT=@ESTABLO
	AND RES_FPREV BETWEEN @DESDE AND @HASTA
	AND RES_AB='A'
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @VACAS_CONTROLADAS
	CLOSE C1
	DEALLOCATE C1
	
	DECLARE C1 cursor for 
	SELECT count(*)
	FROM LECTURASCONTROL,LECTURASFINALIZADAS
	WHERE 
	LECTURASCONTROL.ESTABLO=@ESTABLO
	AND LECTURASCONTROL.ESTABLO=LECTURASFINALIZADAS.ESTABLO
	AND FBAJA IS NULL
	AND LECTURASFINALIZADAS.FPREVISTA BETWEEN @DESDE AND @HASTA
	OPEN  C1 
	FETCH NEXT FROM C1 INTO  @NUM_LECTURAS
	CLOSE C1
	DEALLOCATE C1
	
	DECLARE C1 CURSOR FOR 
	SELECT COUNT(*) FROM CONTROL
	WHERE 
	RES_TIT=@ESTABLO
	AND RES_FPREV BETWEEN @DESDE AND @HASTA
	AND RES_AB='B'
	 
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @VACAS_SECADAS
	CLOSE C1
	DEALLOCATE C1

		/* =============PROMEDIO DE DIAS SECAS CANTABRIA===========================================================*/
		DECLARE @ESTABLODIAS_SECAS REAL,@DIAS_SECAS45 REAL,@DIAS_SECAS4565 REAL,@DIAS_SECAS65 REAL
				
		DECLARE C1 CURSOR FOR 
		SELECT SUM(DATEDIFF(DAY,FBAJAANTERIOR,FPARTO))/COUNT(*)
		FROM PARTOS
		WHERE 
		ESTABLO=@ESTABLO
		AND FBAJA BETWEEN @DESDE AND @HASTA
		AND FBAJAANTERIOR IS NOT NULL
		 
		OPEN  C1 
		FETCH NEXT FROM C1 INTO @ESTABLODIAS_SECAS
		CLOSE C1
		DEALLOCATE C1
		
		/*...................................................................................DIAS SECAS < 45...............................*/
		DECLARE C1 CURSOR FOR 
		SELECT COUNT(*)
		FROM PARTOS
		WHERE  ESTABLO=@ESTABLO 
		AND FBAJA BETWEEN @DESDE AND @HASTA
		AND DATEDIFF(DAY,FBAJAANTERIOR,FPARTO)<45
		AND PARTOS.FBAJAANTERIOR IS NOT NULL
		 
		OPEN  C1 
		FETCH NEXT FROM C1 INTO @DIAS_SECAS45
		CLOSE C1
		DEALLOCATE C1
		/*...................................................................................DIAS SECAS >=45 Y <=65...............................*/
		DECLARE C1 CURSOR FOR 
		SELECT COUNT(*)
		FROM PARTOS
		WHERE  PARTOS.ESTABLO=@ESTABLO /*cojo solo los activos actualmente*/ 
		AND FBAJA BETWEEN @DESDE AND @HASTA
		AND DATEDIFF(DAY,FBAJAANTERIOR,FPARTO)>=45
		AND DATEDIFF(DAY,FBAJAANTERIOR,FPARTO)<=65
		AND PARTOS.FBAJAANTERIOR IS NOT NULL
		 
		OPEN  C1 
		FETCH NEXT FROM C1 INTO @DIAS_SECAS4565
		CLOSE C1
		DEALLOCATE C1
		/*...................................................................................DIAS SECAS >65...............................*/
		DECLARE C1 CURSOR FOR 
		SELECT COUNT(*)
		FROM PARTOS
		WHERE  PARTOS.ESTABLO=@ESTABLO /*cojo solo los activos actualmente*/
		AND FBAJA BETWEEN @DESDE AND @HASTA
		AND DATEDIFF(DAY,FBAJAANTERIOR,FPARTO)>65
		AND PARTOS.FBAJAANTERIOR IS NOT NULL
		 
		OPEN  C1 
		FETCH NEXT FROM C1 INTO @DIAS_SECAS65
		CLOSE C1
		DEALLOCATE C1
				
		SELECT @VACAS_SECADAS/@NUM_LECTURAS AS PROMEDIOVACASSECADAS,(@VACAS_SECADAS*100/@VACAS_CONTROLADAS)  AS PORCENTAJEVACASSECADAS,@ESTABLODIAS_SECAS AS PROMEDIODIASSECAS,
		@VACAS_SECADAS AS VACASSECADAS,@DIAS_SECAS45 AS DIASSECAS45,@DIAS_SECAS4565 AS DIASSECAS4565,@DIAS_SECAS65 AS DIASSECAS65
		
END
ELSE
BEGIN
	/* =============NUMERO,PROMEDIO Y PORCENTAJE DE  VACAS SECAS CANTABRIA=================================*/
	 DECLARE C1 CURSOR FOR 
	SELECT COUNT(DISTINCT MAES_TIT) FROM MAESTRO,LECTURASCONTROL
	WHERE LECTURASCONTROL.FBAJA IS  NULL
	AND MAES_TIT=ESTABLO /*cojo solo los activos actualmente*/
	AND TAMANOESTABLO IS NOT NULL
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @NUM_ESTABLOS
	CLOSE C1
	DEALLOCATE C1

	DECLARE C1 cursor for 
	SELECT count(*)
	FROM LECTURASCONTROL,LECTURASFINALIZADAS
	WHERE 
	LECTURASCONTROL.ESTABLO=LECTURASFINALIZADAS.ESTABLO
	AND FBAJA IS NULL
	AND LECTURASFINALIZADAS.FPREVISTA BETWEEN @DESDE AND @HASTA
	OPEN  C1 
	FETCH NEXT FROM C1 INTO  @NUM_LECTURAS
	CLOSE C1
	DEALLOCATE C1
	
	DECLARE C1 CURSOR FOR 
	SELECT COUNT(*) FROM CONTROL,LECTURASCONTROL
	WHERE 
	LECTURASCONTROL.FBAJA IS  NULL
	AND CONTROL.RES_TIT=LECTURASCONTROL.ESTABLO
	AND RES_FPREV BETWEEN @DESDE AND @HASTA
	AND RES_AB='A'
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @VACAS_CONTROLADAS
	CLOSE C1
	DEALLOCATE C1
	
	 
	DECLARE C1 CURSOR FOR 
	SELECT COUNT(*) FROM CONTROL,LECTURASCONTROL
	WHERE 
	LECTURASCONTROL.FBAJA IS  NULL
	AND CONTROL.RES_TIT=LECTURASCONTROL.ESTABLO
	AND RES_FPREV BETWEEN @DESDE AND @HASTA
	AND RES_AB='B'
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @VACAS_SECADAS
	CLOSE C1
	DEALLOCATE C1
	
	UPDATE INFORMEANUAL SET VALOR=@VACAS_SECADAS/@NUM_ESTABLOS
	WHERE GRUPO='CANTABRIA'
	AND CONCEPTO='NUMERO VACAS SECAS' --POR PERIODO SELECCIONADO

	UPDATE INFORMEANUAL SET VALOR=@VACAS_SECADAS/@NUM_LECTURAS
	WHERE GRUPO='CANTABRIA'
	AND CONCEPTO='PROMEDIO VACAS SECAS' --POR CONTROL
	
	UPDATE INFORMEANUAL SET VALOR=(@VACAS_SECADAS*100/@VACAS_CONTROLADAS) 
	WHERE GRUPO='CANTABRIA'
	AND CONCEPTO='PORCENTAJE VACAS SECAS' --POR CONTROL
	
	/*========VACAS SECAS EN TRAMOS================*/
	
	DECLARE C1 cursor for 
	SELECT TAMANOESTABLO,COUNT(DISTINCT MAES_TIT)
	FROM MAESTRO,LECTURASCONTROL
	WHERE 
	LECTURASCONTROL.FBAJA IS  NULL
	AND TAMANOESTABLO IS NOT NULL
	AND MAES_TIT=ESTABLO
	GROUP BY TAMANOESTABLO
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	WHILE (@@FETCH_STATUS=0)
	BEGIN


		DECLARE C3 cursor for 
		SELECT count(*)
		FROM LECTURASCONTROL,LECTURASFINALIZADAS
		WHERE 
		LECTURASCONTROL.ESTABLO=LECTURASFINALIZADAS.ESTABLO
		AND TAMANOESTABLO=@TAMANOESTABLO
		AND FBAJA IS NULL
		AND LECTURASFINALIZADAS.FPREVISTA BETWEEN @DESDE AND @HASTA
		OPEN  C3 
		FETCH NEXT FROM C3 INTO  @NUM_LECTURAS
		CLOSE C3
		DEALLOCATE C3
			
		DECLARE C3 CURSOR FOR 
		SELECT COUNT(*) FROM CONTROL,LECTURASCONTROL
		WHERE RES_TIT=ESTABLO
		AND TAMANOESTABLO=@TAMANOESTABLO
		AND RES_FPREV BETWEEN @DESDE AND @HASTA
		AND RES_AB='A'
		AND LECTURASCONTROL.FBAJA IS  NULL
		AND TAMANOESTABLO IS NOT NULL
		OPEN  C3
		FETCH NEXT FROM C3 INTO @VACAS_CONTROLADAS
		CLOSE C3
		DEALLOCATE C3
	
		DECLARE C2 cursor  FOR
		SELECT COUNT(*) FROM CONTROL,LECTURASCONTROL
		WHERE 
		LECTURASCONTROL.FBAJA IS  NULL
		AND TAMANOESTABLO IS NOT NULL
		AND CONTROL.RES_TIT=LECTURASCONTROL.ESTABLO
		AND RES_FPREV BETWEEN @DESDE AND @HASTA
		AND RES_AB='B'
		AND TAMANOESTABLO=@TAMANOESTABLO
		
				
		OPEN C2
		FETCH NEXT FROM C2 INTO  @VACAS_SECADAS

			UPDATE INFORMEANUAL SET VALOR=@VACAS_SECADAS/@NUM_ESTABLOS
			WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
			AND CONCEPTO='NUMERO VACAS SECAS' --POR PERIODO SELECCIONADO
		
			UPDATE INFORMEANUAL SET VALOR=@VACAS_SECADAS/@NUM_LECTURAS
			WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
			AND CONCEPTO='PROMEDIO VACAS SECAS'
	
			UPDATE INFORMEANUAL SET VALOR=(@VACAS_SECADAS*100/@VACAS_CONTROLADAS) 
			WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
			AND CONCEPTO='PORCENTAJE VACAS SECAS'
	
			CLOSE C2
			DEALLOCATE C2
		FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	END
	CLOSE C1
	DEALLOCATE C1
	
	/* =============PROMEDIO DE DIAS SECAS CANTABRIA===========================================================*/
	DECLARE @DIAS_SECAS REAL
	DECLARE C1 CURSOR FOR 
	SELECT COUNT(DISTINCT MAES_TIT) FROM MAESTRO,LECTURASCONTROL
	WHERE LECTURASCONTROL.FBAJA IS  NULL
	AND MAES_TIT=ESTABLO /*cojo solo los activos actualmente*/
	AND TAMANOESTABLO IS NOT NULL
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @NUM_ESTABLOS
	CLOSE C1
	DEALLOCATE C1
	
	DECLARE C1 CURSOR FOR 
	SELECT SUM(DATEDIFF(DAY,FBAJAANTERIOR,FPARTO))/COUNT(*)
	FROM PARTOS,LECTURASCONTROL
	WHERE LECTURASCONTROL.FBAJA IS  NULL
	AND PARTOS.ESTABLO=LECTURASCONTROL.ESTABLO /*cojo solo los activos actualmente*/
	AND PARTOS.FPARTO BETWEEN @DESDE AND @HASTA
	AND FBAJAANTERIOR IS NOT NULL
	 
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @DIAS_SECAS
	CLOSE C1
	DEALLOCATE C1
	
	UPDATE INFORMEANUAL SET VALOR=@DIAS_SECAS
	WHERE GRUPO='CANTABRIA'
	AND CONCEPTO='PROMEDIO DIAS SECAS'
	
	/*...................................................................................DIAS SECAS < 45...............................*/
	DECLARE C1 CURSOR FOR 
	SELECT COUNT(*)
	FROM PARTOS,LECTURASCONTROL
	WHERE LECTURASCONTROL.FBAJA IS  NULL
	AND PARTOS.ESTABLO=LECTURASCONTROL.ESTABLO /*cojo solo los activos actualmente*/
	AND PARTOS.FBAJA BETWEEN @DESDE AND @HASTA
	AND DATEDIFF(DAY,FBAJAANTERIOR,FPARTO)<45
	AND PARTOS.FBAJAANTERIOR IS NOT NULL
	 
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @DIAS_SECAS
	CLOSE C1
	DEALLOCATE C1
	UPDATE INFORMEANUAL SET VALOR=@DIAS_SECAS/@NUM_ESTABLOS
	WHERE GRUPO='CANTABRIA'
	AND CONCEPTO='DIAS SECAS<45'
	/*...................................................................................DIAS SECAS >=45 Y <=65...............................*/
	DECLARE C1 CURSOR FOR 
	SELECT COUNT(*)
	FROM PARTOS,LECTURASCONTROL
	WHERE LECTURASCONTROL.FBAJA IS  NULL
	AND PARTOS.ESTABLO=LECTURASCONTROL.ESTABLO /*cojo solo los activos actualmente*/ 
	AND PARTOS.FBAJA BETWEEN @DESDE AND @HASTA
	AND DATEDIFF(DAY,FBAJAANTERIOR,FPARTO)>=45
	AND DATEDIFF(DAY,FBAJAANTERIOR,FPARTO)<=65
	AND PARTOS.FBAJAANTERIOR IS NOT NULL
	 
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @DIAS_SECAS
	CLOSE C1
	DEALLOCATE C1
	UPDATE INFORMEANUAL SET VALOR=@DIAS_SECAS/@NUM_ESTABLOS
	WHERE GRUPO='CANTABRIA'
	AND CONCEPTO='DIAS SECAS>45<65'
	/*...................................................................................DIAS SECAS >65...............................*/
	DECLARE C1 CURSOR FOR 
	SELECT COUNT(*)
	FROM PARTOS,LECTURASCONTROL
	WHERE LECTURASCONTROL.FBAJA IS  NULL
	AND PARTOS.FBAJA BETWEEN @DESDE AND @HASTA
	AND PARTOS.ESTABLO=LECTURASCONTROL.ESTABLO /*cojo solo los activos actualmente*/
	AND DATEDIFF(DAY,FBAJAANTERIOR,FPARTO)>65
	AND PARTOS.FBAJAANTERIOR IS NOT NULL
	 
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @DIAS_SECAS
	CLOSE C1
	DEALLOCATE C1
	UPDATE INFORMEANUAL SET VALOR=@DIAS_SECAS/@NUM_ESTABLOS
	WHERE GRUPO='CANTABRIA'
	AND CONCEPTO='DIAS SECAS>65'
	
	/*========VACAS SECAS EN TRAMOS=========================================================================================*/
	
	DECLARE C1 cursor for 
	SELECT TAMANOESTABLO,COUNT(DISTINCT MAES_TIT) FROM MAESTRO,LECTURASCONTROL
	WHERE 
	LECTURASCONTROL.FBAJA IS  NULL
	AND TAMANOESTABLO IS NOT NULL
	AND MAES_TIT=ESTABLO
	GROUP BY TAMANOESTABLO
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	WHILE (@@FETCH_STATUS=0)
	BEGIN
		DECLARE C2 cursor  FOR
		SELECT SUM(DATEDIFF(DAY,FBAJAANTERIOR,FPARTO))/COUNT(*)
		FROM PARTOS,LECTURASCONTROL
		WHERE 
		PARTOS.ESTABLO=LECTURASCONTROL.ESTABLO
		AND PARTOS.FBAJA BETWEEN @DESDE AND @HASTA
		AND FBAJAANTERIOR IS NOT NULL
		AND TAMANOESTABLO=@TAMANOESTABLO
		AND LECTURASCONTROL.FBAJA IS  NULL
		AND TAMANOESTABLO IS NOT NULL
		OPEN C2
		FETCH NEXT FROM C2 INTO  @DIAS_SECAS
		
		UPDATE INFORMEANUAL SET VALOR=@DIAS_SECAS
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='PROMEDIO DIAS SECAS'
		
		CLOSE C2
		DEALLOCATE C2
		/*............................................................SEGMENTOS 45,65.......*/
		DECLARE C2 cursor  FOR
		SELECT COUNT(*)
		FROM PARTOS,LECTURASCONTROL
		WHERE LECTURASCONTROL.FBAJA IS  NULL
		AND PARTOS.ESTABLO=LECTURASCONTROL.ESTABLO /*cojo solo los activos actualmente*/
		AND PARTOS.FBAJA BETWEEN @DESDE AND @HASTA
		AND DATEDIFF(DAY,FBAJAANTERIOR,FPARTO)<45
		AND PARTOS.FBAJAANTERIOR IS NOT NULL
	 	AND TAMANOESTABLO=@TAMANOESTABLO
		AND TAMANOESTABLO IS NOT NULL
		OPEN C2
		FETCH NEXT FROM C2 INTO  @DIAS_SECAS
		
		UPDATE INFORMEANUAL SET VALOR=@DIAS_SECAS/@NUM_ESTABLOS
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='DIAS SECAS<45'
		
		CLOSE C2
		DEALLOCATE C2
	
		DECLARE C2 cursor  FOR
		SELECT COUNT(*)
		FROM PARTOS,LECTURASCONTROL
		WHERE LECTURASCONTROL.FBAJA IS  NULL
		AND PARTOS.ESTABLO=LECTURASCONTROL.ESTABLO /*cojo solo los activos actualmente*/
		AND PARTOS.FBAJA BETWEEN @DESDE AND @HASTA
		AND DATEDIFF(DAY,FBAJAANTERIOR,FPARTO)>=45
		AND DATEDIFF(DAY,FBAJAANTERIOR,FPARTO)<=65
		AND PARTOS.FBAJAANTERIOR IS NOT NULL
	 	AND TAMANOESTABLO=@TAMANOESTABLO
		AND TAMANOESTABLO IS NOT NULL
		OPEN C2
		FETCH NEXT FROM C2 INTO  @DIAS_SECAS
		
		UPDATE INFORMEANUAL SET VALOR=@DIAS_SECAS/@NUM_ESTABLOS
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='DIAS SECAS>45<65'
		
		CLOSE C2
		DEALLOCATE C2
	
		DECLARE C2 cursor  FOR
		SELECT COUNT(*)
		FROM PARTOS,LECTURASCONTROL
		WHERE LECTURASCONTROL.FBAJA IS  NULL
		AND PARTOS.ESTABLO=LECTURASCONTROL.ESTABLO /*cojo solo los activos actualmente*/
		AND PARTOS.FBAJA BETWEEN @DESDE AND @HASTA
		AND DATEDIFF(DAY,FBAJAANTERIOR,FPARTO)>65
		AND PARTOS.FBAJAANTERIOR IS NOT NULL
	 	AND TAMANOESTABLO=@TAMANOESTABLO
		AND TAMANOESTABLO IS NOT NULL
		OPEN C2
		FETCH NEXT FROM C2 INTO  @DIAS_SECAS
		
		UPDATE INFORMEANUAL SET VALOR=@DIAS_SECAS/@NUM_ESTABLOS
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='DIAS SECAS>65'
		
		CLOSE C2
		DEALLOCATE C2
	
		FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	
	END
	CLOSE C1
	DEALLOCATE C1
END






