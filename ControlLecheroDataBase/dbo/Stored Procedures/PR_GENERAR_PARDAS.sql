CREATE PROCEDURE  PR_GENERAR_PARDAS
(@datFDesde smalldatetime, @datFHasta smalldatetime)
AS 

DECLARE @GRASA REAL,@PROTEINA REAL,@KILOS REAL,@WKILOS REAL
DECLARE @INC CHAR(10)

-- BORRO REGISTROS DE TABLA TEMPORAL
DELETE FROM CONTROL_TEMPORAL

--SELECCIONO EL RANGO DE VALORES

INSERT INTO CONTROL_TEMPORAL (RES_TIT,RES_GEN,RES_FCTR,CONTROLADOR,RES_KLAM,RES_KLPM,RES_TGR,RES_TPR,RES_TLA,RES_TRC,
RES_FP,RES_NP,RES_NC,RES_FBA,RES_CBA,RES_FN,RES_NOM,RES_AB,RES_FPREV,RES_SW0,RES_COL,RES_ORD,RES_XAB,RES_INC,RES_VELORD)
SELECT RES_TIT, RES_GEN,RES_FCTR,CONTROLADOR,RES_KLAM,RES_KLPM,RES_TGR,RES_TPR,RES_TLA,RES_TRC,
RES_FP,RES_NP,RES_NC,RES_FBA,RES_CBA,RES_FN,RES_NOM,RES_AB,RES_FPREV,RES_SW0,RES_COL,RES_ORD,RES_XAB,RES_INC,RES_VELORD
FROM CONTROL,MAESTRO
WHERE  RES_FPREV BETWEEN @datFDesde AND @datFHasta
AND RES_TIT=MAES_TIT
AND MAES_GEN=RES_GEN
--AND RES_TIT='J397000'
AND MAES_RAZA='12'
--ACTUALIZO EL DE CONAFE AL SANITARIO
UPDATE CONTROL_TEMPORAL
SET RES_TIT=NUMSANITARIO
FROM REGGEN..GANADERIAS_MAESTRO
WHERE RES_TIT=CODGAN