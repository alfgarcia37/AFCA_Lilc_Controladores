







CREATE PROCEDURE PR_Check_VACAS_DIB_MENOR_01868130
--VACAS QUE SE ESTAN CONTROLANDO POR EL DIB Y TENDRIA QUE SER ESPH
	
AS
	
DECLARE @MAES_TIT CHAR(7),@MAES_GEN CHAR(14),@CONTROLADOR INT,@DIB CHAR(14)
DECLARE @TIT CHAR(7),@GEN CHAR(14),@NP INT,@NC INT,@FP SMALLDATETIME

DELETE FROM NUMGEN_DIB_MENOR_01868130

	DECLARE C1 CURSOR  FOR
	SELECT MAES_TIT,MAES_GEN,NUMCONTROLER 
	FROM MAESTRO,LECTURASCONTROL
	WHERE MAES_TIT=ESTABLO
	AND LEFT(MAES_GEN,4)<>'ESPH'
	AND LEFT(MAES_GEN,3)<>'ESS'
	AND MAES_ESTADO<>'0'
	--AND RIGHT(MAES_GEN,8)<'01868130'
	--AND MAES_FP>'01/01/06'
	--AND NUMCONTROLER=98
	OPEN C1
	FETCH NEXT FROM C1 INTO @MAES_TIT,@MAES_GEN,@CONTROLADOR
	
	WHILE ( @@FETCH_STATUS=0)
	BEGIN
		--RECUPERO EL ESPH DE REGISTRO
		DECLARE C2 CURSOR  FOR
		SELECT  (PAIS+SEXO+PROANI+NUMERO)
		FROM RegGen..ANIMALES
		WHERE (CODIGOIDENTIF) =@MAES_GEN
		AND NUMERO<'01868130'
		
		OPEN C2
		FETCH NEXT FROM C2 INTO @GEN
		IF @@FETCH_STATUS=0
		BEGIN
		INSERT INTO NUMGEN_DIB_MENOR_01868130
		VALUES (@MAES_TIT,@GEN,@MAES_GEN,@CONTROLADOR)

		END
		CLOSE C2
		DEALLOCATE C2
		FETCH NEXT FROM C1 INTO @MAES_TIT,@MAES_GEN,@CONTROLADOR		
	END --DEL WHILE

CLOSE C1
DEALLOCATE C1


