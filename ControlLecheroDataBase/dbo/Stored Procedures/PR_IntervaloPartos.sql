CREATE PROCEDURE [dbo].[PR_IntervaloPartos]
	(
		@Establo char(7),
		@Desde smalldatetime,
		@Hasta smalldatetime,
		@Tamano char(1)
	)
as
DECLARE @GEN CHAR(14),@NP  INT,@FPARTO SMALLDATETIME,@TOTALDIAS REAL,@FPARTO_ANTERIOR SMALLDATETIME,@NUM_VACAS REAL,@A INT
DECLARE @TAMANOESTABLO CHAR(1),@NUM_ESTABLOS REAL
IF @Establo=''--IF 1
BEGIN--1
	IF @TAMANO<>''--IF 2
		BEGIN--... PARA CALUCLAR EL TAMAÑO.......................
			DECLARE C1 CURSOR FOR
			SELECT ID,NP,FPARTO FROM PARTOS P,LECTURASCONTROL LC
			WHERE P.ESTABLO=LC.ESTABLO
			AND TAMANOESTABLO=@Tamano
			AND FPARTO>=@DESDE
			AND FPARTO<=@HASTA
			AND NP>1
			SET @TOTALDIAS=0;SET @NUM_VACAS=0
			OPEN  C1 
			FETCH NEXT FROM C1 INTO @GEN,@NP,@FPARTO
			WHILE (@@FETCH_STATUS=0)
			  BEGIN
				DECLARE C2 CURSOR FOR
				SELECT FPARTO FROM PARTOS
				WHERE 
				ID=@GEN
				AND  NP=@NP-1
				OPEN  C2 
				FETCH NEXT FROM C2 INTO @FPARTO_ANTERIOR 
				IF @@FETCH_STATUS=0
				BEGIN
					SET @TOTALDIAS=@TOTALDIAS+DATEDIFF(DAY,@FPARTO_ANTERIOR,@FPARTO)
					SET @NUM_VACAS=@NUM_VACAS+1
				END
				CLOSE C2
				DEALLOCATE C2
				FETCH NEXT FROM C1 INTO  @GEN,@NP,@FPARTO
			END--DEL WHILE.......................................
			CLOSE C1
			DEALLOCATE C1
		END--DEL @TAMANO, IF 2
		ELSE
		BEGIN--DEL 2
	-- TODOS
			DECLARE C1 CURSOR FOR
			SELECT ID,NP,FPARTO FROM PARTOS 
			WHERE FPARTO>=@DESDE
			AND FPARTO<=@HASTA
			AND NP>1
			SET @TOTALDIAS=0;SET @NUM_VACAS=0
			OPEN  C1 
			FETCH NEXT FROM C1 INTO @GEN,@NP,@FPARTO
			WHILE (@@FETCH_STATUS=0)
			  BEGIN
				DECLARE C2 CURSOR FOR
				SELECT FPARTO FROM PARTOS
				WHERE 
				ID=@GEN
				AND  NP=@NP-1
				OPEN  C2 
				FETCH NEXT FROM C2 INTO @FPARTO_ANTERIOR 
				IF @@FETCH_STATUS=0
				BEGIN
					SET @TOTALDIAS=@TOTALDIAS+DATEDIFF(DAY,@FPARTO_ANTERIOR,@FPARTO)
					SET @NUM_VACAS=@NUM_VACAS+1
				END
				CLOSE C2
				DEALLOCATE C2
				FETCH NEXT FROM C1 INTO  @GEN,@NP,@FPARTO
			END--DEL WHILE.......................................
			CLOSE C1
			DEALLOCATE C1
		END --DEL 2
END	
ELSE--DEL IF 1
BEGIN--1
	--PRINT 'ESTABLOOOO'
	DECLARE C1 CURSOR FOR
	SELECT ID,NP,FPARTO FROM PARTOS 
	WHERE ESTABLO=@ESTABLO
	AND FPARTO>=@DESDE
	AND FPARTO<=@HASTA
	AND NP>1
	SET @TOTALDIAS=0;SET @NUM_VACAS=0
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @GEN,@NP,@FPARTO
	WHILE (@@FETCH_STATUS=0)
	  BEGIN
		DECLARE C2 CURSOR FOR
		SELECT FPARTO FROM PARTOS
		WHERE 
		ESTABLO=@ESTABLO
		AND ID=@GEN
		AND  NP=@NP-1
		OPEN  C2 
		FETCH NEXT FROM C2 INTO @FPARTO_ANTERIOR 
		IF @@FETCH_STATUS=0
		BEGIN
			SET @TOTALDIAS=@TOTALDIAS+DATEDIFF(DAY,@FPARTO_ANTERIOR,@FPARTO)
			SET @NUM_VACAS=@NUM_VACAS+1
		END
		CLOSE C2
		DEALLOCATE C2
		FETCH NEXT FROM C1 INTO  @GEN,@NP,@FPARTO
	END--DEL WHILE.......................................
	CLOSE C1
	DEALLOCATE C1
END--1
IF @NUM_VACAS=0
BEGIN
	SELECT 0 as valor--/@NUM_VACAS AS INTERVALOPARTOS
END
ELSE
BEGIN
	SELECT @TOTALDIAS/@NUM_VACAS as valor--/@NUM_VACAS AS INTERVALOPARTOS
END
		
		
	
