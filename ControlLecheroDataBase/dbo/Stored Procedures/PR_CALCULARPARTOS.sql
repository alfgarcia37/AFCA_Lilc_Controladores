--ACTUALIZO LOS SEMENTALES DE LOS PARTOS
UPDATE PARTOS
SET VACA_GEN=ID
WHERE SUBSTRING(ID,4,1)='H'

UPDATE PARTOS
SET VACA_GEN=(PAIS+SEXO+PROANI+NUMERO)
FROM REGGEN..ANIMALES
WHERE ID=CODIGOIDENTIF
AND VACA_GEN IS  NULL

UPDATE PARTOS
SET TORO=NUPAD1
FROM REGGEN..ANIMALES
WHERE VACA_GEN=NUMAD1
AND FPARTO=cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4))

 --Actualizo LOS QUE NO TIENEN FBAJA Y LA CALCULO DE LACTACIONES FINALIZADAS
 


UPDATE PARTOS
SET PARTOS.FBAJA=FSECADO
FROM LACTACIONES
WHERE 
ID=RES AND
PARTOS.NP=LACTACIONES.NP 
AND PARTOS.FBAJA IS NULL
AND LACTACIONES.FINALIZADA='S' AND
LACTACIONES.FPARTO BETWEEN @datFDesde AND @datFHasta

/*........................CALCULO FBAJAANTERIOR....PARA SABER FSECADO ANTERIOR....*/
DECLARE @GEN CHAR(14),@NP  INT

declare C1 cursor for 
SELECT ID,NP FROM PARTOS
WHERE 
NP>1 AND
FPARTO BETWEEN @datFDesde AND @datFHasta

OPEN  C1 
FETCH NEXT FROM C1 INTO @GEN,@NP 
WHILE (@@FETCH_STATUS=0)
  BEGIN
	
			
	UPDATE PARTOS
	SET FBAJAANTERIOR=(SELECT FBAJA FROM PARTOS WHERE ID=@GEN AND NP=@NP-1)
	
	WHERE CURRENT OF C1
	FETCH NEXT FROM C1 INTO  @GEN,@NP

 END

CLOSE C1
DEALLOCATE C1