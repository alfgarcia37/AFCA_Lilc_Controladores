CREATE PROCEDURE [dbo].[PR_CALCULARPARTOS]

(@datFDesde smalldatetime, @datFHasta smalldatetime)
 AS
  /*Borro solamente los regs. de Partos que existen en Control*/
  /*De no hacerlo asi me cargaría históricos*/
--despues recalcular vel. ordeño

DELETE PARTOS where FPARTO BETWEEN @datFDesde AND @datFHasta

--DESPUES DE ESTE PROCEDIMIENTO...EJECUTAR: PR-RENUMERAINS Y PR_VINCULOINSEMINACIONPARTO

/*FROM PARTOS,VISTAPARTOS
WHERE VISTAPARTOS.GEN=ID AND
VISTAPARTOS.NP=PARTOS.NP*/
  /*Inserto Valores en Partos*/
INSERT INTO PARTOS ( ID,DET,NP,FPARTO,ESTABLO)
SELECT GEN,DET,NP,FP,ESTABLO FROM VISTAPARTOS
WHERE FP  BETWEEN @datFDesde AND @datFHasta
  /*Actualizo VELORD*/
UPDATE PARTOS
SET VELORD=RES_VELORD
FROM CONTROL
WHERE 
ESTABLO=RES_TIT AND
ID=RES_GEN AND
NP=RES_NP AND
RES_VELORD>='0' AND
RES_FP BETWEEN @datFDesde AND @datFHasta
 /*Actualizo FACP,RETPLACENTA,CONFORMACIONCRIA,TAMANOCRIA,SEXOTERNERO,CONTROLADOR*/
UPDATE PARTOS
SET DIFPARTO=RES_FACP,
RETPLACENTA=RES_PLACENTA,
CONFORMACIONCRIA=RES_CONFORMACION,
TAMANOCRIA=RES_TAM,
SEXOTERNERO=RES_SEXO,
NUMCONTROLADOR=CONTROLADOR
FROM CONTROL
WHERE 
ESTABLO=RES_TIT AND
ID=RES_GEN AND
NP=RES_NP AND
RES_FACP>='0' AND
RES_FP BETWEEN @datFDesde AND @datFHasta

 --Actualizo FBAJA Y CAUSA SECADO
UPDATE PARTOS
SET FBAJA=RES_FBA,CBAJA=RES_CBA
FROM CONTROL
WHERE 
--ESTABLO=RES_TIT AND
ID=RES_GEN AND
NP=RES_NP AND
RES_AB='B' AND
RES_FP BETWEEN @datFDesde AND @datFHasta





