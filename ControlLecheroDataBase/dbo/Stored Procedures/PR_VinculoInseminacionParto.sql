CREATE PROCEDURE PR_VinculoInseminacionParto
(@datDESDE smalldatetime,@datHASTA smalldatetime)
--ANTES DE EJECUTAR ESTE PROCEDIMIENTO, DEBO EJECUTAR EL DE RENUMERAR INSEMINACIONES
--ANTES DEBO EJECUTAR PR_INSEMINACION_CL_REG
	
AS
--TENGO QUE COGER TODAS LAS INSEMINACIONES SIN ASIGNAR (NP=0)
-- VEO SI HAY UN PARTO ENTRE 8 Y 10 MESES PARA LA FECHA DE INSEMINACION MAS ANTIGUA
-- SI LO HAY , ACTUALIZO LA TABLA DE PARTOS Y LA DE INSEMINACIONES
-- PARA INSEMINACIONES: ACTUALIZA NP,. PUEDE HABER:
-- FINS: MAYO 2007, FEBRERO 2007, NOVIEMBRE 2008, DICIEMBRE 2008. -> TODAS PERTENECEN AL PARTO
-- TENDRE QUE DAR UN CODIGO (P.EJ:99) PARA LAS QUE NO SEAN DEL PARTO (P.EJ LAS DE 2007)
	
DECLARE @ID CHAR(14),@FINS SMALLDATETIME,@IDP CHAR(14),@FPARTO SMALLDATETIME,@NP INT,@SEMENTAL CHAR(14),@TORO CHAR(14)
DECLARE @NINS INT


DECLARE C1 cursor LOCAL SCROLL OPTIMISTIC FOR
SELECT MAX(ID),MAX(NINS),MAX(FINSEMINACION) FROM INSEMINACIONES
WHERE FINSEMINACION BETWEEN @datDESDE  AND @datHASTA
AND NP=0
GROUP BY ID
--WHERE ESTABLO='J390097'
--AND ID='ES000602732887'

OPEN C1 
FETCH NEXT FROM C1 INTO @ID,@NINS,@FINS

WHILE (@@FETCH_STATUS=0)
BEGIN
	DECLARE C2 CURSOR LOCAL SCROLL OPTIMISTIC FOR
	SELECT  ID,NP FROM PARTOS
	WHERE ID=@ID
	AND DATEDIFF(MONTH,@FINS, FPARTO) BETWEEN 7 AND 10 -- 
	ORDER BY FPARTO ASC
	OPEN C2
	FETCH NEXT FROM C2 INTO @IDP,@NP
		/*PRINT @ID + '- '+ CONVERT(CHAR,@NP)+' '+CONVERT(CHAR,@NP)*/
	IF @@FETCH_STATUS=0  /* EXISTE PARTO PARA ESA INSEM*/
		BEGIN
			UPDATE INSEMINACIONES
			SET NP=@NP
	 		WHERE ID=@IDP
			AND NP=0
			--PRINT @ID + ' '+ CONVERT(CHAR,@NP)
			UPDATE PARTOS 
			SET NINS=@NINS,
			FINS=@FINS,
			TORO=SEMENTAL
			FROM INSEMINACIONES I,PARTOS P
			WHERE P.ID=@IDP
			AND P.NP=@NP
			AND P.NINS=@NINS
		END
	CLOSE C2
	DEALLOCATE C2
	FETCH NEXT FROM C1 INTO @ID,@NINS,@FINS
END
CLOSE C1
DEALLOCATE C1