
CREATE PROCEDURE PR_FPARTODUPLICADA AS

DECLARE @GEN CHAR(14),@PARTO INT,@FP SMALLDATETIME,@WGEN CHAR(14),@WPARTO INT,@WFP SMALLDATETIME,@C INT


DECLARE C1 CURSOR FOR 

	SELECT MAX(RES_GEN),MAX(RES_NP),MAX(RES_FP)
	FROM CONTROL
	WHERE RES_FP>'01/01/06'
	GROUP BY RES_GEN,RES_NP,RES_FP
	ORDER BY RES_GEN,RES_NP,RES_FP
	
		
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @GEN,@PARTO,@FP
	SET @WGEN=0
	SET @WPARTO=0
	SET @WFP=0
	
WHILE (@@FETCH_STATUS=0)
  BEGIN
	
	IF @WGEN=@GEN AND @WPARTO=@PARTO
	BEGIN
		SELECT @GEN,@PARTO
	END	
	
	SET @WGEN=@GEN
	SET @WPARTO=@PARTO
	SET @WFP=@FP

	FETCH NEXT FROM C1 INTO  @GEN,@PARTO,@FP
	--IF @GEN='DE000344028103' 
	--BEGIN
		--SET @C=1
	--END
 END

CLOSE C1
DEALLOCATE C1