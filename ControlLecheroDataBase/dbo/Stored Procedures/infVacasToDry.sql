





CREATE PROCEDURE [dbo].[infVacasToDry] 
(
	@Establo char(14)
	
	)
AS
IF @Establo<>''
BEGIN
	SELECT MAX(ID) AS ID,MAX(NP) AS NP, MAX(FPARTO) AS FPARTO
	 FROM PARTOS
	WHERE ESTABLO=@ESTABLO
	and DATEDIFF(MONTH,FPARTO,GETDATE())<10
	GROUP BY ID
END
ELSE
BEGIN
	SELECT MAX(ID) AS ID,MAX(NP) AS NP, MAX(FPARTO) AS FPARTO
	 FROM PARTOS
	WHERE  DATEDIFF(MONTH,FPARTO,GETDATE())<10
	GROUP BY ID
END





