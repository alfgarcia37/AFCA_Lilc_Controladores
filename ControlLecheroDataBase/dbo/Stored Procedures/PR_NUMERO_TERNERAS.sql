CREATE PROCEDURE PR_NUMERO_TERNERAS 

 (@ESTABLO char(7),
@DESDE SMALLDATETIME,@HASTA SMALLDATETIME ) 

AS

DECLARE @NUM_ESTABLOS INT,@TOTAL_VACAS REAL
DECLARE @NUM_VACAS REAL,@NUM_VACAS2 REAL,@NUM_VACAS3 REAL,@RES CHAR(14)

	SET @TOTAL_VACAS=0

	
	DECLARE C1 cursor for 
	SELECT ESTABLO
	FROM LECTURASFINALIZADAS
	WHERE 
	FPREVISTA BETWEEN @DESDE AND @HASTA
	AND NUMCONTROLER=5
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @ESTABLO
	WHILE (@@FETCH_STATUS=0)
	BEGIN
		DECLARE C2 cursor  FOR --CENSO ACTUAL
		SELECT COUNT(*) FROM REGGEN..ANIMALES 
		WHERE 
		GANPRO=@ESTABLO
		AND DATEDIFF(month, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), getdate())>=15
		AND NUMLAC=0 and AÑOBAJ=0
		AND  SEXO='H'
		AND DATEDIFF(month, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), getdate())<30
		OPEN C2
		FETCH NEXT FROM C2 INTO @NUM_VACAS
		CLOSE C2
		DEALLOCATE C2
	
		DECLARE C2 cursor  FOR
		SELECT COUNT(*)  FROM REGGEN..TRANSFERENCIAS T,REGGEN..ANIMALES A  --COMPRADOS EN ESA FECHA
		WHERE  CODCOM=@ESTABLO
		AND GANPRO=@ESTABLO
		AND  T.SEXO='H'
		AND AÑOTR>2006
		AND (T.PAIS+T.SEXO+T.PROANI+T.NUMERO)=(A.PAIS+A.SEXO+A.PROANI+A.NUMERO)
		AND DATEDIFF(month, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), @DESDE)>=15
		AND DATEDIFF(month, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), getdate())<30
		AND (CASE WHEN MESTR=0    THEN NULL 
		ELSE  (cast(DIATR as char(2)) + '/' + cast(MESTR as char(2)) + '/'+ cast(AÑOTR as char(4))) END) >@DESDE
		OPEN C2
		FETCH NEXT FROM C2 INTO @NUM_VACAS2
		CLOSE C2
		DEALLOCATE C2

		DECLARE C2 cursor  FOR
		SELECT  COUNT(*) FROM REGGEN..TRANSFERENCIAS T,REGGEN..ANIMALES A
		WHERE CODVEN=@ESTABLO
		AND GANPRO=@ESTABLO
		AND  T.SEXO='H'
		AND AÑOTR>2006
		AND (T.PAIS+T.SEXO+T.PROANI+T.NUMERO)=(A.PAIS+A.SEXO+A.PROANI+A.NUMERO)
		AND DATEDIFF(month, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), @DESDE)>=15
		AND DATEDIFF(month, cast(DIANA1 as char(2)) + '/' + cast(MESNA1 as char(2)) + '/'+ cast(AÑONA1 as char(4)), getdate())<30
		AND (CASE WHEN MESTR=0    THEN NULL 
		ELSE  (cast(DIATR as char(2)) + '/' + cast(MESTR as char(2)) + '/'+ cast(AÑOTR as char(4))) END) >@DESDE
		OPEN C2
		FETCH NEXT FROM C2 INTO @NUM_VACAS3
		CLOSE C2
		DEALLOCATE C2
		-- VALOR=(@NUM_VACAS-@NUM_VACAS2+@NUM_VACAS3)/@NUM_ESTABLOS
		FETCH NEXT FROM C1 INTO @ESTABLO
	END
	CLOSE C1
	DEALLOCATE C1