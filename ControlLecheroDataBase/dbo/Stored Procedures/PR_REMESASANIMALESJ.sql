CREATE PROCEDURE [dbo].[PR_REMESASANIMALESJ] 
	(@REMESA CHAR(10),@ESTABLO char(7),@DESDE SMALLDATETIME,@CETOSIS VARCHAR(10) ) 
AS
--SET @REMESA ='R60'
--SET @ESTABLO='J390029'
--SET @DESDE='30/06/2012'
DECLARE @WESTABLO AS CHAR(7)

--- BORRO TODO LO ANTERIOR
--DELETE FROM  TMP_PruebaAFCA
--- 

IF @ESTABLO='*'
BEGIN
	IF @CETOSIS='cetosis' 
	BEGIN
		DECLARE C1 CURSOR FOR 
		SELECT ESTABLO FROM LECTURASCONTROL WHERE FBAJA IS NULL
		AND CETOSIS='1'
		--and ESTABLO IN (SELECT res_tit FROM CONTROL WHERE res_fprev between '01/01/2014' AND '31/12/2014'
			--AND RES_TIT='J390097'
			--and res_ab='A'
			--and res_bhb>0.1
		--group by res_tit
		--having COUNT(DISTINCT RES_FPREV)>5)
	END
	ELSE
	BEGIN
		DECLARE C1 CURSOR FOR 
		SELECT ESTABLO FROM LECTURASCONTROL WHERE FBAJA IS NULL
		-- prueba
		--AND ESTABLO IN ('J391903','J390367')
		--
	END
END
ELSE
BEGIN
	DECLARE C1 CURSOR FOR 
	SELECT ESTABLO FROM LECTURASCONTROL WHERE FBAJA IS NULL
	AND ESTABLO=@ESTABLO
END
OPEN  C1

FETCH NEXT FROM C1 INTO @WESTABLO
WHILE (@@FETCH_STATUS=0)
BEGIN
	--SELECT @REMESA,@WEstablo,CODIGOIDENTIF,NOMBRE FROM REGGEN..ANIMALES
	-- 1. SOLO LOS QUE ENTRARON EN VACAS CON ANTERIORIDAD A FECHAMOVIMIENTO Y TENIAN>=24 MESES 
	INSERT INTO REMESASD (REMESA,ESTABLO,VACA,NOMBRE,FN)
	SELECT @REMESA,@WESTABLO,vaca,nombre,FN FROM TMP_PruebaAFCA
	WHERE ESTABLO=@WESTABLO
FETCH NEXT FROM C1 INTO @WESTABLO
END--DEL WHILE

CLOSE C1
DEALLOCATE C1
--borro las que tienen<24 meses
DELETE FROM REMESASD
WHERE REMESA=@REMESA
AND DATEDIFF(DAY,FN,@DESDE)<730

--ACTUALIZO DATOS BANCARIOS
UPDATE REMESASD
SET BANCO=G.BANCOCUOTA,
SUCURSAL=G.SUCURSALCUOTA,
DC=G.DCCUOTA,
CUENTA=G.CUENTACUOTA,
formapago=G.formapago
FROM REGGEN..GANADERIAS_MAESTRO G
WHERE ESTABLO=CODGAN	
AND remesa=@remesa

--ACTUALIZO ESTADO--pongo todos los de FP=0:banco como pasados al cobro
update remesasD
set estado='1'
where remesa=@remesa
--ACTUALIZO ESTADO--pongo todos los de FP=1:caja como devueltos(de momento pdtes.)
update remesasD
set estado='0'
where remesa=@remesa
and formapago='1'--caja

-- ACTUALIZO BANCOS NULL A 0000
UPDATE REMESASD
SET BANCO='0000',
SUCURSAL='0000',
DC='00',
CUENTA='0000000000'
WHERE  remesa=@remesa
AND BANCO IS NULL

