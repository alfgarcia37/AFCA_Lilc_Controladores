CREATE PROCEDURE [dbo].[PR_CENSO_MAESTRO_AFCA]
	@Establo char(7)
AS
/*
DECLARE @establo CHAR(14),@DESDE smalldatetime,@usuario varchar(50)
SET @ESTABLO='J390029'
--de vez en cuando ejecutar PR_Historico_Ganaderias
*/

IF @ESTABLO='*'
	BEGIN
		DECLARE C1 CURSOR FOR 
		SELECT ESTABLO FROM HISTORICOGANADERIAS WHERE FBAJA IS NULL
		order by establo
	END
ELSE
	BEGIN
		DECLARE C1 CURSOR FOR 
		SELECT ESTABLO FROM HISTORICOGANADERIAS WHERE FBAJA IS NULL
		AND ESTABLO=@ESTABLO
	END
OPEN  C1

FETCH NEXT FROM C1 INTO @ESTABLO
WHILE (@@FETCH_STATUS=0)
BEGIN
	UPDATE MAESTRO 
	SET MAES_FBAJACENSO= CONVERT(VARCHAR(10), GETDATE(), 103),
	MAES_ESTADO='0'
	WHERE MAES_TIT=@ESTABLO
	and MAES_ESTADO='B'
	and DATEDIFF(MONTH,MAES_FBA,GETDATE())>7
	AND MAES_GEN NOT IN (SELECT CODIGOIDENTIF
	from reggen..ANIMALES where GANPRO=@Establo)
	AND MAES_GEN NOT IN (SELECT (PAIS+SEXO+PROANI+NUMERO)
	from reggen..ANIMALES where GANPRO=@Establo)
FETCH NEXT FROM C1 INTO @ESTABLO
END--DEL WHILE


CLOSE C1
DEALLOCATE C1
