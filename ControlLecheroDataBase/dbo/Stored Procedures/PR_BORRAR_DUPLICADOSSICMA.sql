

CREATE PROCEDURE PR_BORRAR_DUPLICADOSSICMA  AS
	
DECLARE @ID CHAR(14),@WID CHAR(14),@CONTADOR INT,@FP smalldatetime,@WFP smalldatetime


DECLARE C1 CURSOR LOCAL SCROLL OPTIMISTIC FOR
SELECT ID,FPartoSicma
FROM PARTOSSICMA
GROUP BY ID,FPartoSicma
HAVING COUNT(*)>1
OPEN C1 
FETCH NEXT FROM C1 INTO @ID,@FP
WHILE (@@FETCH_STATUS=0)
BEGIN
	DECLARE C2 CURSOR LOCAL SCROLL 
	OPTIMISTIC 
	DYNAMIC
	FOR
	SELECT  ID,FPartoSicma FROM PARTOSSICMA
	WHERE ID=@ID
	AND FPartoSicma=@FP
	
	
	OPEN C2
	FETCH NEXT FROM C2 INTO @WID,@WFP
	/*PRINT CONVERT(CHAR,@@FETCH_STATUS) + ' '+@ID*/
	IF @@FETCH_STATUS=0  
		BEGIN
			DELETE PARTOSSICMA
			WHERE CURRENT OF C2
		END
	CLOSE C2
	DEALLOCATE C2
	FETCH NEXT FROM C1 INTO  @ID,@FP
END
CLOSE C1
DEALLOCATE C1