






CREATE PROCEDURE PR_InfAnualServiciosConcepcion 
 (@ESTABLO char(7),@DESDE SMALLDATETIME,@HASTA SMALLDATETIME)
AS


DECLARE @NUM_ESTABLOS INT,@TAMANOESTABLO CHAR(1)
DECLARE @NUM_VACAS REAL,@TOTAL_VACAS INT,@NUM_INSEMINACIONES REAL
DECLARE @NUM_PARTOS REAL


IF @ESTABLO<>' '
BEGIN
/*===================SERVICIOS POR CONCEPCION EN ESTABLO=======================*/
	DECLARE C1 CURSOR FOR 
	SELECT COUNT(INSEMINACIONES.ID)
	FROM PARTOS,INSEMINACIONES
	WHERE 
	PARTOS.ESTABLO=@ESTABLO
	AND FPARTO BETWEEN @DESDE AND @HASTA
	AND INSEMINACIONES.ID=PARTOS.ID
	AND INSEMINACIONES.NP=PARTOS.NP
	AND INSEMINACIONES.NP>0
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @NUM_INSEMINACIONES
	CLOSE C1
	DEALLOCATE C1
	
	DECLARE C1 CURSOR FOR 
	SELECT COUNT(PARTOS.ID)
	FROM PARTOS
	WHERE 
	PARTOS.ESTABLO=@ESTABLO
	AND FPARTO BETWEEN @DESDE AND @HASTA
	AND FINS IS NOT NULL
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @NUM_PARTOS
	CLOSE C1
	DEALLOCATE C1
	
		SELECT (@NUM_INSEMINACIONES/@NUM_PARTOS) AS SERVICIOSCONCEPCION
		
	
END
ELSE
BEGIN
	/*===================SERVICIOS POR CONCEPCION EN CANTABRIA=======================*/
	DECLARE C1 CURSOR FOR 
	SELECT COUNT(INSEMINACIONES.ID)
	FROM PARTOS,INSEMINACIONES,LECTURASCONTROL
	WHERE 
	PARTOS.ESTABLO=LECTURASCONTROL.ESTABLO
	AND LECTURASCONTROL.FBAJA IS  NULL
	AND TAMANOESTABLO IS NOT NULL
	AND FPARTO BETWEEN @DESDE AND @HASTA
	AND INSEMINACIONES.ID=PARTOS.ID
	AND INSEMINACIONES.NP=PARTOS.NP
	AND INSEMINACIONES.NP>0
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @NUM_INSEMINACIONES
	CLOSE C1
	DEALLOCATE C1
	
	DECLARE C1 CURSOR FOR 
	SELECT COUNT(PARTOS.ID)
	FROM PARTOS,LECTURASCONTROL
	WHERE 
	PARTOS.ESTABLO=LECTURASCONTROL.ESTABLO
	AND LECTURASCONTROL.FBAJA IS  NULL
	AND TAMANOESTABLO IS NOT NULL
	AND FPARTO BETWEEN @DESDE AND @HASTA
	AND FINS IS NOT NULL
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @NUM_PARTOS
	CLOSE C1
	DEALLOCATE C1
	
		UPDATE INFORMEANUAL SET VALOR=@NUM_INSEMINACIONES/@NUM_PARTOS
		WHERE GRUPO='CANTABRIA' 
		AND CONCEPTO='SERVICIOS POR CONCEPCION'
	
	
	/*===================SERVICIOS POR CONCEPCION EN TRAMOS=======================*/
	
	
	DECLARE C1 CURSOR FOR 
	SELECT TAMANOESTABLO,COUNT(DISTINCT MAES_TIT) FROM MAESTRO,LECTURASCONTROL
	WHERE 
	FBAJA IS  NULL
	AND TAMANOESTABLO IS NOT NULL
	AND MAES_TIT=ESTABLO
	GROUP BY TAMANOESTABLO
	
	OPEN  C1 
	FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	WHILE (@@FETCH_STATUS=0)
	BEGIN
		DECLARE C2 CURSOR FOR 
		SELECT COUNT(INSEMINACIONES.ID)
		FROM PARTOS,INSEMINACIONES,LECTURASCONTROL
		WHERE 
		PARTOS.ESTABLO=LECTURASCONTROL.ESTABLO
		AND LECTURASCONTROL.FBAJA IS  NULL
		AND TAMANOESTABLO IS NOT NULL
		AND FPARTO BETWEEN @DESDE AND @HASTA
		AND INSEMINACIONES.ID=PARTOS.ID
		AND INSEMINACIONES.NP=PARTOS.NP
		AND INSEMINACIONES.NP>0
		AND TAMANOESTABLO=@TAMANOESTABLO
		AND TAMANOESTABLO IS NOT NULL
		
		OPEN  C2 
		FETCH NEXT FROM C2 INTO @NUM_INSEMINACIONES
		CLOSE C2
		DEALLOCATE C2
	
		DECLARE C2 CURSOR FOR 
		SELECT COUNT(PARTOS.ID)
		FROM PARTOS,LECTURASCONTROL
		WHERE 
		PARTOS.ESTABLO=LECTURASCONTROL.ESTABLO
		AND LECTURASCONTROL.FBAJA IS  NULL
		AND TAMANOESTABLO=@TAMANOESTABLO
		AND TAMANOESTABLO IS NOT NULL
		AND FPARTO BETWEEN @DESDE AND @HASTA
		AND FINS IS NOT NULL
		
		OPEN  C2 
		FETCH NEXT FROM C2 INTO @NUM_PARTOS
		CLOSE C2
		DEALLOCATE C2
	
		UPDATE INFORMEANUAL SET VALOR=@NUM_INSEMINACIONES/@NUM_PARTOS
		WHERE GRUPO='TRAMO'  + CAST(@TAMANOESTABLO as char(1)) 
		AND CONCEPTO='SERVICIOS POR CONCEPCION'
	
		FETCH NEXT FROM C1 INTO @TAMANOESTABLO,@NUM_ESTABLOS
	END
	CLOSE C1
	DEALLOCATE C1
END






