






CREATE PROCEDURE DBO.infDaysOpen 
(
	@Establo char(7)
		)
AS
delete from View_MaxPartos

IF @Establo<>''
BEGIN
	Insert into View_MaxPartos(ID,NP,FPARTO) select max(id) as ID,max(NP) as NP,MAX(FPARTO) AS FPARTO
	from PARTOS where establo=@Establo
	group by ID
	
	select VIEW_MAXPARTOS.ID,FPARTO,DATEDIFF(DAY,FPARTO,GETDATE()) AS DIAS,NP
	FROM VIEW_MAXPARTOS
	WHERE
	not EXISTS
	(SELECT ID FROM INSEMINACIONES WHERE
	ESTABLO=@Establo AND ID=VIEW_MAXPARTOS.ID AND FDIAGNOSTICO IS NOT NULL)
	AND DATEDIFF(DAY,FPARTO,GETDATE())<300
END
ELSE
BEGIN
	Insert into View_MaxPartos(ID,NP,FPARTO) select max(id) as ID,max(NP) as NP,MAX(FPARTO) AS FPARTO
	from PARTOS 
	group by ID
	
	select VIEW_MAXPARTOS.ID,FPARTO,DATEDIFF(DAY,FPARTO,GETDATE()) AS DIAS,NP
	FROM VIEW_MAXPARTOS
	WHERE
	not EXISTS
	(SELECT ID FROM INSEMINACIONES WHERE
	ID=VIEW_MAXPARTOS.ID AND FDIAGNOSTICO IS NOT NULL)
	AND DATEDIFF(DAY,FPARTO,GETDATE())<300
END





