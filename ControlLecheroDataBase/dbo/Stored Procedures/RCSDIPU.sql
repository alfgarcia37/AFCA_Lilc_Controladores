CREATE PROCEDURE RCSDIPU AS
DECLARE @RCS FLOAT, @TOT FLOAT, @CONT SMALLINT
declare C1 cursor for 
SELECT rcs FROM lactaciones
where fsecado between '01/01/07' and '01/01/07'
and finalizada='S'
SET @TOT=1;SET @CONT=0
OPEN  C1 
FETCH NEXT FROM C1 INTO @RCS
WHILE (@@FETCH_STATUS=0)
  BEGIN
	SET @CONT=@CONT +1 
	--SET @TOT=@TOT* (CAST(@RCS AS FLOAT))
	SET @TOT=@TOT* (CAST(@RCS AS FLOAT))
	--SET @TOT=@TOT*100
	FETCH NEXT FROM C1 INTO @RCS
  END
--SET @TOT=POWER( @TOT ,(1/@CONT))
CLOSE C1
DEALLOCATE C1
SELECT  @TOT